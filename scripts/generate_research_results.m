    fullfile( ...
        data_dir, ...
        'data_monthly.mat');

daily_mat = ...
    fullfile( ...
        data_dir, ...
        'data_daily.mat');

ff_daily_csv = ...
    fullfile( ...
        data_dir, ...
        'F-F_Research_Data_Factors_daily.csv');

ff_monthly_csv = ...
    fullfile( ...
        data_dir, ...
        'F-F_Research_Data_Factors.csv');


assert( ...
    isfolder(src_dir), ...
    'GenerateResearch:MissingSourceDirectory', ...
    'Source directory not found: %s', ...
    src_dir);


required_input_files = ...
    string( ...
        { ...
            monthly_mat, ...
            daily_mat, ...
            ff_daily_csv, ...
            ff_monthly_csv});


missing_input_files = ...
    required_input_files(~isfile(required_input_files));


if ~isempty(missing_input_files)

    error( ...
        'GenerateResearch:MissingInputFiles', ...
        ['Missing required data files in data/:\n%s\n' ...
         'Expected files: data_monthly.mat, data_daily.mat, ' ...
         'F-F_Research_Data_Factors_daily.csv, F-F_Research_Data_Factors.csv\n' ...
         'The equity .mat files are not distributed with this repository.\n' ...
         'Fama-French factor files: https://mba.tuck.dartmouth.edu/pages/faculty/ken.french/data_library.html'], ...
        strjoin(cellstr(missing_input_files), newline));

end


addpath(src_dir);


owned_files = [ ...
    "core_performance.csv"; ...
    "r0_data_diagnostic.csv"; ...
    "r1_signal_comparison.csv"; ...
    "r2_bootstrap_summary.csv"; ...
    "r3_size_sensitivity.csv"; ...
    "r4_subperiod_robustness.csv"; ...
    "r4_period_differences.csv"; ...
    "r5_calibration_robustness.csv"; ...
    "r5_summary.csv"; ...
    "capm_levels.csv"; ...
    "capm_differences.csv"; ...
    "capm_channel.csv"; ...
    "capm_meta.csv"];


% Results are written to a staging folder and replace research_results
% only after all 13 files have been written and checked. A failed run
% leaves the previous results untouched, and the leftovers of a run that
% stopped abruptly during an earlier replacement are repaired first.

recover_output_directory( ...
    output_dir, ...
    owned_files);

staging_dir = ...
    [output_dir '.staging'];

if isfolder(staging_dir)

    rmdir(staging_dir, 's');

end


