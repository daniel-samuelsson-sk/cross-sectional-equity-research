    comparison = ...
        comparisons(k);


    row_sharpe = ...
        r2_comparison == comparison & ...
        r2_metric == "sharpe";


    row_volatility = ...
        r2_comparison == comparison & ...
        r2_metric == "annualized_volatility";


    row_cagr = ...
        r2_comparison == comparison & ...
        r2_metric == "cagr";


    assert( ...
        sum(row_sharpe) == 1 && ...
        sum(row_volatility) == 1 && ...
        sum(row_cagr) == 1, ...
        'GenerateResearch:R2SummaryShape', ...
        'Unexpected R2 rows for %s.', ...
        comparison);


    r2_export{k,2:4} = [ ...
        r2.summary.observed_difference(row_sharpe), ...
        r2.summary.ci_lower(row_sharpe), ...
        r2.summary.ci_upper(row_sharpe)];


