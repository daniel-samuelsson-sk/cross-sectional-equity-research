%% GENERATE_RESEARCH_RESULTS
% Generate aggregate research result tables.
%
% Source data remain outside the generated research_results package.
% The exported CSV files contain aggregate research outputs only.


%% Paths and owned outputs

script_dir = ...
    fileparts( ...
        mfilename('fullpath'));

project_root = ...
    fileparts(script_dir);

src_dir = ...
    fullfile( ...
        project_root, ...
        'src');

data_dir = ...
    fullfile( ...
        project_root, ...
        'data');

output_dir = ...
    fullfile( ...
        project_root, ...
        'research_results');


