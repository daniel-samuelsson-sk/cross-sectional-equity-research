function write_table_17g( ...
    T, ...
    file_path)
%WRITE_TABLE_17G Write CSV data with exact numeric round-trip checking.
%
% Numeric values use the shortest representation among %.15g, %.16g and
% %.17g that parses back to the exact same double.


export_table = ...
    table();


for k = 1:width(T)

    variable_name = ...
        T.Properties.VariableNames{k};


    value = ...
        T.(variable_name);


    if isnumeric(value)

        export_table.(variable_name) = ...
            format_numeric_roundtrip( ...
                double(value));


    elseif islogical(value)

        text_value = ...
            repmat( ...
                "false", ...
                size(value));


        text_value(value) = ...
            "true";


        export_table.(variable_name) = ...
            text_value;


    elseif isdatetime(value)

        export_table.(variable_name) = ...
            string( ...
                value, ...
                'yyyy-MM-dd');


    elseif isstring(value)

        export_table.(variable_name) = ...
            value;


    elseif iscategorical(value) || ...
            iscellstr(value) || ...
            ischar(value)

        export_table.(variable_name) = ...
            string(value);


    else

        error( ...
            'GenerateResearch:UnsupportedCSVType', ...
            'Unsupported type in %s / %s.', ...
            file_path, ...
            variable_name);

    end

end


writetable( ...
    export_table, ...
    file_path, ...
    'QuoteStrings', ...
    'minimal', ...
    'Encoding', ...
    'UTF-8');


options = ...
    detectImportOptions( ...
        file_path, ...
        'TextType', ...
        'string', ...
        'Encoding', ...
        'UTF-8');


options.VariableNamingRule = ...
    'preserve';


options = ...
    setvartype( ...
        options, ...
        options.VariableNames, ...
        'string');


round_trip = ...
    readtable( ...
        file_path, ...
        options);


assert( ...
    isequal( ...
        string(round_trip.Properties.VariableNames), ...
        string(T.Properties.VariableNames)) && ...
    height(round_trip) == height(T), ...
    'GenerateResearch:RoundTripShape', ...
    'CSV shape changed on round-trip: %s', ...
    file_path);


for k = 1:width(T)

    variable_name = ...
        T.Properties.VariableNames{k};


    original_value = ...
        T.(variable_name);


    round_trip_text = ...
        string( ...
            round_trip.(variable_name));


    if isnumeric(original_value)

        assert( ...
            isequaln( ...
                str2double(round_trip_text), ...
                double(original_value)), ...
            'GenerateResearch:NumericRoundTripFailure', ...
            'Numeric round-trip failed: %s / %s', ...
            file_path, ...
            variable_name);


    elseif islogical(original_value)

        assert( ...
            all( ...
                round_trip_text == "true" | ...
                round_trip_text == "false") && ...
            isequal( ...
                round_trip_text == "true", ...
                original_value), ...
            'GenerateResearch:LogicalRoundTripFailure', ...
            'Logical round-trip failed: %s / %s', ...
            file_path, ...
            variable_name);


    elseif isdatetime(original_value)

        assert( ...
            isequal( ...
                round_trip_text, ...
                string( ...
                    original_value, ...
                    'yyyy-MM-dd')), ...
            'GenerateResearch:DateRoundTripFailure', ...
            'Date round-trip failed: %s / %s', ...
            file_path, ...
            variable_name);


    else

        assert( ...
            isequal( ...
                round_trip_text, ...
                string(original_value)), ...
            'GenerateResearch:TextRoundTripFailure', ...
            'Text round-trip failed: %s / %s', ...
            file_path, ...
            variable_name);

    end

end

end


function text_value = format_numeric_roundtrip(value)
%FORMAT_NUMERIC_ROUNDTRIP Shortest exact %.15g/%.16g/%.17g representation.

value = ...
    double(value);


text_value = ...
    strings( ...
        size(value));


formats = { ...
    '%.15g', ...
    '%.16g', ...
    '%.17g'};


for k = 1:numel(value)

    candidates = ...
        strings( ...
            numel(formats), ...
            1);


    exact = ...
        false( ...
            numel(formats), ...
            1);


    for j = 1:numel(formats)

        candidates(j) = ...
            string( ...
                sprintf( ...
                    formats{j}, ...
                    value(k)));


        exact(j) = ...
            isequaln( ...
                str2double( ...
                    candidates(j)), ...
                value(k));

    end


    assert( ...
        any(exact), ...
        'GenerateResearch:NoExactNumericFormat', ...
        'Could not round-trip numeric value %.17g.', ...
        value(k));


    candidate_length = ...
        inf( ...
            numel(formats), ...
            1);


    candidate_length(exact) = ...
        double( ...
            strlength( ...
                candidates(exact)));


    [~,best_index] = ...
        min(candidate_length);


    text_value(k) = ...
        candidates(best_index);

end

