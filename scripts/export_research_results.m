function assert_close(actual,expected,tolerance,label)
%ASSERT_CLOSE Require two scalar research statistics to agree.

assert( ...
    isscalar(actual) && ...
    isscalar(expected) && ...
    isfinite(actual) && ...
    isfinite(expected), ...
    'ExportResearchResults:InvalidMetricComparison', ...
    'Metric comparison for %s contains a non-finite value.', ...
    label);

difference = ...
    abs(actual - expected);

assert( ...
    difference <= tolerance, ...
    'ExportResearchResults:MetricMismatch', ...
    ['Independent reconstruction disagrees with headline metric for %s. ' ...
     'Actual difference: %.12g.'], ...
    label, ...
    difference);

end


function disable_axes_toolbars(fig)
%DISABLE_AXES_TOOLBARS Remove interactive axes controls before export.

axes_handles = ...
    findall( ...
        fig, ...
        'Type', ...
        'axes');

for k = 1:numel(axes_handles)

    ax = ...
        axes_handles(k);

    try
        axtoolbar(ax,'none');
    catch
    end

    if isprop(ax,'Toolbar') && ...
       ~isempty(ax.Toolbar)

        ax.Toolbar.Visible = ...
            'off';

    end

end

