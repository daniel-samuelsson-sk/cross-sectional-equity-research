%% Reconstruct OOS portfolio return series
%
% Returns are reconstructed from target weights and realized monthly stock
% returns. A missing return on any held asset invalidates the month; weights
% are not renormalized around missing observations.

fprintf('Reconstructing monthly portfolio returns...\n');


portfolio_month = ...
    research.evaluation.portfolios.portfolio_month(:);


[month_found,monthly_row] = ...
    ismember( ...
        portfolio_month, ...
        data.monthly.dates(:));


assert( ...
    all(month_found), ...
    'ExportResearchResults:MissingMonthlyDates', ...
    'At least one evaluation portfolio month is absent from monthly data.');


asset_monthly_returns = ...
    data.monthly.returns(monthly_row,:);

monthly_rf = ...
    data.monthly.rf(monthly_row);

monthly_rf = ...
    monthly_rf(:);


n_eval_months = ...
    numel(portfolio_month);


portfolio_returns = ...
    NaN( ...
        n_eval_months, ...
        n_strategies);


for k = 1:n_strategies

    key = ...
        strategy_fields{k};

    weights = ...
        research.evaluation.portfolios.weights.(key);

    valid_portfolio = ...
        research.evaluation.portfolios.valid.(key);


    assert( ...
        size(weights,1) == n_eval_months, ...
        'ExportResearchResults:WeightDateMismatch', ...
        'Weight row count does not match evaluation months for %s.', ...
        key);


    for t = 1:n_eval_months

        if ~valid_portfolio(t)
            continue
        end


        w = ...
            weights(t,:);

        held = ...
            w > 0;


        if ~any(held)
            continue
        end


        realized = ...
            asset_monthly_returns(t,:);


        if any(~isfinite(realized(held)))
            continue
        end


        portfolio_returns(t,k) = ...
            sum( ...
                w(held) .* ...
                realized(held));

    end

end


assert( ...
    all(isfinite(portfolio_returns),'all'), ...
    'ExportResearchResults:IncompleteReconstructedReturns', ...
    ['At least one OOS portfolio return is incomplete. ' ...
     'No result is exported until the discrepancy is resolved.']);


%% Verify reconstructed returns against performance summaries
%
% Sharpe is verified using the standard deviation of monthly excess returns,
% matching evaluate_performance().

fprintf('Verifying reconstructed returns against headline metrics...\n');


metric_tolerance = ...
    1e-8;


for k = 1:n_strategies

    key = ...
        strategy_fields{k};

    s = ...
        research.evaluation.summary.(key);

    r = ...
        portfolio_returns(:,k);


    ann_return_check = ...
        12 * mean(r);

    ann_vol_check = ...
        sqrt(12) * std(r,0);

    excess_return_check = ...
        r - monthly_rf;

    ann_excess_check = ...
        12 * mean(excess_return_check);

    excess_vol_check = ...
        std(excess_return_check,0);

    assert( ...
        isfinite(excess_vol_check) && ...
        excess_vol_check > 0, ...
        'ExportResearchResults:InvalidExcessVolatility', ...
        'Excess-return volatility is invalid for %s.', ...
        key);

    sharpe_check = ...
        sqrt(12) * ...
        mean(excess_return_check) / ...
        excess_vol_check;

    gross_wealth = ...
        [ ...
            1; ...
            cumprod(1 + r)];

    cagr_check = ...
        gross_wealth(end)^(12 / numel(r)) - 1;

    running_peak = ...
        cummax(gross_wealth);

    drawdown_check = ...
        gross_wealth ./ ...
        running_peak - 1;

    max_drawdown_check = ...
        -min(drawdown_check);


    assert_close( ...
        ann_return_check, ...
        s.annualized_total_return, ...
        metric_tolerance, ...
        sprintf('%s annualized return',key));

    assert_close( ...
        ann_vol_check, ...
        s.annualized_volatility, ...
        metric_tolerance, ...
        sprintf('%s annualized volatility',key));

    assert_close( ...
        ann_excess_check, ...
        s.annualized_excess_return, ...
        metric_tolerance, ...
        sprintf('%s annualized excess return',key));

    assert_close( ...
        sharpe_check, ...
        s.sharpe, ...
        metric_tolerance, ...
        sprintf('%s Sharpe ratio',key));

    assert_close( ...
        cagr_check, ...
        s.cagr, ...
        metric_tolerance, ...
        sprintf('%s CAGR',key));

    assert_close( ...
        max_drawdown_check, ...
        s.maximum_drawdown, ...
        metric_tolerance, ...
        sprintf('%s maximum drawdown',key));

end


