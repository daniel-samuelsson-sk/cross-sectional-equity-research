%% PAIRED BOOTSTRAP INTERVALS — REPRODUCIBLE CSV-ONLY FIGURE
% Requires MATLAB R2025b. No equity data or additional toolboxes are needed.
% Sources: research_results/r2_bootstrap_summary.csv,
% research_results/core_performance.csv,
% research_results/r1_signal_comparison.csv.
% Output: results/figures/bootstrap_intervals.png.
% The four plotted contrasts concern incremental portfolio screens.
% The benchmark comparison remains available in the source CSV.

script_path = mfilename('fullpath');
assert(~isempty(script_path), ...
    'BootstrapPlot:ScriptLocation', ...
    'Save this script as scripts/plot_bootstrap_intervals.m before running.');
root_dir = fileparts(fileparts(script_path));
source_csv = fullfile(root_dir, 'research_results', 'r2_bootstrap_summary.csv');
output_dir = fullfile(root_dir, 'results', 'figures');
output_png = fullfile(output_dir, 'bootstrap_intervals.png');

assert(isfile(source_csv), 'BootstrapPlot:MissingSource', ...
    'Required CSV not found: %s', source_csv);

T = readtable(source_csv, 'TextType', 'string');
required_columns = [ ...
    "comparison", ...
    "delta_sharpe", ...
    "delta_sharpe_ci_lower", ...
    "delta_sharpe_ci_upper", ...
    "delta_annualized_volatility_decimal", ...
    "delta_annualized_volatility_ci_lower_decimal", ...
    "delta_annualized_volatility_ci_upper_decimal", ...
    "bootstrap_replicates", ...
    "mean_block_length_months", ...
    "seed"];

assert(all(ismember(required_columns, string(T.Properties.VariableNames))), ...
    'BootstrapPlot:MissingColumns', ...
    'The bootstrap CSV is missing one or more required columns.');

expected_comparisons = [ ...
    "MOM+DD - MOM"
    "FINAL - MOM+DD"
    "MOM+DD - EW"
    "MOM+sigma - MOM+DD"
    "MOM+DD - DD-only"];

assert(height(T) == 5 && ...
    numel(unique(T.comparison)) == 5 && ...
    isequal(sort(T.comparison), sort(expected_comparisons)), ...
    'BootstrapPlot:UnexpectedComparisons', ...
    'The source CSV must contain exactly the five expected comparisons.');

assert(all(T.bootstrap_replicates == 10000) && ...
    all(T.mean_block_length_months == 6) && ...
    all(T.seed == 1), ...
    'BootstrapPlot:UnexpectedBootstrapDesign', ...
    'Expected paired stationary bootstrap with B=10000, L=6, seed=1.');

% The selected rows address the incremental screening question.
% MOM+DD - EW is available in the CSV and discussed separately.
selected = [ ...
    "MOM+DD - MOM"
    "FINAL - MOM+DD"
    "MOM+sigma - MOM+DD"
    "MOM+DD - DD-only"];


[found, row_index] = ismember(selected, T.comparison);
assert(all(found), 'BootstrapPlot:MissingComparison', ...
    'A requested screening contrast is absent.');

vol_point = 100 * T.delta_annualized_volatility_decimal(row_index);
vol_lower = 100 * T.delta_annualized_volatility_ci_lower_decimal(row_index);
vol_upper = 100 * T.delta_annualized_volatility_ci_upper_decimal(row_index);
sharpe_point = T.delta_sharpe(row_index);
sharpe_lower = T.delta_sharpe_ci_lower(row_index);
sharpe_upper = T.delta_sharpe_ci_upper(row_index);

assert(all(isfinite([vol_point; vol_lower; vol_upper; ...
                     sharpe_point; sharpe_lower; sharpe_upper])) && ...
    all(vol_lower <= vol_point & vol_point <= vol_upper) && ...
    all(sharpe_lower <= sharpe_point & sharpe_point <= sharpe_upper), ...
    'BootstrapPlot:InvalidIntervals', ...
    'Nonfinite, reversed or inconsistent intervals in bootstrap CSV.');

%% Observed portfolio levels for explanatory labels

core_csv = fullfile(root_dir, 'research_results', ...
    'core_performance.csv');

signals_csv = fullfile(root_dir, 'research_results', ...
    'r1_signal_comparison.csv');

assert(isfile(core_csv) && isfile(signals_csv), ...
    'BootstrapPlot:MissingLevelTables', ...
    'Required portfolio-level CSV files are missing.');

core = readtable(core_csv, 'TextType', 'string');
signals = readtable(signals_csv, 'TextType', 'string');

core_required = ["portfolio", ...
    "annualized_volatility_decimal", "sharpe"];

signals_required = ["variant", ...
    "annualized_volatility_decimal", "sharpe"];

assert(all(ismember(core_required, ...
    string(core.Properties.VariableNames))) && ...
    all(ismember(signals_required, ...
    string(signals.Properties.VariableNames))), ...
    'BootstrapPlot:MissingLevelColumns', ...
    'Required performance columns are missing.');

[core_found, core_dd] = ismember("MOM+DD", core.portfolio);
[signal_found, signal_dd] = ismember("MOM+DD", signals.variant);

assert(core_found && signal_found, ...
    'BootstrapPlot:MissingDuplicateControl', ...
    'MOM+DD is required in both performance tables.');

assert( ...
    abs(core.annualized_volatility_decimal(core_dd) - ...
        signals.annualized_volatility_decimal(signal_dd)) < 1e-12 && ...
    abs(core.sharpe(core_dd) - ...
        signals.sharpe(signal_dd)) < 1e-12, ...
    'BootstrapPlot:DuplicateLevelMismatch', ...
    'MOM+DD values disagree between performance tables.');

signals_unique = signals(signals.variant ~= "MOM+DD", :);

level_names = [core.portfolio; signals_unique.variant];
level_vol = [core.annualized_volatility_decimal; ...
    signals_unique.annualized_volatility_decimal];
level_sharpe = [core.sharpe; signals_unique.sharpe];

assert(numel(unique(level_names)) == numel(level_names) && ...
    all(isfinite(level_vol)) && all(isfinite(level_sharpe)), ...
    'BootstrapPlot:InvalidLevelLookup', ...
    'Portfolio lookup keys must be unique and values finite.');

before_names = [ ...
    "MOM"
    "MOM+DD"
    "MOM+DD"
    "DD-only"];

after_names = [ ...
    "MOM+DD"
    "FINAL"
    "MOM+sigma"
    "MOM+DD"];

[found_before, idx_before] = ismember(before_names, level_names);
[found_after, idx_after] = ismember(after_names, level_names);

assert(all(found_before) && all(found_after), ...
    'BootstrapPlot:MissingPortfolioLevels', ...
    'Required portfolio performance levels were not found.');

vol_before = 100 * level_vol(idx_before);
vol_after = 100 * level_vol(idx_after);
sharpe_before = level_sharpe(idx_before);
sharpe_after = level_sharpe(idx_after);

assert( ...
    all(abs((vol_after - vol_before) - vol_point) < 1e-8) && ...
    all(abs((sharpe_after - sharpe_before) - sharpe_point) < 1e-8), ...
    'BootstrapPlot:LevelDifferenceMismatch', ...
    'Observed portfolio levels disagree with R2 differences.');

before_display = replace(before_names, ...
    "MOM+sigma", "MOM+σ");

after_display = replace(after_names, ...
    "MOM+sigma", "MOM+σ");

if ~isfolder(output_dir)
    [ok, message] = mkdir(output_dir);
    assert(ok, 'BootstrapPlot:CreateOutputDirectory', '%s', message);
end

fig = figure('Color', 'w', ...
    'Position', [100 100 1400 950], ...
    'ToolBar', 'none');
tl = tiledlayout(fig, 2, 1, ...
    'Padding', 'loose', 'TileSpacing', 'compact');

% Exact source identifiers are retained above; these are display labels only.
experiment_names = { ...
    'Add downside-risk screen'
    'Add idiosyncratic-skewness screen'
    'Replace downside-risk screen with total-volatility screen'
    'Add momentum threshold to downside-risk screen'};

labels_vol = cell(4,1);
labels_sharpe = cell(4,1);

for j = 1:4
    labels_vol{j} = sprintf( ...
        '%s\\newline\\color[rgb]{0.40,0.40,0.40}%s → %s (%.2f%% → %.2f%%)', ...
        experiment_names{j}, ...
        char(before_display(j)), char(after_display(j)), ...
        vol_before(j), vol_after(j));

    labels_sharpe{j} = sprintf( ...
        '%s\\newline\\color[rgb]{0.40,0.40,0.40}%s → %s (%.3f → %.3f)', ...
        experiment_names{j}, ...
        char(before_display(j)), char(after_display(j)), ...
        sharpe_before(j), sharpe_after(j));
end


label_color = [0.16 0.28 0.43];

ax1 = nexttile(tl);
plot_intervals(ax1, vol_point, vol_lower, vol_upper, ...
    labels_vol, label_color);
xlabel(ax1, 'Difference in annualized volatility (percentage points)', ...
    'FontSize', 12);
title(ax1, 'A   Annualized volatility', 'FontWeight', 'bold');
xtickformat(ax1, '%.1f');

ax2 = nexttile(tl);
plot_intervals(ax2, sharpe_point, sharpe_lower, sharpe_upper, ...
    labels_sharpe, label_color);
xlabel(ax2, 'Difference in annualized Sharpe ratio', ...
    'FontSize', 12);
title(ax2, 'B   Annualized Sharpe ratio', 'FontWeight', 'bold');
xtickformat(ax2, '%.2f');

title(tl, 'What changes when equity screens are added or replaced?', ...
    'FontWeight', 'bold', 'FontSize', 15);

xlabel(tl, { ...
        'Out-of-sample 1990–2023 | difference = after minus before', ...
        'MOM = momentum · DD = downside deviation · σ = total volatility · FINAL adds idiosyncratic skewness', ...
        'DD-only = downside-risk screen without momentum cutoff (full momentum history still required)', ...
        'Paired stationary bootstrap | 10,000 resamples | mean block length 6 months | interval width depends partly on return co-movement', ...
        '95% percentile intervals | before transaction costs | not adjusted for multiple comparisons'}, ...
    'FontSize', 11, 'Color', [0.30 0.30 0.30], ...
    'Interpreter', 'none');


drawnow;
exportgraphics(fig, output_png, 'Resolution', 200, ...
    'Padding', 55, 'Units', 'pixels');
close(fig);

assert(isfile(output_png), 'BootstrapPlot:MissingOutput', ...
    'The bootstrap figure was not exported.');
fprintf('Bootstrap intervals exported: %s\n', output_png);
fprintf('Four screening contrasts plotted; benchmark comparison retained in CSV.\n');

%% Local plotting function
function plot_intervals(ax, point, lower, upper, labels, point_color)
    n = numel(point);
    y = (1:n)';
    hold(ax, 'on');

    all_x = [lower(:); upper(:); 0];
    left_edge = min(all_x);
    right_edge = max(all_x);
    margin = max(0.10 * (right_edge - left_edge), 0.025);
    xlim(ax, [left_edge - margin, right_edge + margin]);
    ylim(ax, [0.45, n + 0.55]);

    xline(ax, 0, '--', 'Color', [0.37 0.37 0.37], ...
        'LineWidth', 1.1, 'HandleVisibility', 'off');

    cap_half_height = 0.11;
    for j = 1:n
        plot(ax, [lower(j), upper(j)], [y(j), y(j)], ...
            '-', 'Color', point_color, 'LineWidth', 2.2);
        plot(ax, [lower(j), lower(j)], ...
            [y(j)-cap_half_height, y(j)+cap_half_height], ...
            '-', 'Color', point_color, 'LineWidth', 1.8);
        plot(ax, [upper(j), upper(j)], ...
            [y(j)-cap_half_height, y(j)+cap_half_height], ...
            '-', 'Color', point_color, 'LineWidth', 1.8);
        plot(ax, point(j), y(j), 'o', ...
            'MarkerSize', 7.5, 'MarkerFaceColor', point_color, ...
            'MarkerEdgeColor', 'w', 'LineWidth', 1.1);
    end

    set(ax, 'YTick', y, 'YTickLabel', labels, ...
        'YDir', 'reverse', 'TickLabelInterpreter', 'tex', ...
        'FontSize', 12, 'Box', 'off', ...
        'Layer', 'bottom');
    actual_labels = string(ax.YTickLabel);
    expected_labels = string(labels);

    assert( ...
        numel(actual_labels) == n && ...
        isequal(actual_labels(:), expected_labels(:)), ...
        'BootstrapPlot:TickLabelMismatch', ...
        'MATLAB changed the number or content of tick labels.');

    assert( ...
        all(count(actual_labels, "\newline") == 1) && ...
        isequal(ax.YTick(:), y(:)), ...
        'BootstrapPlot:InvalidTickLabelLayout', ...
        'Expected one TeX line break per tick label and four matching tick positions.');

    grid(ax, 'on');
    ax.YGrid = 'off';
    ax.GridAlpha = 0.12;
    ax.XColor = [0.25 0.25 0.25];
    ax.YColor = [0.25 0.25 0.25];
end
