function downside = compute_downside_deviation(data, calendar, cfg)
%COMPUTE_DOWNSIDE_DEVIATION Compute daily downside-deviation signals.
%
% For portfolio month t, downside deviation is estimated from daily
% stock excess returns over the calendar months t-12 through t-2:
%
%   excess_return = stock_return - risk_free_return
%
%   DD = sqrt(mean(min(excess_return, 0).^2))
%
% A signal is valid only when the asset has at least the configured
% fraction of daily observations in the signal window.
%
% Timing is supplied entirely by build_research_calendar(). This function
% must not independently infer t-12, t-2, or formation dates.

validate_research_data(data);


%% Validate configuration

assert( ...
    isfield(cfg, 'signals') && ...
    isfield(cfg.signals, 'downside'), ...
    'DownsideDeviation:MissingConfiguration', ...
    'cfg.signals.downside is required.');

dd_cfg = cfg.signals.downside;

required_cfg = { ...
    'start_lag_months', ...
    'end_lag_months', ...
    'min_coverage'};

for k = 1:numel(required_cfg)

    assert(isfield(dd_cfg, required_cfg{k}), ...
        'DownsideDeviation:MissingConfiguration', ...
        'Missing downside configuration field: %s', ...
        required_cfg{k});

end

start_lag = dd_cfg.start_lag_months;
end_lag   = dd_cfg.end_lag_months;

assert( ...
    isscalar(start_lag) && ...
    isscalar(end_lag) && ...
    isfinite(start_lag) && ...
    isfinite(end_lag) && ...
    start_lag == floor(start_lag) && ...
    end_lag == floor(end_lag) && ...
    start_lag > end_lag && ...
    end_lag >= 1, ...
    'DownsideDeviation:InvalidLags', ...
    'Downside-deviation lags must satisfy start_lag > end_lag >= 1.');

assert( ...
    isscalar(dd_cfg.min_coverage) && ...
    isfinite(dd_cfg.min_coverage) && ...
    dd_cfg.min_coverage > 0 && ...
    dd_cfg.min_coverage <= 1, ...
    'DownsideDeviation:InvalidCoverage', ...
    'min_coverage must lie in the interval (0,1].');


%% Validate calendar interface

required_calendar = { ...
    'portfolio_month', ...
    'daily_window_start', ...
    'daily_window_end'};

for k = 1:numel(required_calendar)

    assert( ...
        ismember( ...
            required_calendar{k}, ...
            calendar.Properties.VariableNames), ...
        'DownsideDeviation:MissingCalendarField', ...
        'Calendar is missing required field: %s', ...
        required_calendar{k});

end

% Confirm that the supplied central calendar is consistent with the
% downside-deviation configuration.

expected_window_start = dateshift( ...
    calendar.portfolio_month - calmonths(start_lag), ...
    'start', ...
    'month');

expected_window_end = dateshift( ...
    calendar.portfolio_month - calmonths(end_lag), ...
    'end', ...
    'month');

assert( ...
    isequal(calendar.daily_window_start, expected_window_start), ...
    'DownsideDeviation:CalendarStartMismatch', ...
    'Research calendar does not match configured downside start lag.');

assert( ...
    isequal(calendar.daily_window_end, expected_window_end), ...
    'DownsideDeviation:CalendarEndMismatch', ...
    'Research calendar does not match configured downside end lag.');


%% Input data

daily_dates   = data.daily.dates(:);
daily_returns = data.daily.returns;
daily_rf      = data.daily.rf(:);

M = height(calendar);
N = numel(data.assets.id);

assert(M > 0, ...
    'DownsideDeviation:EmptyCalendar', ...
    'Research calendar contains no portfolio months.');

assert(size(daily_returns,1) == numel(daily_rf), ...
    'DownsideDeviation:DailyRFMismatch', ...
    'Daily returns and risk-free series must have the same number of rows.');


%% Preallocate

value = ...
    NaN(M,N);

valid = ...
    false(M,N);

n_observations = ...
    zeros(M,N);

coverage = ...
    zeros(M,N);

n_expected_observations = ...
    zeros(M,1);

min_required_observations = ...
    zeros(M,1);


%% Compute downside deviation

for k = 1:M

    window_start = ...
        calendar.daily_window_start(k);

    window_end = ...
        calendar.daily_window_end(k);

    rows = ...
        daily_dates >= window_start & ...
        daily_dates <= window_end;

    n_days = ...
        sum(rows);

    assert(n_days > 0, ...
        'DownsideDeviation:EmptyDailyWindow', ...
        ['No daily observations exist between %s and %s for ' ...
         'portfolio month %s.'], ...
        string(window_start), ...
        string(window_end), ...
        string(calendar.portfolio_month(k)));

    n_expected_observations(k) = ...
        n_days;

    required_n = ...
        ceil(dd_cfg.min_coverage * n_days);

    min_required_observations(k) = ...
        required_n;


    %% Daily excess returns

    stock_returns = ...
        daily_returns(rows,:);

    rf = ...
        daily_rf(rows);

    % MATLAB implicit expansion applies the daily risk-free return
    % across all securities.
    excess_returns = ...
        stock_returns - rf;


    %% Coverage and signal validity

    observed = ...
        isfinite(excess_returns);

    n_obs = ...
        sum(observed,1);

    n_observations(k,:) = ...
        n_obs;

    coverage(k,:) = ...
        n_obs / n_days;

    signal_valid = ...
        n_obs >= required_n;

    valid(k,:) = ...
        signal_valid;


    %% Signal calculation

    if any(signal_valid)

        x = ...
            excess_returns(:,signal_valid);

        % Positive excess returns contribute zero downside.
        downside_returns = ...
            min(x,0);

        squared_downside = ...
            downside_returns.^2;

        % Missing observations are excluded from the mean only after the
        % explicit coverage rule has determined signal eligibility.
        value(k,signal_valid) = ...
            sqrt(mean( ...
                squared_downside, ...
                1, ...
                'omitnan'));

    end

end


%% Integrity checks

assert(all(isnan(value(~valid))), ...
    'DownsideDeviation:InvalidSignalStored', ...
    'Invalid downside-deviation observations must remain NaN.');

assert(all(isfinite(value(valid))), ...
    'DownsideDeviation:NonFiniteSignal', ...
    'Valid downside-deviation observations must be finite.');

assert(all(value(valid) >= 0), ...
    'DownsideDeviation:NegativeSignal', ...
    'Downside deviation cannot be negative.');

required_matrix = ...
    repmat(min_required_observations, 1, N);

assert(all( ...
    n_observations(valid) >= required_matrix(valid)), ...
    'DownsideDeviation:CoverageViolation', ...
    'A valid signal violates the configured coverage requirement.');


%% Output

downside.portfolio_month = ...
    calendar.portfolio_month;

downside.value = ...
    value;

downside.valid = ...
    valid;

downside.n_observations = ...
    n_observations;

downside.coverage = ...
    coverage;

downside.n_expected_observations = ...
    n_expected_observations;

downside.min_required_observations = ...
    min_required_observations;

downside.window_start = ...
    calendar.daily_window_start;

downside.window_end = ...
    calendar.daily_window_end;

end