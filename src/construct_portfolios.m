function portfolios = construct_portfolios(universe, selection, cfg)
%CONSTRUCT_PORTFOLIOS Construct point-in-time target portfolio weights.
%
% Builds five portfolios:
%
%   1. Momentum
%   2. Momentum + Downside Deviation
%   3. Momentum + Downside Deviation + Idiosyncratic Skewness
%   4. Equal-weighted market benchmark
%   5. Value-weighted market benchmark
%
% Strategy portfolios are equal weighted under the default specification.
%
% Benchmark definitions:
%
%   EW:
%       equal weight across the base formation universe
%
%   VW:
%       weights proportional to point-in-time market capitalization
%       across the base formation universe
%
% IMPORTANT:
%   This function receives no realized returns. Portfolio weights therefore
%   cannot depend on information realized during the portfolio month.
%
% Empty portfolios follow cfg.portfolio.empty_month_policy. Under the
% current "invalid" policy, the full target-weight row is NaN and the
% corresponding valid-month flag is false. This prevents an empty stock
% portfolio from being silently interpreted as a cash position.

%% Validate configuration

assert( ...
    isfield(cfg, 'portfolio'), ...
    'PortfolioConstruction:MissingConfiguration', ...
    'cfg.portfolio is required.');

required_cfg = { ...
    'long_only', ...
    'fully_invested', ...
    'strategy_weighting', ...
    'empty_month_policy'};

for k = 1:numel(required_cfg)

    assert(isfield(cfg.portfolio, required_cfg{k}), ...
        'PortfolioConstruction:MissingConfiguration', ...
        'Missing portfolio configuration field: %s', ...
        required_cfg{k});

end

assert(cfg.portfolio.long_only, ...
    'PortfolioConstruction:UnsupportedShorting', ...
    'The current research specification requires long-only portfolios.');

assert(cfg.portfolio.fully_invested, ...
    'PortfolioConstruction:UnsupportedInvestmentRule', ...
    'The current research specification requires fully invested portfolios.');

assert( ...
    string(cfg.portfolio.strategy_weighting) == "equal", ...
    'PortfolioConstruction:UnsupportedStrategyWeighting', ...
    'The current strategy specification requires equal weighting.');

assert( ...
    string(cfg.portfolio.empty_month_policy) == "invalid", ...
    'PortfolioConstruction:UnsupportedEmptyPolicy', ...
    'The current implementation supports empty_month_policy = "invalid".');


%% Validate universe

required_universe = { ...
    'portfolio_month', ...
    'base_eligible', ...
    'market_cap'};

for k = 1:numel(required_universe)

    assert(isfield(universe, required_universe{k}), ...
        'PortfolioConstruction:MissingUniverseField', ...
        'Universe is missing required field: %s', ...
        required_universe{k});

end

base_eligible = ...
    universe.base_eligible;

market_cap = ...
    universe.market_cap;

assert(islogical(base_eligible), ...
    'PortfolioConstruction:InvalidUniverseType', ...
    'universe.base_eligible must be logical.');

[M,N] = ...
    size(base_eligible);

assert( ...
    isequal(size(market_cap), [M N]), ...
    'PortfolioConstruction:MarketCapDimensionMismatch', ...
    'universe.market_cap must match base_eligible dimensions.');

assert(all(isfinite(market_cap(base_eligible))), ...
    'PortfolioConstruction:InvalidEligibleMarketCap', ...
    'Every base-eligible security must have finite market capitalization.');

assert(all(market_cap(base_eligible) > 0), ...
    'PortfolioConstruction:InvalidEligibleMarketCap', ...
    'Every base-eligible security must have positive market capitalization.');


%% Validate selection

assert(isfield(selection, 'portfolio_month'), ...
    'PortfolioConstruction:MissingSelectionField', ...
    'selection.portfolio_month is required.');

assert(isfield(selection, 'selected'), ...
    'PortfolioConstruction:MissingSelectionField', ...
    'selection.selected is required.');

required_selection = { ...
    'momentum', ...
    'momentum_downside', ...
    'final'};

for k = 1:numel(required_selection)

    assert(isfield(selection.selected, required_selection{k}), ...
        'PortfolioConstruction:MissingSelectionField', ...
        'selection.selected.%s is required.', ...
        required_selection{k});

end

assert( ...
    isequal( ...
        selection.portfolio_month(:), ...
        universe.portfolio_month(:)), ...
    'PortfolioConstruction:CalendarMismatch', ...
    'Selection and universe portfolio months must align.');

momentum_mask = ...
    selection.selected.momentum;

momentum_downside_mask = ...
    selection.selected.momentum_downside;

final_mask = ...
    selection.selected.final;

assert( ...
    isequal(size(momentum_mask), [M N]) && ...
    isequal(size(momentum_downside_mask), [M N]) && ...
    isequal(size(final_mask), [M N]), ...
    'PortfolioConstruction:SelectionDimensionMismatch', ...
    'Selection masks must match formation-universe dimensions.');

assert( ...
    islogical(momentum_mask) && ...
    islogical(momentum_downside_mask) && ...
    islogical(final_mask), ...
    'PortfolioConstruction:InvalidSelectionType', ...
    'Selection masks must be logical.');

assert(~any(momentum_mask(~base_eligible)), ...
    'PortfolioConstruction:UniverseViolation', ...
    'Momentum selection contains a security outside the formation universe.');

assert(~any(momentum_downside_mask(~base_eligible)), ...
    'PortfolioConstruction:UniverseViolation', ...
    'Momentum+downside selection contains a security outside the formation universe.');

assert(~any(final_mask(~base_eligible)), ...
    'PortfolioConstruction:UniverseViolation', ...
    'Final selection contains a security outside the formation universe.');


%% Construct strategy portfolios

[weights_momentum, valid_momentum, n_momentum] = ...
    equal_weight_portfolio(momentum_mask);

[weights_momentum_downside, ...
 valid_momentum_downside, ...
 n_momentum_downside] = ...
    equal_weight_portfolio(momentum_downside_mask);

[weights_final, valid_final, n_final] = ...
    equal_weight_portfolio(final_mask);


%% Construct equal-weighted benchmark

[weights_ew, valid_ew, n_ew] = ...
    equal_weight_portfolio(base_eligible);


%% Construct value-weighted benchmark

weights_vw = ...
    NaN(M,N);

valid_vw = ...
    false(M,1);

n_vw = ...
    sum(base_eligible,2);

for t = 1:M

    eligible = ...
        base_eligible(t,:);

    if ~any(eligible)
        continue;
    end

    cap = ...
        market_cap(t,eligible);

    total_cap = ...
        sum(cap);

    if ~isfinite(total_cap) || total_cap <= 0
        continue;
    end

    row = ...
        zeros(1,N);

    row(eligible) = ...
        cap / total_cap;

    weights_vw(t,:) = ...
        row;

    valid_vw(t) = ...
        true;

end


%% Integrity checks

validate_weight_matrix( ...
    weights_momentum, ...
    valid_momentum, ...
    momentum_mask, ...
    "momentum");

validate_weight_matrix( ...
    weights_momentum_downside, ...
    valid_momentum_downside, ...
    momentum_downside_mask, ...
    "momentum_downside");

validate_weight_matrix( ...
    weights_final, ...
    valid_final, ...
    final_mask, ...
    "final");

validate_weight_matrix( ...
    weights_ew, ...
    valid_ew, ...
    base_eligible, ...
    "equal_weight_benchmark");

validate_weight_matrix( ...
    weights_vw, ...
    valid_vw, ...
    base_eligible, ...
    "value_weight_benchmark");


%% Output

portfolios.portfolio_month = ...
    universe.portfolio_month;


%% Target weights

portfolios.weights.momentum = ...
    weights_momentum;

portfolios.weights.momentum_downside = ...
    weights_momentum_downside;

portfolios.weights.final = ...
    weights_final;

portfolios.weights.equal_weight = ...
    weights_ew;

portfolios.weights.value_weight = ...
    weights_vw;


%% Validity

portfolios.valid.momentum = ...
    valid_momentum;

portfolios.valid.momentum_downside = ...
    valid_momentum_downside;

portfolios.valid.final = ...
    valid_final;

portfolios.valid.equal_weight = ...
    valid_ew;

portfolios.valid.value_weight = ...
    valid_vw;


%% Holdings counts

portfolios.n_holdings.momentum = ...
    n_momentum;

portfolios.n_holdings.momentum_downside = ...
    n_momentum_downside;

portfolios.n_holdings.final = ...
    n_final;

portfolios.n_holdings.equal_weight = ...
    n_ew;

portfolios.n_holdings.value_weight = ...
    n_vw;


%% Metadata

portfolios.meta.strategy_weighting = ...
    string(cfg.portfolio.strategy_weighting);

portfolios.meta.empty_month_policy = ...
    string(cfg.portfolio.empty_month_policy);

portfolios.meta.benchmarks = ...
    ["equal_weight", "value_weight"];

end


function [weights, valid_month, n_holdings] = equal_weight_portfolio(mask)
%EQUAL_WEIGHT_PORTFOLIO Construct equal-weighted target portfolios.

[M,N] = ...
    size(mask);

weights = ...
    NaN(M,N);

valid_month = ...
    false(M,1);

n_holdings = ...
    sum(mask,2);

for t = 1:M

    selected = ...
        mask(t,:);

    n = ...
        n_holdings(t);

    if n == 0
        continue;
    end

    row = ...
        zeros(1,N);

    row(selected) = ...
        1 / n;

    weights(t,:) = ...
        row;

    valid_month(t) = ...
        true;

end

end


function validate_weight_matrix(weights, valid_month, allowed_mask, name)
%VALIDATE_WEIGHT_MATRIX Verify target-weight integrity.

[M,N] = ...
    size(weights);

assert( ...
    isequal(size(allowed_mask), [M N]), ...
    'PortfolioConstruction:InternalDimensionMismatch', ...
    'Allowed-mask dimensions do not match weight dimensions.');

assert( ...
    isequal(size(valid_month), [M 1]), ...
    'PortfolioConstruction:InternalDimensionMismatch', ...
    'Portfolio validity vector has incorrect dimensions.');


%% Valid months

if any(valid_month)

    valid_weights = ...
        weights(valid_month,:);

    assert(all(isfinite(valid_weights(:))), ...
        'PortfolioConstruction:NonFiniteWeight', ...
        '%s contains non-finite weights in a valid month.', ...
        name);

    assert(all(valid_weights(:) >= 0), ...
        'PortfolioConstruction:NegativeWeight', ...
        '%s contains a negative portfolio weight.', ...
        name);

    row_sums = ...
        sum(valid_weights,2);

    assert(all(abs(row_sums - 1) < 1e-12), ...
        'PortfolioConstruction:NotFullyInvested', ...
        '%s weights do not sum to one in every valid month.', ...
        name);

end


%% Invalid months

if any(~valid_month)

    invalid_weights = ...
        weights(~valid_month,:);

    assert(all(isnan(invalid_weights(:))), ...
        'PortfolioConstruction:InvalidMonthWeights', ...
        ['Invalid portfolio months must contain NaN weights rather ' ...
         'than silently representing cash.']);

end


%% Holdings restriction

for t = 1:M

    if ~valid_month(t)
        continue;
    end

    disallowed = ...
        ~allowed_mask(t,:);

    assert(all(weights(t,disallowed) == 0), ...
        'PortfolioConstruction:HoldingsViolation', ...
        '%s assigns weight to a security outside its allowed set.', ...
        name);

end

end