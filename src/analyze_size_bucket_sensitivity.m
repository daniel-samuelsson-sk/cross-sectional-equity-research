function r3 = analyze_size_bucket_sensitivity(data, research)
%ANALYZE_SIZE_BUCKET_SENSITIVITY Evaluate performance by relative size bucket.
%
% r3 = ANALYZE_SIZE_BUCKET_SENSITIVITY(data, research)
%
% The analysis uses the existing out-of-sample portfolio weights for:
%
%   MOM
%   MOM + DD
%   FINAL
%   EW
%
% For each portfolio, six variants are evaluated:
%
%   size bucket 1
%   size bucket 2
%   size bucket 3
%   size bucket 4
%   size bucket 5
%   excluding size bucket 1
%
% For a size-bucket portfolio, weights outside the selected bucket are
% set to zero and the remaining target weights are renormalized to sum
% to one each month.
%
% For the ex-bucket-1 portfolio, bucket 1 is removed and the remaining
% bucket 2-5 target weights are renormalized.
%
% Performance measures are computed by evaluate_performance. This
% function does not recreate Sharpe, CAGR, volatility, drawdown or
% turnover calculations.


%% Validate top-level inputs

validate_research_data(data);

assert(isstruct(research), ...
    'SizeSensitivity:InvalidResearch', ...
    'research must be a research-result struct.');

required_research_fields = { ...
    'config', ...
    'calendar', ...
    'size_control', ...
    'evaluation'};

for k = 1:numel(required_research_fields)

    field = ...
        required_research_fields{k};

    assert(isfield(research, field), ...
        'SizeSensitivity:MissingResearchField', ...
        'research.%s is required.', ...
        field);

end


cfg = ...
    research.config;

calendar = ...
    research.evaluation.calendar;


%% Validate evaluation calendar

assert(istable(calendar), ...
    'SizeSensitivity:InvalidCalendar', ...
    'research.evaluation.calendar must be a table.');

assert( ...
    ismember('portfolio_month', calendar.Properties.VariableNames) && ...
    ismember('phase', calendar.Properties.VariableNames), ...
    'SizeSensitivity:MissingCalendarField', ...
    'Evaluation calendar must contain portfolio_month and phase.');

assert(all(calendar.phase == "evaluation"), ...
    'SizeSensitivity:InvalidEvaluationCalendar', ...
    'R3 must use evaluation-period months only.');

M = ...
    height(calendar);

N = ...
    numel(data.assets.id);

assert(M > 0, ...
    'SizeSensitivity:EmptyEvaluationPeriod', ...
    'Evaluation calendar is empty.');


%% Obtain the evaluation-period size-bucket matrix
%
% The bucket matrix is taken directly from the existing size-control
% object using the evaluation rows of the research calendar.

assert( ...
    isequal( ...
        research.size_control.portfolio_month(:), ...
        research.calendar.portfolio_month(:)), ...
    'SizeSensitivity:SizeControlCalendarMismatch', ...
    'Size-control months must align with the research calendar.');

evaluation_mask = ...
    research.calendar.phase == "evaluation";

assert( ...
    sum(evaluation_mask) == M, ...
    'SizeSensitivity:EvaluationRowMismatch', ...
    'Evaluation-row count differs between research objects.');

bucket = ...
    research.size_control.bucket(evaluation_mask,:);

bucket_month = ...
    research.size_control.portfolio_month(evaluation_mask);

assert( ...
    isequal( ...
        bucket_month(:), ...
        calendar.portfolio_month(:)), ...
    'SizeSensitivity:BucketCalendarMismatch', ...
    'Evaluation size buckets do not align with the evaluation calendar.');

assert( ...
    isequal(size(bucket), [M N]), ...
    'SizeSensitivity:BucketDimensionMismatch', ...
    'Evaluation size-bucket matrix has incorrect dimensions.');

assert( ...
    isfield(research.size_control, 'n_buckets') && ...
    research.size_control.n_buckets == 5, ...
    'SizeSensitivity:UnexpectedBucketCount', ...
    'R3 requires exactly five size buckets.');


%% Validate existing OOS portfolio interface

source_portfolios = ...
    research.evaluation.portfolios;

assert(isfield(source_portfolios, 'portfolio_month'), ...
    'SizeSensitivity:MissingPortfolioCalendar', ...
    'Evaluation portfolios must contain portfolio_month.');

assert( ...
    isequal( ...
        source_portfolios.portfolio_month(:), ...
        calendar.portfolio_month(:)), ...
    'SizeSensitivity:PortfolioCalendarMismatch', ...
    'Evaluation portfolio weights do not align with the R3 calendar.');

assert(isfield(source_portfolios, 'weights'), ...
    'SizeSensitivity:MissingWeights', ...
    'Evaluation portfolios must contain weights.');

assert(isfield(source_portfolios, 'valid'), ...
    'SizeSensitivity:MissingValidity', ...
    'Evaluation portfolios must contain valid.');

assert(isfield(source_portfolios, 'n_holdings'), ...
    'SizeSensitivity:MissingHoldings', ...
    'Evaluation portfolios must contain n_holdings.');


source_fields = { ...
    'momentum', ...
    'momentum_downside', ...
    'final', ...
    'equal_weight'};

output_prefixes = { ...
    'mom', ...
    'mom_dd', ...
    'final', ...
    'ew'};

portfolio_labels = [ ...
    "MOM"; ...
    "MOM+DD"; ...
    "FINAL"; ...
    "EW"];


%% Validate source weights before constructing R3 portfolios

weight_tolerance = ...
    1e-12;


for j = 1:numel(source_fields)

    source_field = ...
        source_fields{j};

    assert(isfield(source_portfolios.weights, source_field), ...
        'SizeSensitivity:MissingSourcePortfolio', ...
        'Missing evaluation portfolio weights: %s.', ...
        source_field);

    assert(isfield(source_portfolios.valid, source_field), ...
        'SizeSensitivity:MissingSourceValidity', ...
        'Missing evaluation portfolio validity: %s.', ...
        source_field);

    weights = ...
        source_portfolios.weights.(source_field);

    assert( ...
        isequal(size(weights), [M N]), ...
        'SizeSensitivity:SourceWeightDimensionMismatch', ...
        '%s weights have incorrect dimensions.', ...
        source_field);

    nan_row = ...
        all(isnan(weights), 2);

    assert(~any(nan_row), ...
        'SizeSensitivity:EmptySourceWeightRow', ...
        '%s contains an all-NaN OOS weight row.', ...
        source_field);

    assert(all(isfinite(weights(:))), ...
        'SizeSensitivity:NonFiniteSourceWeight', ...
        '%s contains non-finite OOS target weights.', ...
        source_field);

    assert(all(weights(:) >= 0), ...
        'SizeSensitivity:NegativeSourceWeight', ...
        '%s contains a negative target weight.', ...
        source_field);

    source_valid = ...
        source_portfolios.valid.(source_field);

    assert( ...
        isequal(size(source_valid), [M 1]) && ...
        islogical(source_valid) && ...
        all(source_valid), ...
        'SizeSensitivity:InvalidSourcePortfolioMonth', ...
        '%s must have a valid target portfolio in every OOS month.', ...
        source_field);

    row_sum = ...
        sum(weights, 2);

    assert( ...
        max(abs(row_sum - 1)) <= weight_tolerance, ...
        'SizeSensitivity:SourceWeightsNotNormalized', ...
        '%s target weights must sum to one every OOS month.', ...
        source_field);

    held = ...
        weights > 0;

    held_bucket = ...
        bucket(held);

    assert( ...
        all(isfinite(held_bucket)) && ...
        all(held_bucket == floor(held_bucket)) && ...
        all(held_bucket >= 1) && ...
        all(held_bucket <= 5), ...
        'SizeSensitivity:HeldAssetMissingBucket', ...
        ['Every asset with positive %s weight must belong to exactly ' ...
         'one of size buckets 1-5.'], ...
        source_field);

end


%% Construct the 24 R3 portfolios

portfolios = ...
    struct();

portfolios.portfolio_month = ...
    calendar.portfolio_month;

portfolio_names = ...
    strings(0,1);


for j = 1:numel(source_fields)

    source_field = ...
        source_fields{j};

    prefix = ...
        output_prefixes{j};

    source_weights = ...
        source_portfolios.weights.(source_field);


    %% Bucket 1 through bucket 5

    for b = 1:5

        bucket_mask = ...
            bucket == b;

        [weights, valid, n_holdings] = ...
            mask_and_normalize( ...
                source_weights, ...
                bucket_mask, ...
                sprintf('%s size bucket %d', ...
                    portfolio_labels(j), ...
                    b));

        name = ...
            sprintf('%s_bucket_%d', prefix, b);

        portfolios.weights.(name) = ...
            weights;

        portfolios.valid.(name) = ...
            valid;

        portfolios.n_holdings.(name) = ...
            n_holdings;

        portfolio_names(end+1,1) = ...
            string(name);

    end


    %% Exclude bucket 1 and renormalize buckets 2-5

    ex_bucket_1_mask = ...
        bucket >= 2 & ...
        bucket <= 5;

    [weights, valid, n_holdings] = ...
        mask_and_normalize( ...
            source_weights, ...
            ex_bucket_1_mask, ...
            sprintf('%s excluding size bucket 1', ...
                portfolio_labels(j)));

    name = ...
        sprintf('%s_ex_bucket_1', prefix);

    portfolios.weights.(name) = ...
        weights;

    portfolios.valid.(name) = ...
        valid;

    portfolios.n_holdings.(name) = ...
        n_holdings;

    portfolio_names(end+1,1) = ...
        string(name);

end


assert(numel(portfolio_names) == 24, ...
    'SizeSensitivity:UnexpectedPortfolioCount', ...
    'R3 must construct exactly 24 portfolios.');


%% Evaluate all 24 portfolios in one engine call

performance = ...
    evaluate_performance( ...
        data, ...
        portfolios, ...
        calendar, ...
        cfg);


%% Require a complete realized-return series for every portfolio

for k = 1:numel(portfolio_names)

    name = ...
        char(portfolio_names(k));

    assert( ...
        all(performance.valid_return.(name)), ...
        'SizeSensitivity:InvalidRealizedReturnMonth', ...
        '%s does not have a valid realized return in every OOS month.', ...
        name);

    assert( ...
        performance.summary.evaluation.(name).complete_return_series, ...
        'SizeSensitivity:IncompleteReturnSeries', ...
        '%s does not have a complete OOS return series.', ...
        name);

end


%% Partition and renormalization identities
%
% These identities verify the mechanics of the partition:
%
%   - each positive source weight is allocated across the five bucket
%     portfolios without loss or duplication;
%   - within-bucket and ex-bucket-1 renormalization is consistent.
%
% Correct size-bucket definitions and date alignment are established
% separately by the structural checks above.

identity_full_max_abs_diff = ...
    NaN(numel(source_fields),1);

identity_ex1_max_abs_diff = ...
    NaN(numel(source_fields),1);


for j = 1:numel(source_fields)

    source_field = ...
        source_fields{j};

    prefix = ...
        output_prefixes{j};

    source_weights = ...
        source_portfolios.weights.(source_field);

    bucket_share = ...
        NaN(M,5);

    bucket_return = ...
        NaN(M,5);


    for b = 1:5

        in_bucket = ...
            bucket == b;

        bucket_share(:,b) = ...
            sum( ...
                source_weights .* double(in_bucket), ...
                2);

        name = ...
            sprintf('%s_bucket_%d', prefix, b);

        bucket_return(:,b) = ...
            performance.returns.(name);

    end


    %% The five buckets must partition all positive source weight

    total_bucket_share = ...
        sum(bucket_share, 2);

    assert( ...
        max(abs(total_bucket_share - 1)) <= weight_tolerance, ...
        'SizeSensitivity:BucketPartitionMismatch', ...
        ['Size buckets do not partition all positive %s target weight ' ...
         'within tolerance.'], ...
        source_field);


    %% Reconstruct the full portfolio return from bucket portfolios

    reconstructed_full_return = ...
        sum( ...
            bucket_share .* bucket_return, ...
            2);

    source_return = ...
        research.evaluation.performance.returns.(source_field);

    full_difference = ...
        reconstructed_full_return - ...
        source_return;

    identity_full_max_abs_diff(j) = ...
        max(abs(full_difference));

    assert( ...
        identity_full_max_abs_diff(j) <= weight_tolerance, ...
        'SizeSensitivity:FullReturnIdentityMismatch', ...
        ['Bucket-weighted returns fail to reconstruct the full %s ' ...
         'portfolio return within %.1e.'], ...
        source_field, ...
        weight_tolerance);


    %% Reconstruct the ex-bucket-1 return from buckets 2-5

    remaining_share = ...
        sum(bucket_share(:,2:5), 2);

    assert(all(remaining_share > 0), ...
        'SizeSensitivity:EmptyExBucket1Portfolio', ...
        '%s has no remaining weight after excluding size bucket 1.', ...
        source_field);

    normalized_remaining_share = ...
        bucket_share(:,2:5) ./ ...
        remaining_share;

    reconstructed_ex1_return = ...
        sum( ...
            normalized_remaining_share .* ...
            bucket_return(:,2:5), ...
            2);

    ex1_name = ...
        sprintf('%s_ex_bucket_1', prefix);

    ex1_return = ...
        performance.returns.(ex1_name);

    ex1_difference = ...
        reconstructed_ex1_return - ...
        ex1_return;

    identity_ex1_max_abs_diff(j) = ...
        max(abs(ex1_difference));

    assert( ...
        identity_ex1_max_abs_diff(j) <= weight_tolerance, ...
        'SizeSensitivity:ExBucket1IdentityMismatch', ...
        ['Bucket 2-5 returns fail to reconstruct the %s ex-bucket-1 ' ...
         'portfolio within %.1e.'], ...
        source_field, ...
        weight_tolerance);

end


identity = ...
    table( ...
        portfolio_labels, ...
        identity_full_max_abs_diff, ...
        identity_ex1_max_abs_diff, ...
        'VariableNames', { ...
            'portfolio', ...
            'full_return_max_abs_diff', ...
            'ex_bucket_1_max_abs_diff'});


%% Build compact six-row result table

segment_keys = { ...
    'bucket_1', ...
    'bucket_2', ...
    'bucket_3', ...
    'bucket_4', ...
    'bucket_5', ...
    'ex_bucket_1'};

segment_labels = [ ...
    "Size bucket 1"; ...
    "Size bucket 2"; ...
    "Size bucket 3"; ...
    "Size bucket 4"; ...
    "Size bucket 5"; ...
    "Excluding size bucket 1"];


summary = ...
    table( ...
        segment_labels, ...
        'VariableNames', {'segment'});


for j = 1:numel(output_prefixes)

    prefix = ...
        output_prefixes{j};

    sharpe = ...
        NaN(6,1);

    cagr = ...
        NaN(6,1);

    annualized_volatility = ...
        NaN(6,1);

    maximum_drawdown = ...
        NaN(6,1);

    average_holdings = ...
        NaN(6,1);


    for s = 1:numel(segment_keys)

        name = ...
            sprintf( ...
                '%s_%s', ...
                prefix, ...
                segment_keys{s});

        metrics = ...
            performance.summary.evaluation.(name);

        sharpe(s) = ...
            metrics.sharpe;

        cagr(s) = ...
            metrics.cagr;

        annualized_volatility(s) = ...
            metrics.annualized_volatility;

        maximum_drawdown(s) = ...
            metrics.maximum_drawdown;

        average_holdings(s) = ...
            metrics.average_holdings;

    end


    summary.(sprintf('%s_sharpe', prefix)) = ...
        sharpe;

    summary.(sprintf('%s_cagr', prefix)) = ...
        cagr;

    summary.(sprintf('%s_annualized_volatility', prefix)) = ...
        annualized_volatility;

    summary.(sprintf('%s_maximum_drawdown', prefix)) = ...
        maximum_drawdown;

    summary.(sprintf('%s_average_holdings', prefix)) = ...
        average_holdings;

end


%% Output

r3 = ...
    struct();

r3.calendar = ...
    calendar;

r3.size_bucket = ...
    bucket;

r3.portfolios = ...
    portfolios;

r3.performance = ...
    performance;

r3.summary = ...
    summary;

r3.identity = ...
    identity;


r3.meta = ...
    struct();

r3.meta.n_size_buckets = ...
    5;

r3.meta.strategy_order = ...
    portfolio_labels;

r3.meta.segment_order = ...
    segment_labels;

r3.meta.weight_tolerance = ...
    weight_tolerance;

r3.meta.performance_engine = ...
    "evaluate_performance";

end


function [weights, valid, n_holdings] = ...
    mask_and_normalize(source_weights, inclusion_mask, label)
%MASK_AND_NORMALIZE Restrict target weights and renormalize each month.

assert( ...
    isequal(size(source_weights), size(inclusion_mask)), ...
    'SizeSensitivity:MaskDimensionMismatch', ...
    '%s mask does not match the source weight dimensions.', ...
    label);

assert(islogical(inclusion_mask), ...
    'SizeSensitivity:InvalidMaskType', ...
    '%s inclusion mask must be logical.', ...
    label);


masked_weights = ...
    source_weights .* ...
    double(inclusion_mask);


%% Check holdings before division

n_holdings = ...
    sum(masked_weights > 0, 2);

assert(all(n_holdings > 0), ...
    'SizeSensitivity:EmptySizeBucketPortfolio', ...
    '%s has at least one OOS month with no holdings.', ...
    label);


row_sum = ...
    sum(masked_weights, 2);

assert( ...
    all(isfinite(row_sum)) && ...
    all(row_sum > 0), ...
    'SizeSensitivity:InvalidMaskedWeightSum', ...
    '%s has a non-positive or non-finite target-weight sum.', ...
    label);


%% Renormalize

weights = ...
    masked_weights ./ ...
    row_sum;

valid = ...
    true(size(row_sum));


%% Integrity checks

assert(all(isfinite(weights(:))), ...
    'SizeSensitivity:NonFiniteNormalizedWeight', ...
    '%s produced non-finite normalized weights.', ...
    label);

assert(all(weights(:) >= 0), ...
    'SizeSensitivity:NegativeNormalizedWeight', ...
    '%s produced negative normalized weights.', ...
    label);

normalized_sum = ...
    sum(weights, 2);

assert( ...
    max(abs(normalized_sum - 1)) <= 1e-12, ...
    'SizeSensitivity:NormalizedWeightsDoNotSumToOne', ...
    '%s normalized weights do not sum to one.', ...
    label);

end