function halves = split_sample_halves(portfolio_month)
%SPLIT_SAMPLE_HALVES Split consecutive portfolio months into two halves.
%
% halves = SPLIT_SAMPLE_HALVES(portfolio_month)
%
% The first half holds the first floor(M/2) months and the second half the
% remaining months. The subperiod analysis and the CAPM channel both use
% this single rule, so they always evaluate the same subperiods.
%
% Labels name the calendar years, for example 1990-2006. If two of the
% three periods (the full sample and the two halves) would get the same
% label, all three name months instead, for example 2020-01/2020-06.

portfolio_month = ...
    portfolio_month(:);

M = ...
    numel(portfolio_month);

assert(M >= 2, ...
    'SampleHalves:TooFewMonths', ...
    'At least two portfolio months are required.');


n_first = ...
    floor(M / 2);

first_mask = ...
    (1:M)' <= n_first;


halves.mask = { ...
    first_mask, ...
    ~first_mask};

labels = [ ...
    year_label(portfolio_month); ...
    year_label(portfolio_month(first_mask)); ...
    year_label(portfolio_month(~first_mask))];

if numel(unique(labels)) < 3

    labels = [ ...
        month_label(portfolio_month); ...
        month_label(portfolio_month(first_mask)); ...
        month_label(portfolio_month(~first_mask))];

end

halves.full_label = ...
    labels(1);

halves.label = ...
    labels(2:3);

halves.start_month = [ ...
    portfolio_month(1); ...
    portfolio_month(n_first + 1)];

halves.end_month = [ ...
    portfolio_month(n_first); ...
    portfolio_month(end)];

end


function label = year_label(months)
%YEAR_LABEL Label a block of months by its first and last calendar year.

label = ...
    string( ...
        sprintf( ...
            '%d-%d', ...
            year(months(1)), ...
            year(months(end))));

end


function label = month_label(months)
%MONTH_LABEL Label a block of months by its first and last month.

label = ...
    string( ...
        sprintf( ...
            '%d-%02d/%d-%02d', ...
            year(months(1)), ...
            month(months(1)), ...
            year(months(end)), ...
            month(months(end))));

end
