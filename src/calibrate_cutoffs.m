function calibration = calibrate_cutoffs( ...
    data, ...
    calendar, ...
    universe, ...
    size_control, ...
    momentum, ...
    downside, ...
    idio_skew, ...
    cfg)
%CALIBRATE_CUTOFFS Evaluate signal-cutoff candidates on calibration data.
%
% Candidate specifications are evaluated exclusively over calibration
% months. Admissible candidates are ranked by Sharpe ratio, turnover and
% portfolio breadth.
%
% cfg.selection identifies the research specification carried forward to
% out-of-sample evaluation. The selected specification must belong to the
% candidate grid and satisfy the admissibility requirements.

validate_research_data(data);


%% Validate calibration configuration

assert(isfield(cfg, 'calibration'), ...
    'Calibration:MissingConfiguration', ...
    'cfg.calibration is required.');

required_cfg = { ...
    'momentum_pct', ...
    'downside_pct', ...
    'skew_pct', ...
    'min_median_holdings', ...
    'objective', ...
    'tie_breakers'};

for k = 1:numel(required_cfg)

    assert(isfield(cfg.calibration, required_cfg{k}), ...
        'Calibration:MissingConfiguration', ...
        'Missing calibration configuration field: %s', ...
        required_cfg{k});

end

assert(isfield(cfg, 'selection'), ...
    'Calibration:MissingSelection', ...
    'cfg.selection is required.');

required_selection = { ...
    'momentum_pct', ...
    'downside_pct', ...
    'skew_pct'};

for k = 1:numel(required_selection)

    assert(isfield(cfg.selection, required_selection{k}), ...
        'Calibration:MissingSelection', ...
        'Missing selection field: %s', ...
        required_selection{k});

end


%% Validate search grids

validate_grid( ...
    cfg.calibration.momentum_pct, ...
    'momentum_pct');

validate_grid( ...
    cfg.calibration.downside_pct, ...
    'downside_pct');

validate_grid( ...
    cfg.calibration.skew_pct, ...
    'skew_pct');

assert( ...
    isscalar(cfg.calibration.min_median_holdings) && ...
    isnumeric(cfg.calibration.min_median_holdings) && ...
    isfinite(cfg.calibration.min_median_holdings) && ...
    cfg.calibration.min_median_holdings >= 1, ...
    'Calibration:InvalidMinimumHoldings', ...
    'min_median_holdings must be a finite scalar >= 1.');

assert( ...
    string(cfg.calibration.objective) == "sharpe", ...
    'Calibration:UnsupportedObjective', ...
    'The current calibration specification requires objective = "sharpe".');

configured_tie_breakers = ...
    reshape( ...
        string(cfg.calibration.tie_breakers), ...
        1, []);

expected_tie_breakers = ...
    ["turnover_asc", "holdings_desc"];

assert( ...
    isequal( ...
        configured_tie_breakers, ...
        expected_tie_breakers), ...
    'Calibration:UnsupportedTieBreakers', ...
    ['The current calibration specification requires tie breakers ' ...
     '["turnover_asc","holdings_desc"].']);


%% Validate selected specification

validate_percentile( ...
    cfg.selection.momentum_pct, ...
    'selection.momentum_pct');

validate_percentile( ...
    cfg.selection.downside_pct, ...
    'selection.downside_pct');

validate_percentile( ...
    cfg.selection.skew_pct, ...
    'selection.skew_pct');


%% Validate calendar

assert( ...
    ismember('portfolio_month', ...
        calendar.Properties.VariableNames), ...
    'Calibration:MissingCalendarField', ...
    'Calendar is missing portfolio_month.');

assert( ...
    ismember('phase', ...
        calendar.Properties.VariableNames), ...
    'Calibration:MissingCalendarField', ...
    'Calendar is missing phase.');

calibration_mask = ...
    calendar.phase == "calibration";

assert(any(calibration_mask), ...
    'Calibration:NoCalibrationMonths', ...
    'Research calendar contains no calibration months.');


%% Calibration-period research objects

cal_calendar = ...
    calendar(calibration_mask,:);

cal_universe = ...
    subset_universe( ...
        universe, ...
        calibration_mask);

cal_size_control = ...
    subset_size_control( ...
        size_control, ...
        calibration_mask);

cal_momentum = ...
    subset_signal( ...
        momentum, ...
        calibration_mask);

cal_downside = ...
    subset_signal( ...
        downside, ...
        calibration_mask);

cal_idio_skew = ...
    subset_signal( ...
        idio_skew, ...
        calibration_mask);


%% Validate calendar alignment

assert( ...
    isequal( ...
        cal_universe.portfolio_month(:), ...
        cal_calendar.portfolio_month(:)), ...
    'Calibration:UniverseCalendarMismatch', ...
    'Calibration universe does not align with calibration calendar.');

assert( ...
    isequal( ...
        cal_size_control.portfolio_month(:), ...
        cal_calendar.portfolio_month(:)), ...
    'Calibration:SizeCalendarMismatch', ...
    'Calibration size control does not align with calibration calendar.');

assert( ...
    isequal( ...
        cal_momentum.portfolio_month(:), ...
        cal_calendar.portfolio_month(:)), ...
    'Calibration:SignalCalendarMismatch', ...
    'Momentum signal does not align with calibration calendar.');

assert( ...
    isequal( ...
        cal_downside.portfolio_month(:), ...
        cal_calendar.portfolio_month(:)), ...
    'Calibration:SignalCalendarMismatch', ...
    'Downside signal does not align with calibration calendar.');

assert( ...
    isequal( ...
        cal_idio_skew.portfolio_month(:), ...
        cal_calendar.portfolio_month(:)), ...
    'Calibration:SignalCalendarMismatch', ...
    'Idiosyncratic-skewness signal does not align with calibration calendar.');


%% Candidate grid

[mom_grid, dd_grid, skew_grid] = ...
    ndgrid( ...
        cfg.calibration.momentum_pct, ...
        cfg.calibration.downside_pct, ...
        cfg.calibration.skew_pct);

momentum_pct = ...
    mom_grid(:);

downside_pct = ...
    dd_grid(:);

skew_pct = ...
    skew_grid(:);

n_candidates = ...
    numel(momentum_pct);

candidate_id = ...
    (1:n_candidates)';


%% Candidate diagnostics

annualized_total_return = ...
    NaN(n_candidates,1);

cagr = ...
    NaN(n_candidates,1);

annualized_volatility = ...
    NaN(n_candidates,1);

annualized_excess_return = ...
    NaN(n_candidates,1);

sharpe = ...
    NaN(n_candidates,1);

maximum_drawdown = ...
    NaN(n_candidates,1);

average_turnover = ...
    NaN(n_candidates,1);

average_holdings = ...
    NaN(n_candidates,1);

median_holdings = ...
    NaN(n_candidates,1);

n_invalid_target_months = ...
    zeros(n_candidates,1);

n_invalid_returns = ...
    zeros(n_candidates,1);

complete_return_series = ...
    false(n_candidates,1);

complete_turnover_series = ...
    false(n_candidates,1);

admissible = ...
    false(n_candidates,1);


%% Evaluate candidates

for c = 1:n_candidates

    cutoffs.momentum_pct = ...
        momentum_pct(c);

    cutoffs.downside_pct = ...
        downside_pct(c);

    cutoffs.skew_pct = ...
        skew_pct(c);

    selection = ...
        apply_signal_filters( ...
            cal_universe, ...
            cal_size_control, ...
            cal_momentum, ...
            cal_downside, ...
            cal_idio_skew, ...
            cutoffs);

    all_portfolios = ...
        construct_portfolios( ...
            cal_universe, ...
            selection, ...
            cfg);

    final_portfolio = ...
        retain_final_portfolio( ...
            all_portfolios);

    candidate_performance = ...
        evaluate_performance( ...
            data, ...
            final_portfolio, ...
            cal_calendar, ...
            cfg);

    summary = ...
        candidate_performance.summary.calibration.final;

    annualized_total_return(c) = ...
        summary.annualized_total_return;

    cagr(c) = ...
        summary.cagr;

    annualized_volatility(c) = ...
        summary.annualized_volatility;

    annualized_excess_return(c) = ...
        summary.annualized_excess_return;

    sharpe(c) = ...
        summary.sharpe;

    maximum_drawdown(c) = ...
        summary.maximum_drawdown;

    average_turnover(c) = ...
        summary.average_turnover;

    average_holdings(c) = ...
        summary.average_holdings;

    median_holdings(c) = ...
        summary.median_holdings;

    n_invalid_target_months(c) = ...
        sum(~final_portfolio.valid.final);

    n_invalid_returns(c) = ...
        summary.n_invalid_returns;

    complete_return_series(c) = ...
        summary.complete_return_series;

    complete_turnover_series(c) = ...
        summary.complete_turnover_series;

    admissible(c) = ...
        summary.complete_return_series && ...
        summary.complete_turnover_series && ...
        isfinite(summary.sharpe) && ...
        isfinite(summary.average_turnover) && ...
        isfinite(summary.median_holdings) && ...
        summary.median_holdings >= ...
            cfg.calibration.min_median_holdings;

end


%% Candidate table

candidates = table( ...
    candidate_id, ...
    momentum_pct, ...
    downside_pct, ...
    skew_pct, ...
    annualized_total_return, ...
    cagr, ...
    annualized_volatility, ...
    annualized_excess_return, ...
    sharpe, ...
    maximum_drawdown, ...
    average_turnover, ...
    average_holdings, ...
    median_holdings, ...
    n_invalid_target_months, ...
    n_invalid_returns, ...
    complete_return_series, ...
    complete_turnover_series, ...
    admissible);


%% Rank admissible candidates

admissible_candidates = ...
    candidates(candidates.admissible,:);

assert(~isempty(admissible_candidates), ...
    'Calibration:NoAdmissibleCandidates', ...
    ['No calibration candidate satisfies the complete-series and ' ...
     'minimum-holdings requirements.']);

ranked_candidates = ...
    sortrows( ...
        admissible_candidates, ...
        { ...
            'sharpe', ...
            'average_turnover', ...
            'median_holdings', ...
            'candidate_id'}, ...
        { ...
            'descend', ...
            'ascend', ...
            'descend', ...
            'ascend'});

ranked_candidates.rank = ...
    (1:height(ranked_candidates))';


%% Research specification

selected_mask = ...
    candidates.momentum_pct == cfg.selection.momentum_pct & ...
    candidates.downside_pct == cfg.selection.downside_pct & ...
    candidates.skew_pct == cfg.selection.skew_pct;

assert(sum(selected_mask) == 1, ...
    'Calibration:SelectedSpecificationNotInGrid', ...
    'cfg.selection must identify exactly one candidate in the calibration grid.');

selected_candidate = ...
    candidates(selected_mask,:);

assert(selected_candidate.admissible, ...
    'Calibration:SelectedSpecificationNotAdmissible', ...
    'The configured research specification is not admissible.');

selected_rank_mask = ...
    ranked_candidates.candidate_id == ...
    selected_candidate.candidate_id;

assert(sum(selected_rank_mask) == 1, ...
    'Calibration:SelectedSpecificationRankingFailure', ...
    'Selected specification is missing from the admissible ranking.');

selected = ...
    ranked_candidates(selected_rank_mask,:);

selected_cutoffs.momentum_pct = ...
    selected.momentum_pct;

selected_cutoffs.downside_pct = ...
    selected.downside_pct;

selected_cutoffs.skew_pct = ...
    selected.skew_pct;

top_ranked = ...
    ranked_candidates(1,:);


%% Output

calibration.period_start = ...
    cal_calendar.portfolio_month(1);

calibration.period_end = ...
    cal_calendar.portfolio_month(end);

calibration.n_calibration_months = ...
    height(cal_calendar);

calibration.search_space.momentum_pct = ...
    cfg.calibration.momentum_pct;

calibration.search_space.downside_pct = ...
    cfg.calibration.downside_pct;

calibration.search_space.skew_pct = ...
    cfg.calibration.skew_pct;

calibration.min_median_holdings = ...
    cfg.calibration.min_median_holdings;

calibration.objective = ...
    string(cfg.calibration.objective);

calibration.tie_breakers = ...
    configured_tie_breakers;

calibration.candidates = ...
    candidates;

calibration.ranked_candidates = ...
    ranked_candidates;

calibration.top_ranked_candidate_id = ...
    top_ranked.candidate_id;

calibration.top_ranked = ...
    top_ranked;

calibration.selected_candidate_id = ...
    selected.candidate_id;

calibration.selected_rank = ...
    selected.rank;

calibration.selected_cutoffs = ...
    selected_cutoffs;

calibration.selected = ...
    selected;

end


function validate_grid(values, name)
%VALIDATE_GRID Validate a percentile search grid.

assert( ...
    isnumeric(values) && ...
    isvector(values) && ...
    ~isempty(values) && ...
    all(isfinite(values)) && ...
    all(values >= 0) && ...
    all(values <= 100), ...
    'Calibration:InvalidSearchGrid', ...
    '%s must be a non-empty numeric vector between 0 and 100.', ...
    name);

assert( ...
    numel(unique(values)) == numel(values), ...
    'Calibration:DuplicateSearchGridValue', ...
    '%s contains duplicate percentile values.', ...
    name);

end


function validate_percentile(value, name)
%VALIDATE_PERCENTILE Validate a selected percentile.

assert( ...
    isnumeric(value) && ...
    isscalar(value) && ...
    isfinite(value) && ...
    value >= 0 && ...
    value <= 100, ...
    'Calibration:InvalidSelection', ...
    '%s must be a finite scalar between 0 and 100.', ...
    name);

end


function out = subset_universe(universe, mask)
%SUBSET_UNIVERSE Keep fields required by calibration.

out.portfolio_month = ...
    universe.portfolio_month(mask);

out.base_eligible = ...
    universe.base_eligible(mask,:);

out.market_cap = ...
    universe.market_cap(mask,:);

end


function out = subset_size_control(size_control, mask)
%SUBSET_SIZE_CONTROL Keep fields required by signal filtering.

out.portfolio_month = ...
    size_control.portfolio_month(mask);

out.bucket = ...
    size_control.bucket(mask,:);

out.n_buckets = ...
    size_control.n_buckets;

end


function out = subset_signal(signal, mask)
%SUBSET_SIGNAL Keep the common signal interface.

out.portfolio_month = ...
    signal.portfolio_month(mask);

out.value = ...
    signal.value(mask,:);

out.valid = ...
    signal.valid(mask,:);

end


function out = retain_final_portfolio(portfolios)
%RETAIN_FINAL_PORTFOLIO Keep the final strategy.

out.portfolio_month = ...
    portfolios.portfolio_month;

out.weights.final = ...
    portfolios.weights.final;

out.valid.final = ...
    portfolios.valid.final;

out.n_holdings.final = ...
    portfolios.n_holdings.final;

end