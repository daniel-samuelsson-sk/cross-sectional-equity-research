function performance = evaluate_performance(data, portfolios, calendar, cfg)
%EVALUATE_PERFORMANCE Evaluate realized portfolio performance and turnover.
%
% For each portfolio:
%
%   - maps target weights to realized monthly stock returns
%   - computes monthly portfolio total returns
%   - computes monthly excess returns
%   - computes drift-adjusted turnover
%   - reports performance summaries for:
%         full sample
%         calibration period
%         evaluation period
%
% IMPORTANT POINT-IN-TIME RULE:
%
% Target weights are fixed before portfolio-month returns are realized.
% If a security with positive weight subsequently has a missing realized
% return, the portfolio month is marked invalid.
%
% The function NEVER removes that security and renormalizes the remaining
% holdings using information that became known during the month.
%
% TURNOVER:
%
% Previous target weights are first drifted using realized asset returns:
%
%   w_pretrade(i,t) =
%       w_target(i,t-1) * (1 + r(i,t-1))
%       ---------------------------------
%       sum_j w_target(j,t-1) * (1 + r(j,t-1))
%
% Turnover is then:
%
%   0.5 * sum_i |w_target(i,t) - w_pretrade(i,t)|
%
% The first portfolio month has no prior portfolio and therefore has
% undefined turnover (NaN).

validate_research_data(data);


%% Validate configuration

assert( ...
    isfield(cfg, 'turnover') && ...
    isfield(cfg.turnover, 'method'), ...
    'Performance:MissingTurnoverConfiguration', ...
    'cfg.turnover.method is required.');

assert( ...
    string(cfg.turnover.method) == "drift_adjusted", ...
    'Performance:UnsupportedTurnoverMethod', ...
    'The current implementation requires drift-adjusted turnover.');


%% Validate calendar

required_calendar = { ...
    'portfolio_month', ...
    'phase'};

for k = 1:numel(required_calendar)

    assert( ...
        ismember( ...
            required_calendar{k}, ...
            calendar.Properties.VariableNames), ...
        'Performance:MissingCalendarField', ...
        'Calendar is missing required field: %s', ...
        required_calendar{k});

end

portfolio_month = ...
    calendar.portfolio_month(:);

M = ...
    height(calendar);

assert(M > 0, ...
    'Performance:EmptyCalendar', ...
    'Research calendar contains no portfolio months.');

assert( ...
    numel(unique(portfolio_month)) == M && ...
    issorted(portfolio_month), ...
    'Performance:InvalidCalendar', ...
    'Portfolio months must be unique and strictly increasing.');


%% Validate portfolio interface

assert(isfield(portfolios, 'portfolio_month'), ...
    'Performance:MissingPortfolioField', ...
    'portfolios.portfolio_month is required.');

assert(isfield(portfolios, 'weights'), ...
    'Performance:MissingPortfolioField', ...
    'portfolios.weights is required.');

assert(isfield(portfolios, 'valid'), ...
    'Performance:MissingPortfolioField', ...
    'portfolios.valid is required.');

assert(isfield(portfolios, 'n_holdings'), ...
    'Performance:MissingPortfolioField', ...
    'portfolios.n_holdings is required.');

assert( ...
    isequal( ...
        portfolios.portfolio_month(:), ...
        portfolio_month), ...
    'Performance:PortfolioCalendarMismatch', ...
    'Portfolio and research calendars must align.');

portfolio_names = ...
    fieldnames(portfolios.weights);

assert(~isempty(portfolio_names), ...
    'Performance:NoPortfolios', ...
    'No portfolio weight matrices were supplied.');


%% Align portfolio months to monthly realized returns

[has_month, monthly_index] = ...
    ismember( ...
        portfolio_month, ...
        data.monthly.dates(:));

assert(all(has_month), ...
    'Performance:MissingMonthlyReturns', ...
    'One or more portfolio months are absent from monthly return data.');

asset_returns = ...
    data.monthly.returns(monthly_index,:);

rf = ...
    data.monthly.rf(monthly_index);

N = ...
    numel(data.assets.id);

assert( ...
    size(asset_returns,2) == N, ...
    'Performance:AssetDimensionMismatch', ...
    'Monthly return matrix does not match the asset universe.');


%% Output metadata

performance.portfolio_month = ...
    portfolio_month;

performance.rf = ...
    rf;

performance.meta.return_frequency = ...
    "monthly";

performance.meta.annualization_factor = ...
    12;

performance.meta.turnover_method = ...
    "drift_adjusted";

performance.meta.missing_realized_return_policy = ...
    "invalidate_portfolio_month";

performance.meta.transaction_costs_included = ...
    false;


%% Evaluate every portfolio

for p = 1:numel(portfolio_names)

    name = ...
        portfolio_names{p};

    assert(isfield(portfolios.valid, name), ...
        'Performance:MissingPortfolioValidity', ...
        'Missing portfolios.valid.%s.', ...
        name);

    assert(isfield(portfolios.n_holdings, name), ...
        'Performance:MissingHoldingsCount', ...
        'Missing portfolios.n_holdings.%s.', ...
        name);

    weights = ...
        portfolios.weights.(name);

    target_valid = ...
        portfolios.valid.(name);

    n_holdings = ...
        portfolios.n_holdings.(name);


    %% Validate dimensions

    assert( ...
        isequal(size(weights), [M N]), ...
        'Performance:WeightDimensionMismatch', ...
        '%s weight matrix has incorrect dimensions.', ...
        name);

    assert( ...
        isequal(size(target_valid), [M 1]), ...
        'Performance:ValidityDimensionMismatch', ...
        '%s validity vector has incorrect dimensions.', ...
        name);

    assert(islogical(target_valid), ...
        'Performance:InvalidValidityType', ...
        '%s validity vector must be logical.', ...
        name);

    assert( ...
        isequal(size(n_holdings), [M 1]), ...
        'Performance:HoldingsDimensionMismatch', ...
        '%s holdings-count vector has incorrect dimensions.', ...
        name);


    %% Preallocate realized-return diagnostics

    portfolio_return = ...
        NaN(M,1);

    excess_return = ...
        NaN(M,1);

    valid_return = ...
        false(M,1);

    missing_held_returns = ...
        zeros(M,1);


    %% Compute realized monthly returns

    for t = 1:M

        if ~target_valid(t)
            continue;
        end

        w = ...
            weights(t,:);

        held = ...
            w > 0;

        assert(any(held), ...
            'Performance:ValidPortfolioHasNoHoldings', ...
            '%s is marked valid but has no positive portfolio weights.', ...
            name);

        r = ...
            asset_returns(t,held);

        missing_held_returns(t) = ...
            sum(~isfinite(r));

        % Crucial rule:
        % Do not remove securities with missing realized returns and
        % renormalize surviving holdings after the fact.
        if missing_held_returns(t) > 0
            continue;
        end

        portfolio_return(t) = ...
            sum( ...
                w(held) .* r);

        excess_return(t) = ...
            portfolio_return(t) - rf(t);

        valid_return(t) = ...
            true;

    end


    %% Drift-adjusted turnover

    turnover = ...
        NaN(M,1);

    turnover_valid = ...
        false(M,1);

    for t = 2:M

        % Turnover is meaningful only across consecutive portfolio months.
        if ~are_consecutive_months( ...
                portfolio_month(t-1), ...
                portfolio_month(t))
            continue;
        end

        if ~target_valid(t-1) || ...
           ~target_valid(t) || ...
           ~valid_return(t-1)
            continue;
        end

        previous_weights = ...
            weights(t-1,:);

        current_weights = ...
            weights(t,:);

        held_previously = ...
            previous_weights > 0;

        previous_asset_returns = ...
            asset_returns(t-1,held_previously);

        % valid_return(t-1) already guarantees these returns are finite.
        assert(all(isfinite(previous_asset_returns)), ...
            'Performance:InternalReturnValidityError', ...
            'Turnover encountered invalid previously held returns.');

        post_return_values = ...
            previous_weights(held_previously) .* ...
            (1 + previous_asset_returns);

        total_post_return_value = ...
            sum(post_return_values);

        % This could only fail if the entire previous portfolio lost 100%.
        if ~isfinite(total_post_return_value) || ...
           total_post_return_value <= 0
            continue;
        end

        drifted_weights = ...
            zeros(1,N);

        drifted_weights(held_previously) = ...
            post_return_values / total_post_return_value;

        turnover(t) = ...
            0.5 * sum( ...
                abs( ...
                    current_weights - ...
                    drifted_weights));

        turnover_valid(t) = ...
            true;

    end


    %% Integrity checks

    assert(all(isfinite(portfolio_return(valid_return))), ...
        'Performance:NonFinitePortfolioReturn', ...
        'Valid %s portfolio returns must be finite.', ...
        name);

    assert(all(isfinite(excess_return(valid_return))), ...
        'Performance:NonFiniteExcessReturn', ...
        'Valid %s excess returns must be finite.', ...
        name);

    assert(all( ...
        missing_held_returns(valid_return) == 0), ...
        'Performance:MissingReturnPolicyViolation', ...
        ['A %s portfolio month was marked valid despite a missing ' ...
         'realized return for a held security.'], ...
        name);

    assert(all( ...
        turnover(turnover_valid) >= 0), ...
        'Performance:NegativeTurnover', ...
        '%s turnover cannot be negative.', ...
        name);


    %% Store monthly series

    performance.returns.(name) = ...
        portfolio_return;

    performance.excess_returns.(name) = ...
        excess_return;

    performance.valid_return.(name) = ...
        valid_return;

    performance.missing_held_returns.(name) = ...
        missing_held_returns;

    performance.turnover.(name) = ...
        turnover;

    performance.turnover_valid.(name) = ...
        turnover_valid;


    %% Full-sample summary

    full_mask = ...
        true(M,1);

    performance.summary.full_sample.(name) = ...
        summarize_period( ...
            portfolio_month, ...
            portfolio_return, ...
            excess_return, ...
            valid_return, ...
            target_valid, ...
            turnover, ...
            turnover_valid, ...
            n_holdings, ...
            full_mask);


    %% Phase-specific summaries

    phases = ...
        unique(calendar.phase, 'stable');

    for q = 1:numel(phases)

        phase_name = ...
            phases(q);

        assert(phase_name ~= "", ...
            'Performance:UndefinedPhase', ...
            'Research calendar contains an undefined phase.');

        phase_field = ...
            matlab.lang.makeValidName(char(phase_name));

        phase_mask = ...
            calendar.phase == phase_name;

        performance.summary.(phase_field).(name) = ...
            summarize_period( ...
                portfolio_month, ...
                portfolio_return, ...
                excess_return, ...
                valid_return, ...
                target_valid, ...
                turnover, ...
                turnover_valid, ...
                n_holdings, ...
                phase_mask);

    end

end

end


function summary = summarize_period( ...
    portfolio_month, ...
    portfolio_return, ...
    excess_return, ...
    valid_return, ...
    target_valid, ...
    turnover, ...
    turnover_valid, ...
    n_holdings, ...
    mask)
%SUMMARIZE_PERIOD Compute strict performance statistics for one period.
%
% Return-based statistics are reported only when every requested portfolio
% month has a valid realized return. This prevents silently shortening the
% backtest after observing problematic months.

mask = ...
    logical(mask(:));

rows = ...
    find(mask);

assert(~isempty(rows), ...
    'Performance:EmptySummaryPeriod', ...
    'Cannot summarize an empty research period.');

n_months = ...
    numel(rows);

summary.start_date = ...
    portfolio_month(rows(1));

summary.end_date = ...
    portfolio_month(rows(end));

summary.n_months = ...
    n_months;

summary.n_valid_returns = ...
    sum(valid_return(mask));

summary.n_invalid_returns = ...
    n_months - summary.n_valid_returns;

summary.complete_return_series = ...
    all(valid_return(mask));

summary.n_valid_target_months = ...
    sum(target_valid(mask));


%% Holdings diagnostics

holdings_rows = ...
    mask & target_valid;

if any(holdings_rows)

    summary.average_holdings = ...
        mean(n_holdings(holdings_rows));

    summary.median_holdings = ...
        median(n_holdings(holdings_rows));

else

    summary.average_holdings = ...
        NaN;

    summary.median_holdings = ...
        NaN;

end


%% Return statistics
%
% Strict policy:
% no headline performance statistic is computed from a selectively
% shortened time series.

summary.annualized_total_return = ...
    NaN;

summary.cagr = ...
    NaN;

summary.annualized_volatility = ...
    NaN;

summary.annualized_excess_return = ...
    NaN;

summary.sharpe = ...
    NaN;

summary.maximum_drawdown = ...
    NaN;

if summary.complete_return_series

    r = ...
        portfolio_return(mask);

    ex = ...
        excess_return(mask);

    annualization = ...
        12;

    summary.annualized_total_return = ...
        annualization * mean(r);

    terminal_wealth = ...
        prod(1 + r);

    if terminal_wealth >= 0

        summary.cagr = ...
            terminal_wealth^(annualization / n_months) - 1;

    end

    monthly_volatility = ...
        std(r,0);

    summary.annualized_volatility = ...
        sqrt(annualization) * monthly_volatility;

    summary.annualized_excess_return = ...
        annualization * mean(ex);

    excess_volatility = ...
        std(ex,0);

    if isfinite(excess_volatility) && ...
       excess_volatility > 0

        summary.sharpe = ...
            sqrt(annualization) * ...
            mean(ex) / excess_volatility;

    end

    summary.maximum_drawdown = ...
        compute_maximum_drawdown(r);

end


%% Turnover summary

expected_transition = ...
    false(size(mask));

for t = 2:numel(mask)

    if ~mask(t) || ~mask(t-1)
        continue;
    end

    if are_consecutive_months( ...
            portfolio_month(t-1), ...
            portfolio_month(t))

        expected_transition(t) = ...
            true;

    end

end

summary.n_turnover_transitions = ...
    sum(expected_transition);

summary.n_valid_turnover_transitions = ...
    sum( ...
        turnover_valid & ...
        expected_transition);

summary.complete_turnover_series = ...
    all( ...
        turnover_valid(expected_transition));

summary.average_turnover = ...
    NaN;

if any(expected_transition) && ...
   summary.complete_turnover_series

    summary.average_turnover = ...
        mean(turnover(expected_transition));

end

end


function max_drawdown = compute_maximum_drawdown(returns)
%COMPUTE_MAXIMUM_DRAWDOWN Compute maximum drawdown from monthly returns.
%
% Output is expressed as a positive loss magnitude.

wealth = ...
    [1; cumprod(1 + returns(:))];

running_peak = ...
    cummax(wealth);

drawdown = ...
    wealth ./ running_peak - 1;

max_drawdown = ...
    -min(drawdown);

end


function tf = are_consecutive_months(previous_month, current_month)
%ARE_CONSECUTIVE_MONTHS Test whether two month-end dates are consecutive.

expected_current = ...
    dateshift( ...
        previous_month + calmonths(1), ...
        'end', ...
        'month');

tf = ...
    current_month == expected_current;

end