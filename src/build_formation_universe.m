function universe = build_formation_universe(data, calendar, cfg)
%BUILD_FORMATION_UNIVERSE Construct the point-in-time investable universe.
%
% An asset is base eligible for portfolio month t when:
%
%   1. the source identifies it as available at formation,
%   2. it satisfies the configured observed-history seasoning rule,
%   3. a valid positive point-in-time market capitalization is available
%      from the immediately preceding calendar month, and
%   4. it is not known to be non-common equity.
%
% An asset with unknown security type is not excluded solely because its
% security type is unknown.
%
% No realized return from portfolio month t is used.
%
% MARKET-CAP RULE
%
% Within the calendar month immediately preceding portfolio month t, the
% latest valid positive market-cap observation available by the
% information cutoff is used.
%
% HISTORY RULE
%
% cfg.universe.min_observed_history_months specifies the minimum number of
% completed calendar months since the asset was first observed as
% available in data.availability.
%
% Example:
%
%   first observed availability: January 2015
%   portfolio month:             January 2020
%
%   observed history = 60 months
%
% A value of zero disables the seasoning filter.
%
% IMPORTANT:
% "Observed history" is not necessarily identical to true listing age.
% A source dataset can be left-censored and begin after the security was
% originally listed.
%
% If cfg is omitted, default_config() is used.

validate_research_data(data);


%% Configuration

if nargin < 3 || isempty(cfg)

    cfg = ...
        default_config();

end

assert( ...
    isfield(cfg, 'universe') && ...
    isfield(cfg.universe, 'min_observed_history_months'), ...
    'FormationUniverse:MissingHistoryConfiguration', ...
    ['cfg.universe.min_observed_history_months ' ...
     'is required.']);

min_history = ...
    cfg.universe.min_observed_history_months;

assert( ...
    isnumeric(min_history) && ...
    isscalar(min_history) && ...
    isfinite(min_history) && ...
    min_history >= 0 && ...
    min_history == floor(min_history), ...
    'FormationUniverse:InvalidHistoryRequirement', ...
    'min_observed_history_months must be a non-negative integer.');


%% Validate calendar

required_calendar = { ...
    'portfolio_month', ...
    'information_cutoff'};

for k = 1:numel(required_calendar)

    assert( ...
        ismember( ...
            required_calendar{k}, ...
            calendar.Properties.VariableNames), ...
        'FormationUniverse:MissingCalendarField', ...
        'Calendar is missing required field: %s', ...
        required_calendar{k});

end

M = ...
    height(calendar);

N = ...
    numel(data.assets.id);

assert(M > 0, ...
    'FormationUniverse:EmptyCalendar', ...
    'Research calendar contains no portfolio months.');


%% Align source availability to portfolio months

[availability_found, availability_index] = ...
    ismember( ...
        calendar.portfolio_month(:), ...
        data.availability.dates(:));

assert(all(availability_found), ...
    'FormationUniverse:MissingAvailabilityDate', ...
    ['One or more research portfolio months are absent from ' ...
     'data.availability.dates.']);

source_available = ...
    data.availability.available(availability_index,:);

assert( ...
    isequal(size(source_available), [M N]), ...
    'FormationUniverse:AvailabilityDimensionMismatch', ...
    'Aligned availability matrix has incorrect dimensions.');


%% Determine first observed availability date
%
% This is deliberately based on the standard data contract rather than
% provider-specific listing metadata.

first_observed_available_date = ...
    NaT(1,N);

availability_dates = ...
    data.availability.dates(:);

for i = 1:N

    first_row = ...
        find( ...
            data.availability.available(:,i), ...
            1, ...
            'first');

    if ~isempty(first_row)

        first_observed_available_date(i) = ...
            availability_dates(first_row);

    end

end


%% Observed-history diagnostics

observed_history_months = ...
    NaN(M,N);

for t = 1:M

    portfolio_date = ...
        calendar.portfolio_month(t);

    portfolio_month_number = ...
        12 * year(portfolio_date) + ...
        month(portfolio_date);

    for i = 1:N

        first_date = ...
            first_observed_available_date(i);

        if isnat(first_date)
            continue;
        end

        first_month_number = ...
            12 * year(first_date) + ...
            month(first_date);

        history_months = ...
            portfolio_month_number - ...
            first_month_number;

        if history_months >= 0

            observed_history_months(t,i) = ...
                history_months;

        end

    end

end


%% Apply optional history-seasoning rule

if min_history == 0

    % Explicitly disabled. Assets with no historical observation are not
    % rejected here merely because this particular optional rule is off.
    % Current source availability and market-cap validity still apply.
    history_eligible = ...
        true(M,N);

else

    history_eligible = ...
        isfinite(observed_history_months) & ...
        observed_history_months >= min_history;

end


%% Identify left-censored history
%
% If an asset is already available in the first month of the source
% dataset, its true listing age may exceed the history observable here.

first_source_month = ...
    availability_dates(1);

history_left_censored = ...
    ~isnat(first_observed_available_date) & ...
    first_observed_available_date == first_source_month;


%% Point-in-time market capitalization

market_cap = ...
    NaN(M,N);

market_cap_date = ...
    NaT(M,N);

cap_dates = ...
    data.market_cap.dates(:);

cap_values = ...
    data.market_cap.values;

cap_valid = ...
    data.market_cap.valid;

for t = 1:M

    portfolio_month = ...
        calendar.portfolio_month(t);

    cutoff = ...
        calendar.information_cutoff(t);

    previous_month_start = ...
        dateshift( ...
            portfolio_month - calmonths(1), ...
            'start', ...
            'month');

    previous_month_end = ...
        dateshift( ...
            portfolio_month - calmonths(1), ...
            'end', ...
            'month');

    rows = find( ...
        cap_dates >= previous_month_start & ...
        cap_dates <= previous_month_end & ...
        cap_dates <= cutoff);

    if isempty(rows)
        continue;
    end

    for i = 1:N

        valid_rows = ...
            rows( ...
                cap_valid(rows,i) & ...
                isfinite(cap_values(rows,i)) & ...
                cap_values(rows,i) > 0);

        if isempty(valid_rows)
            continue;
        end

        % Latest valid point-in-time observation within the prior month.
        selected_row = ...
            valid_rows(end);

        market_cap(t,i) = ...
            cap_values(selected_row,i);

        market_cap_date(t,i) = ...
            cap_dates(selected_row);

    end

end


%% Base formation universe

valid_market_cap = ...
    isfinite(market_cap) & ...
    market_cap > 0 & ...
    ~isnat(market_cap_date);

security_type_eligible = ...
    data.assets.security_type ~= "non_common_equity";

base_eligible = ...
    source_available & ...
    history_eligible & ...
    valid_market_cap & ...
    security_type_eligible;


%% Integrity checks

assert(~any(base_eligible(~source_available)), ...
    'FormationUniverse:AvailabilityViolation', ...
    'An unavailable asset entered the formation universe.');

assert(~any(base_eligible(~history_eligible)), ...
    'FormationUniverse:HistoryViolation', ...
    'An asset failing the history rule entered the formation universe.');

assert(all(isfinite(market_cap(base_eligible))), ...
    'FormationUniverse:InvalidMarketCap', ...
    'Every eligible asset must have finite market capitalization.');

assert(all(market_cap(base_eligible) > 0), ...
    'FormationUniverse:InvalidMarketCap', ...
    'Every eligible asset must have positive market capitalization.');

for t = 1:M

    eligible = ...
        base_eligible(t,:);

    if ~any(eligible)
        continue;
    end

    dates_used = ...
        market_cap_date(t,eligible);

    cutoff = ...
        calendar.information_cutoff(t);

    previous_month = ...
        calendar.portfolio_month(t) - ...
        calmonths(1);

    assert(all(dates_used <= cutoff), ...
        'FormationUniverse:FutureMarketCap', ...
        'Formation universe used market capitalization after cutoff.');

    assert(all( ...
        year(dates_used) == year(previous_month) & ...
        month(dates_used) == month(previous_month)), ...
        'FormationUniverse:WrongMarketCapMonth', ...
        ['Formation market capitalization must come from the ' ...
         'immediately preceding calendar month.']);

end


%% Output

universe.portfolio_month = ...
    calendar.portfolio_month;

universe.information_cutoff = ...
    calendar.information_cutoff;

universe.source_available = ...
    source_available;

universe.first_observed_available_date = ...
    first_observed_available_date;

universe.observed_history_months = ...
    observed_history_months;

universe.history_eligible = ...
    history_eligible;

universe.history_left_censored = ...
    history_left_censored;

universe.min_observed_history_months = ...
    min_history;

universe.market_cap = ...
    market_cap;

universe.market_cap_date = ...
    market_cap_date;

universe.base_eligible = ...
    base_eligible;

universe.n_source_available = ...
    sum(source_available,2);

universe.n_history_eligible = ...
    sum(history_eligible,2);

universe.n_base_eligible = ...
    sum(base_eligible,2);

end