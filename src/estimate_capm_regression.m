function fit = estimate_capm_regression( ...
    portfolio_month, ...
    portfolio_excess_return, ...
    market_excess_return)
%ESTIMATE_CAPM_REGRESSION Estimate a monthly single-factor market model.
%
% Model:
%
%   portfolio_excess_return_t
%       = alpha + beta * market_excess_return_t + residual_t
%
% Point estimates are ordinary least squares.
%
% Inference uses a Newey-West HAC covariance estimator with Bartlett
% weights
%
%   w_l = 1 - l / (L + 1),    l = 1,...,L
%
% and deterministic lag rule
%
%   L = floor(4 * (T / 100)^(2/9)).
%
% No small-sample covariance correction or prewhitening is applied.
% Confidence intervals use the normal 97.5% critical value.
%
% CAPM residual variance uses sample normalization T-1.


%% Validate inputs

assert(isdatetime(portfolio_month), ...
    'CAPMRegression:InvalidDates', ...
    'portfolio_month must be a datetime vector.');

assert( ...
    isnumeric(portfolio_excess_return) && ...
    isreal(portfolio_excess_return) && ...
    isvector(portfolio_excess_return), ...
    'CAPMRegression:InvalidPortfolioReturn', ...
    'portfolio_excess_return must be a real numeric vector.');

assert( ...
    isnumeric(market_excess_return) && ...
    isreal(market_excess_return) && ...
    isvector(market_excess_return), ...
    'CAPMRegression:InvalidMarketReturn', ...
    'market_excess_return must be a real numeric vector.');


portfolio_month = ...
    portfolio_month(:);

y = ...
    portfolio_excess_return(:);

m = ...
    market_excess_return(:);


T = ...
    numel(portfolio_month);


assert(T >= 3, ...
    'CAPMRegression:InsufficientObservations', ...
    'At least three aligned monthly observations are required.');

assert( ...
    numel(y) == T && ...
    numel(m) == T, ...
    'CAPMRegression:DimensionMismatch', ...
    'Dates, portfolio excess returns and market excess returns must align.');

assert(~any(isnat(portfolio_month)), ...
    'CAPMRegression:MissingDate', ...
    'portfolio_month must not contain NaT values.');

assert( ...
    issorted(portfolio_month) && ...
    numel(unique(portfolio_month)) == T, ...
    'CAPMRegression:InvalidDateOrder', ...
    'portfolio_month must be unique and strictly increasing.');

assert( ...
    all( ...
        portfolio_month == ...
        dateshift(portfolio_month, 'end', 'month')), ...
    'CAPMRegression:DatesNotMonthEnd', ...
    'All regression dates must be month-end dates.');

assert( ...
    all(isfinite(y)) && ...
    all(isfinite(m)), ...
    'CAPMRegression:NonFiniteInput', ...
    'Regression inputs must be finite.');


month_index = ...
    12 .* year(portfolio_month) + ...
    month(portfolio_month);


assert( ...
    all(diff(month_index) == 1), ...
    'CAPMRegression:NonConsecutiveMonths', ...
    'Regression observations must be consecutive calendar months.');


%% OLS

X = ...
    [ ...
        ones(T,1), ...
        m];


assert(rank(X) == 2, ...
    'CAPMRegression:RankDeficientDesign', ...
    'The market excess return must have non-zero time-series variation.');


XtX = ...
    X' * X;


assert( ...
    rcond(XtX) > eps, ...
    'CAPMRegression:IllConditionedDesign', ...
    'The regression design is numerically singular.');


coefficient = ...
    X \ y;


alpha_monthly = ...
    coefficient(1);

beta = ...
    coefficient(2);


fitted_return = ...
    X * coefficient;

residual = ...
    y - fitted_return;


assert(all(isfinite(residual)), ...
    'CAPMRegression:NonFiniteResidual', ...
    'Regression residuals must be finite.');


%% Newey-West / Bartlett HAC covariance

hac_lag = ...
    floor( ...
        4 * ...
        (T / 100)^(2/9));


assert( ...
    hac_lag >= 0 && ...
    hac_lag < T, ...
    'CAPMRegression:InvalidHACLag', ...
    'The HAC lag must lie between zero and T-1.');


S = ...
    zeros(2,2);


for t = 1:T

    x_t = ...
        X(t,:)';

    S = ...
        S + ...
        residual(t)^2 .* ...
        (x_t * x_t');

end


for lag = 1:hac_lag

    bartlett_weight = ...
        1 - ...
        lag / (hac_lag + 1);


    lag_sum = ...
        zeros(2,2);


    for t = (lag + 1):T

        x_t = ...
            X(t,:)';

        x_t_minus_lag = ...
            X(t-lag,:)';


        lag_sum = ...
            lag_sum + ...
            residual(t) * ...
            residual(t-lag) .* ...
            (x_t * x_t_minus_lag');

    end


    S = ...
        S + ...
        bartlett_weight .* ...
        ( ...
            lag_sum + ...
            lag_sum');

end


XtX_inverse = ...
    XtX \ eye(2);


hac_covariance = ...
    XtX_inverse * ...
    S * ...
    XtX_inverse;


hac_covariance = ...
    0.5 .* ...
    ( ...
        hac_covariance + ...
        hac_covariance');


covariance_diagonal = ...
    diag(hac_covariance);


covariance_scale = ...
    max( ...
        [ ...
            abs(hac_covariance(:)); ...
            eps]);


roundoff_tolerance = ...
    100 * eps(covariance_scale);


assert( ...
    all( ...
        covariance_diagonal >= ...
        -roundoff_tolerance), ...
    'CAPMRegression:NegativeHACVariance', ...
    'The HAC covariance contains a materially negative variance estimate.');


hac_standard_error = ...
    sqrt( ...
        max( ...
            covariance_diagonal, ...
            0));


alpha_hac_se = ...
    hac_standard_error(1);

beta_hac_se = ...
    hac_standard_error(2);


%% Confidence intervals

critical_value = ...
    norminv( ...
        0.975, ...
        0, ...
        1);


alpha_monthly_hac_ci = ...
    [ ...
        alpha_monthly - ...
            critical_value * alpha_hac_se, ...
        alpha_monthly + ...
            critical_value * alpha_hac_se];


beta_hac_ci = ...
    [ ...
        beta - ...
            critical_value * beta_hac_se, ...
        beta + ...
            critical_value * beta_hac_se];


alpha_annualized = ...
    12 * ...
    alpha_monthly;


alpha_annualized_hac_ci = ...
    12 .* ...
    alpha_monthly_hac_ci;


%% R-squared

sst = ...
    sum( ...
        ( ...
            y - mean(y) ...
        ).^2);


sse = ...
    sum( ...
        residual.^2);


assert( ...
    isfinite(sst) && ...
    sst > 0, ...
    'CAPMRegression:ZeroPortfolioVariance', ...
    'Portfolio excess returns must have positive sample variation.');


r_squared = ...
    1 - ...
    sse / sst;


%% Sample-variance decomposition

portfolio_excess_variance = ...
    var(y,0);


market_excess_variance = ...
    var(m,0);


capm_residual_variance = ...
    var(residual,0);


market_beta_component_variance = ...
    beta^2 * ...
    market_excess_variance;


variance_identity_error = ...
    portfolio_excess_variance - ...
    market_beta_component_variance - ...
    capm_residual_variance;


variance_identity_tolerance = ...
    1e-12 + ...
    1e-10 * ...
    abs(portfolio_excess_variance);


assert( ...
    abs(variance_identity_error) <= ...
        variance_identity_tolerance, ...
    'CAPMRegression:VarianceIdentityFailure', ...
    ['Sample-variance identity failed: var(portfolio excess) must equal ' ...
     'beta^2*var(market excess) + var(CAPM residual).']);


capm_residual_volatility_annualized = ...
    sqrt(12) * ...
    sqrt(capm_residual_variance);


%% Output

fit = ...
    struct();


fit.start_date = ...
    portfolio_month(1);

fit.end_date = ...
    portfolio_month(end);

fit.n_months = ...
    T;


fit.alpha_monthly = ...
    alpha_monthly;

fit.alpha_hac_se = ...
    alpha_hac_se;

fit.alpha_monthly_hac_ci = ...
    alpha_monthly_hac_ci;

fit.alpha_annualized = ...
    alpha_annualized;

fit.alpha_annualized_hac_ci = ...
    alpha_annualized_hac_ci;


fit.beta = ...
    beta;

fit.beta_hac_se = ...
    beta_hac_se;

fit.beta_hac_ci = ...
    beta_hac_ci;


fit.r_squared = ...
    r_squared;


fit.capm_residual_volatility_annualized = ...
    capm_residual_volatility_annualized;


fit.portfolio_excess_variance = ...
    portfolio_excess_variance;

fit.market_excess_variance = ...
    market_excess_variance;

fit.market_beta_component_variance = ...
    market_beta_component_variance;

fit.capm_residual_variance = ...
    capm_residual_variance;

fit.variance_identity_error = ...
    variance_identity_error;

fit.variance_identity_tolerance = ...
    variance_identity_tolerance;


fit.hac_lag = ...
    hac_lag;

fit.hac_covariance = ...
    hac_covariance;

fit.hac_kernel = ...
    "Bartlett";

fit.hac_lag_rule = ...
    "floor(4*(T/100)^(2/9))";

fit.hac_small_sample_correction = ...
    false;

fit.hac_prewhitening_order = ...
    0;


fit.confidence_level = ...
    0.95;

fit.confidence_critical_value = ...
    critical_value;


fit.alpha_hac_ci_excludes_zero = ...
    alpha_monthly_hac_ci(1) > 0 || ...
    alpha_monthly_hac_ci(2) < 0;


fit.residuals = ...
    residual;

end