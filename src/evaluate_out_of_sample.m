function evaluation = evaluate_out_of_sample( ...
    data, ...
    calendar, ...
    universe, ...
    size_control, ...
    momentum, ...
    downside, ...
    idio_skew, ...
    calibration, ...
    cfg)
%EVALUATE_OUT_OF_SAMPLE Evaluate the frozen specification on holdout data.
%
% The specification recorded by calibration (calibration.selected_cutoffs)
% is held fixed and applied to portfolio months labelled "evaluation" in
% the research calendar.
%
% Evaluation-period workflow:
%
%   calibration.selected_cutoffs
%               ↓
%   apply_signal_filters
%               ↓
%   construct_portfolios
%               ↓
%   evaluate_performance
%
% No parameter selection takes place inside this function.
%
% IMPORTANT:
%   This function does not read cfg.selection directly. The specification
%   applied here is calibration.selected_cutoffs. calibrate_cutoffs records
%   that specification from cfg.selection after confirming that it is a
%   valid candidate in the configured grid.

validate_research_data(data);


%% Validate calibration result

assert(isfield(calibration, 'selected_cutoffs'), ...
    'OutOfSample:MissingCalibrationResult', ...
    'calibration.selected_cutoffs is required.');

selected_cutoffs = ...
    calibration.selected_cutoffs;

required_cutoffs = { ...
    'momentum_pct', ...
    'downside_pct', ...
    'skew_pct'};

for k = 1:numel(required_cutoffs)

    field = ...
        required_cutoffs{k};

    assert(isfield(selected_cutoffs, field), ...
        'OutOfSample:MissingCalibrationCutoff', ...
        'Missing calibrated cutoff: %s', ...
        field);

    value = ...
        selected_cutoffs.(field);

    assert( ...
        isnumeric(value) && ...
        isscalar(value) && ...
        isfinite(value) && ...
        value >= 0 && ...
        value <= 100, ...
        'OutOfSample:InvalidCalibrationCutoff', ...
        'Calibrated cutoff %s must be between 0 and 100.', ...
        field);

end


%% Validate calendar

assert( ...
    ismember( ...
        'portfolio_month', ...
        calendar.Properties.VariableNames), ...
    'OutOfSample:MissingCalendarField', ...
    'Calendar is missing portfolio_month.');

assert( ...
    ismember( ...
        'phase', ...
        calendar.Properties.VariableNames), ...
    'OutOfSample:MissingCalendarField', ...
    'Calendar is missing phase.');

evaluation_mask = ...
    calendar.phase == "evaluation";

assert(any(evaluation_mask), ...
    'OutOfSample:NoEvaluationMonths', ...
    'Research calendar contains no evaluation months.');

eval_calendar = ...
    calendar(evaluation_mask,:);

assert(all(eval_calendar.phase == "evaluation"), ...
    'OutOfSample:InvalidEvaluationPhase', ...
    'Evaluation subset contains non-evaluation observations.');


%% Confirm chronological separation from calibration

calibration_mask = ...
    calendar.phase == "calibration";

if any(calibration_mask)

    last_calibration_month = ...
        max(calendar.portfolio_month(calibration_mask));

    first_evaluation_month = ...
        min(eval_calendar.portfolio_month);

    assert( ...
        last_calibration_month < first_evaluation_month, ...
        'OutOfSample:PeriodOverlap', ...
        'Calibration and evaluation periods overlap.');

end


%% Hard evaluation-only subset
%
% From this point onward, calibration-period rows are absent from every
% research object passed to selection and portfolio construction.

eval_universe = ...
    subset_universe( ...
        universe, ...
        evaluation_mask);

eval_size_control = ...
    subset_size_control( ...
        size_control, ...
        evaluation_mask);

eval_momentum = ...
    subset_signal( ...
        momentum, ...
        evaluation_mask);

eval_downside = ...
    subset_signal( ...
        downside, ...
        evaluation_mask);

eval_idio_skew = ...
    subset_signal( ...
        idio_skew, ...
        evaluation_mask);


%% Validate alignment

assert( ...
    isequal( ...
        eval_universe.portfolio_month(:), ...
        eval_calendar.portfolio_month(:)), ...
    'OutOfSample:UniverseCalendarMismatch', ...
    'Evaluation universe does not align with evaluation calendar.');

assert( ...
    isequal( ...
        eval_size_control.portfolio_month(:), ...
        eval_calendar.portfolio_month(:)), ...
    'OutOfSample:SizeCalendarMismatch', ...
    'Evaluation size control does not align with evaluation calendar.');

assert( ...
    isequal( ...
        eval_momentum.portfolio_month(:), ...
        eval_calendar.portfolio_month(:)), ...
    'OutOfSample:SignalCalendarMismatch', ...
    'Momentum signal does not align with evaluation calendar.');

assert( ...
    isequal( ...
        eval_downside.portfolio_month(:), ...
        eval_calendar.portfolio_month(:)), ...
    'OutOfSample:SignalCalendarMismatch', ...
    'Downside signal does not align with evaluation calendar.');

assert( ...
    isequal( ...
        eval_idio_skew.portfolio_month(:), ...
        eval_calendar.portfolio_month(:)), ...
    'OutOfSample:SignalCalendarMismatch', ...
    'Idiosyncratic-skewness signal does not align with evaluation calendar.');


%% Apply frozen calibrated specification

selection = ...
    apply_signal_filters( ...
        eval_universe, ...
        eval_size_control, ...
        eval_momentum, ...
        eval_downside, ...
        eval_idio_skew, ...
        selected_cutoffs);


%% Construct all strategy variants and benchmarks

portfolios = ...
    construct_portfolios( ...
        eval_universe, ...
        selection, ...
        cfg);


%% Evaluate realized performance

performance = ...
    evaluate_performance( ...
        data, ...
        portfolios, ...
        eval_calendar, ...
        cfg);


%% Require evaluation summary

assert(isfield(performance.summary, 'evaluation'), ...
    'OutOfSample:MissingEvaluationSummary', ...
    'Performance engine did not produce an evaluation summary.');


%% Output

evaluation.period_start = ...
    eval_calendar.portfolio_month(1);

evaluation.period_end = ...
    eval_calendar.portfolio_month(end);

evaluation.n_months = ...
    height(eval_calendar);

evaluation.cutoffs = ...
    selected_cutoffs;

evaluation.calendar = ...
    eval_calendar;

evaluation.selection = ...
    selection;

evaluation.portfolios = ...
    portfolios;

evaluation.performance = ...
    performance;

evaluation.summary = ...
    performance.summary.evaluation;

end


function out = subset_universe(universe, mask)
%SUBSET_UNIVERSE Keep fields required by evaluation.

out.portfolio_month = ...
    universe.portfolio_month(mask);

out.base_eligible = ...
    universe.base_eligible(mask,:);

out.market_cap = ...
    universe.market_cap(mask,:);

end


function out = subset_size_control(size_control, mask)
%SUBSET_SIZE_CONTROL Keep fields required by signal filtering.

out.portfolio_month = ...
    size_control.portfolio_month(mask);

out.bucket = ...
    size_control.bucket(mask,:);

out.n_buckets = ...
    size_control.n_buckets;

end


function out = subset_signal(signal, mask)
%SUBSET_SIGNAL Keep the common signal interface.

out.portfolio_month = ...
    signal.portfolio_month(mask);

out.value = ...
    signal.value(mask,:);

out.valid = ...
    signal.valid(mask,:);

end