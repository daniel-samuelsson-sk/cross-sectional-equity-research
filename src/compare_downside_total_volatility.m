function r1 = compare_downside_total_volatility(data, research)
%COMPARE_DOWNSIDE_TOTAL_VOLATILITY
% Compare downside deviation with ordinary total volatility.
%
% r1 = COMPARE_DOWNSIDE_TOTAL_VOLATILITY(data, research)
%
% PURPOSE
%
% Test whether the downside-deviation screen provides economically
% distinct information relative to ordinary total volatility.
%
% The function reuses the completed research pipeline. It does not
% recompute momentum, downside deviation, idiosyncratic skewness,
% calibration, the universe, or the research calendar.
%
% R1 constructs:
%
%   MOM + DD
%   MOM + sigma
%   DD only
%   sigma only
%
% and exposes a common OOS return panel used by the bootstrap and CAPM
% analyses:
%
%   MOM
%   MOM + DD
%   FINAL
%   EW
%   VW
%   MOM + sigma
%   DD only
%   sigma only
%
% The function also computes monthly cross-sectional Spearman rank
% correlation between downside deviation and total volatility among
% base-eligible stocks for which both signals are valid.


%% Validate inputs

assert(isstruct(data), ...
    'R1:InvalidData', ...
    'data must be a research-data struct.');

assert(isstruct(research), ...
    'R1:InvalidResearch', ...
    'research must be the output of run_research_pipeline.');

required_research_fields = { ...
    'config', ...
    'calendar', ...
    'universe', ...
    'size_control', ...
    'signals', ...
    'calibration', ...
    'evaluation'};

for k = 1:numel(required_research_fields)

    field = ...
        required_research_fields{k};

    assert(isfield(research, field), ...
        'R1:MissingResearchField', ...
        'research.%s is required.', ...
        field);

end

assert(isfield(research.signals, 'momentum'), ...
    'R1:MissingMomentum', ...
    'research.signals.momentum is required.');

assert(isfield(research.signals, 'downside'), ...
    'R1:MissingDownside', ...
    'research.signals.downside is required.');

assert(isfield(research.signals, 'idio_skew'), ...
    'R1:MissingIdioSkew', ...
    'research.signals.idio_skew is required.');


cfg = ...
    research.config;

calendar = ...
    research.calendar;

universe = ...
    research.universe;

size_control = ...
    research.size_control;

momentum = ...
    research.signals.momentum;

downside = ...
    research.signals.downside;

idio_skew = ...
    research.signals.idio_skew;


%% Require selected specification

assert(isfield(research.calibration, 'selected_cutoffs'), ...
    'R1:MissingSelectedCutoffs', ...
    'research.calibration.selected_cutoffs is required.');

selected_cutoffs = ...
    research.calibration.selected_cutoffs;

%% Compute total volatility

sigma = ...
    compute_total_volatility( ...
        data, ...
        calendar, ...
        cfg);


%% Require exact DD / sigma timing and coverage equivalence
%
% DD and sigma must differ only in the statistic applied to the same
% daily excess-return observations.

assert( ...
    isequal( ...
        sigma.portfolio_month, ...
        downside.portfolio_month), ...
    'R1:SignalMonthMismatch', ...
    'Total volatility and downside deviation use different months.');

assert( ...
    isequal( ...
        sigma.window_start, ...
        downside.window_start), ...
    'R1:WindowStartMismatch', ...
    'Total volatility and downside deviation use different window starts.');

assert( ...
    isequal( ...
        sigma.window_end, ...
        downside.window_end), ...
    'R1:WindowEndMismatch', ...
    'Total volatility and downside deviation use different window ends.');

assert( ...
    isequal( ...
        sigma.n_expected_observations, ...
        downside.n_expected_observations), ...
    'R1:ExpectedObservationMismatch', ...
    'Total volatility and downside deviation expect different observations.');

assert( ...
    isequal( ...
        sigma.min_required_observations, ...
        downside.min_required_observations), ...
    'R1:MinimumObservationMismatch', ...
    'Total volatility and downside deviation use different coverage thresholds.');

assert( ...
    isequal( ...
        sigma.n_observations, ...
        downside.n_observations), ...
    'R1:ObservationCountMismatch', ...
    ['Total volatility and downside deviation must use the same ' ...
     'daily excess-return observations.']);

assert( ...
    isequal( ...
        sigma.valid, ...
        downside.valid), ...
    'R1:ValidityMismatch', ...
    ['Total volatility and downside deviation must have identical ' ...
     'signal validity.']);


%% Re-run calibration-selected specification
%
% Re-evaluating the selected specification verifies that the supplied
% research components reproduce the pipeline evaluation exactly.

baseline_reinjected = ...
    evaluate_out_of_sample( ...
        data, ...
        calendar, ...
        universe, ...
        size_control, ...
        momentum, ...
        downside, ...
        idio_skew, ...
        research.calibration, ...
        cfg);

assert( ...
    isequaln( ...
        baseline_reinjected.performance.returns, ...
        research.evaluation.performance.returns), ...
    'R1:ReinjectionReturnParityFailure', ...
    'Re-injected baseline returns differ from the pipeline evaluation.');

assert( ...
    isequaln( ...
        baseline_reinjected.performance.excess_returns, ...
        research.evaluation.performance.excess_returns), ...
    'R1:ReinjectionExcessReturnParityFailure', ...
    'Re-injected baseline excess returns differ from the pipeline evaluation.');

assert( ...
    isequaln( ...
        baseline_reinjected.summary, ...
        research.evaluation.summary), ...
    'R1:ReinjectionSummaryParityFailure', ...
    'Re-injected baseline summary differs from the pipeline evaluation.');


%% R1 cutoff specifications
%
% skew_pct = 100 prevents the skew screen from affecting the
% momentum_downside portfolio. R1 always reads the intended intermediate
% portfolio rather than FINAL.
%
% momentum_pct = 0 removes the momentum threshold while retaining the
% existing valid-momentum/history eligibility requirement.

cut_mom_dd = ...
    struct( ...
        'momentum_pct', selected_cutoffs.momentum_pct, ...
        'downside_pct', selected_cutoffs.downside_pct, ...
        'skew_pct', 100);

cut_mom_sigma = ...
    cut_mom_dd;

cut_dd_only = ...
    struct( ...
        'momentum_pct', 0, ...
        'downside_pct', selected_cutoffs.downside_pct, ...
        'skew_pct', 100);

cut_sigma_only = ...
    cut_dd_only;


%% Evaluate MOM + DD

cal_mom_dd = ...
    struct();

cal_mom_dd.selected_cutoffs = ...
    cut_mom_dd;

eval_mom_dd = ...
    evaluate_out_of_sample( ...
        data, ...
        calendar, ...
        universe, ...
        size_control, ...
        momentum, ...
        downside, ...
        idio_skew, ...
        cal_mom_dd, ...
        cfg);


%% Verify explicit cutoff injection
%
% The cutoff object with the skew screen switched off must reproduce
% the selected-specification MOM and MOM+DD portfolios exactly. This
% verifies the cutoff-injection route used by the control variants.

assert( ...
    isequaln( ...
        eval_mom_dd.performance.returns.momentum, ...
        research.evaluation.performance.returns.momentum) && ...
    isequaln( ...
        eval_mom_dd.performance.excess_returns.momentum, ...
        research.evaluation.performance.excess_returns.momentum) && ...
    isequaln( ...
        eval_mom_dd.summary.momentum, ...
        research.evaluation.summary.momentum), ...
    'R1:MomentumInjectionParityFailure', ...
    ['Explicit cutoff injection with the skew screen off does not reproduce the ' ...
     'pipeline MOM portfolio exactly.']);

assert( ...
    isequaln( ...
        eval_mom_dd.performance.returns.momentum_downside, ...
        research.evaluation.performance.returns.momentum_downside) && ...
    isequaln( ...
        eval_mom_dd.performance.excess_returns.momentum_downside, ...
        research.evaluation.performance.excess_returns.momentum_downside) && ...
    isequaln( ...
        eval_mom_dd.summary.momentum_downside, ...
        research.evaluation.summary.momentum_downside), ...
    'R1:MomentumDownsideInjectionParityFailure', ...
    ['Explicit cutoff injection with the skew screen off does not reproduce the ' ...
     'pipeline MOM+DD portfolio exactly.']);


%% Evaluate MOM + sigma

cal_mom_sigma = ...
    struct();

cal_mom_sigma.selected_cutoffs = ...
    cut_mom_sigma;

eval_mom_sigma = ...
    evaluate_out_of_sample( ...
        data, ...
        calendar, ...
        universe, ...
        size_control, ...
        momentum, ...
        sigma, ...
        idio_skew, ...
        cal_mom_sigma, ...
        cfg);


%% Evaluate DD only

cal_dd_only = ...
    struct();

cal_dd_only.selected_cutoffs = ...
    cut_dd_only;

eval_dd_only = ...
    evaluate_out_of_sample( ...
        data, ...
        calendar, ...
        universe, ...
        size_control, ...
        momentum, ...
        downside, ...
        idio_skew, ...
        cal_dd_only, ...
        cfg);


%% Evaluate sigma only

cal_sigma_only = ...
    struct();

cal_sigma_only.selected_cutoffs = ...
    cut_sigma_only;

eval_sigma_only = ...
    evaluate_out_of_sample( ...
        data, ...
        calendar, ...
        universe, ...
        size_control, ...
        momentum, ...
        sigma, ...
        idio_skew, ...
        cal_sigma_only, ...
        cfg);


%% Common OOS calendar

oos_months = ...
    baseline_reinjected.performance.portfolio_month;

assert( ...
    isequal( ...
        eval_mom_dd.performance.portfolio_month, ...
        oos_months) && ...
    isequal( ...
        eval_mom_sigma.performance.portfolio_month, ...
        oos_months) && ...
    isequal( ...
        eval_dd_only.performance.portfolio_month, ...
        oos_months) && ...
    isequal( ...
        eval_sigma_only.performance.portfolio_month, ...
        oos_months), ...
    'R1:EvaluationCalendarMismatch', ...
    'R1 variants do not share the same OOS calendar.');


%% Common return panel
%
% The panel provides date-aligned total-return and excess-return series
% for the bootstrap and CAPM analyses.

series = ...
    struct();

series.portfolio_month = ...
    oos_months;


%% Selected-specification series

series.mom = ...
    extract_series( ...
        baseline_reinjected.performance, ...
        'momentum');

series.mom_dd = ...
    extract_series( ...
        baseline_reinjected.performance, ...
        'momentum_downside');

series.final = ...
    extract_series( ...
        baseline_reinjected.performance, ...
        'final');

series.ew = ...
    extract_series( ...
        baseline_reinjected.performance, ...
        'equal_weight');

series.vw = ...
    extract_series( ...
        baseline_reinjected.performance, ...
        'value_weight');


%% R1 control series
%
% All three controls are read from momentum_downside. In particular,
% p0 removes the momentum threshold but does not turn the output field
% "momentum" into a DD-only or sigma-only portfolio.

series.mom_sigma = ...
    extract_series( ...
        eval_mom_sigma.performance, ...
        'momentum_downside');

series.dd_only = ...
    extract_series( ...
        eval_dd_only.performance, ...
        'momentum_downside');

series.sigma_only = ...
    extract_series( ...
        eval_sigma_only.performance, ...
        'momentum_downside');


%% Require complete return panel
%
% Every strategy must provide finite total and excess returns on the
% common OOS calendar.

series_names = { ...
    'mom', ...
    'mom_dd', ...
    'final', ...
    'ew', ...
    'vw', ...
    'mom_sigma', ...
    'dd_only', ...
    'sigma_only'};

for k = 1:numel(series_names)

    name = ...
        series_names{k};

    assert( ...
        numel(series.(name).returns) == numel(oos_months) && ...
        numel(series.(name).excess_returns) == numel(oos_months), ...
        'R1:SeriesLengthMismatch', ...
        'R1 series %s does not match the common OOS calendar.', ...
        name);

    assert( ...
        all(isfinite(series.(name).returns(:))), ...
        'R1:NonFiniteReturns', ...
        'R1 series %s contains non-finite total returns.', ...
        name);

    assert( ...
        all(isfinite(series.(name).excess_returns(:))), ...
        'R1:NonFiniteExcessReturns', ...
        'R1 series %s contains non-finite excess returns.', ...
        name);

end


%% Cross-sectional Spearman rank correlation
%
% Population for each OOS month:
%
%   base_eligible
%   AND downside.valid
%   AND sigma.valid
%
% Correlation is computed over the entire cross-section, not separately
% within size buckets.

evaluation_mask = ...
    calendar.phase == "evaluation";

evaluation_months = ...
    calendar.portfolio_month(evaluation_mask);

assert( ...
    isequal( ...
        evaluation_months, ...
        oos_months), ...
    'R1:SpearmanDateAlignmentMismatch', ...
    ['Evaluation months used for the DD/sigma rank correlation do not ' ...
     'match the common OOS return-panel dates.']);

oos_universe = ...
    universe.base_eligible(evaluation_mask,:);

oos_downside_value = ...
    downside.value(evaluation_mask,:);

oos_downside_valid = ...
    downside.valid(evaluation_mask,:);

oos_sigma_value = ...
    sigma.value(evaluation_mask,:);

oos_sigma_valid = ...
    sigma.valid(evaluation_mask,:);

assert( ...
    size(oos_universe,1) == numel(oos_months), ...
    'R1:SpearmanCalendarMismatch', ...
    'OOS universe does not align with the return panel.');

n_oos = ...
    numel(oos_months);

rank_correlation = ...
    NaN(n_oos,1);

rank_n = ...
    zeros(n_oos,1);


for t = 1:n_oos

    eligible = ...
        oos_universe(t,:) & ...
        oos_downside_valid(t,:) & ...
        oos_sigma_valid(t,:);

    rank_n(t) = ...
        nnz(eligible);

    assert(rank_n(t) >= 2, ...
        'R1:InsufficientRankObservations', ...
        ['Fewer than two stocks are available for DD/sigma rank ' ...
         'correlation in %s.'], ...
        string(oos_months(t)));

    dd_values = ...
        oos_downside_value(t,eligible).';

    sigma_values = ...
        oos_sigma_value(t,eligible).';

    rank_correlation(t) = ...
        corr( ...
            dd_values, ...
            sigma_values, ...
            'Type', ...
            'Spearman');

end


assert(all(isfinite(rank_correlation)), ...
    'R1:InvalidRankCorrelation', ...
    'One or more monthly DD/sigma rank correlations are non-finite.');

mean_rank_correlation = ...
    mean(rank_correlation);


rank_table = ...
    table( ...
        oos_months, ...
        rank_n, ...
        rank_correlation, ...
        'VariableNames', { ...
            'portfolio_month', ...
            'n_stocks', ...
            'spearman_rho'});


%% Performance comparison

variant_name = [ ...
    "MOM+DD"; ...
    "MOM+sigma"; ...
    "DD-only"; ...
    "sigma-only"];

summary_mom_dd = ...
    eval_mom_dd.summary.momentum_downside;

summary_mom_sigma = ...
    eval_mom_sigma.summary.momentum_downside;

summary_dd_only = ...
    eval_dd_only.summary.momentum_downside;

summary_sigma_only = ...
    eval_sigma_only.summary.momentum_downside;

summary_structs = { ...
    summary_mom_dd; ...
    summary_mom_sigma; ...
    summary_dd_only; ...
    summary_sigma_only};

n_variants = ...
    numel(summary_structs);

sharpe = ...
    NaN(n_variants,1);

cagr = ...
    NaN(n_variants,1);

annualized_volatility = ...
    NaN(n_variants,1);

maximum_drawdown = ...
    NaN(n_variants,1);

average_turnover = ...
    NaN(n_variants,1);

average_holdings = ...
    NaN(n_variants,1);

median_holdings = ...
    NaN(n_variants,1);


for k = 1:n_variants

    s = ...
        summary_structs{k};

    sharpe(k) = ...
        s.sharpe;

    cagr(k) = ...
        s.cagr;

    annualized_volatility(k) = ...
        s.annualized_volatility;

    maximum_drawdown(k) = ...
        s.maximum_drawdown;

    average_turnover(k) = ...
        s.average_turnover;

    average_holdings(k) = ...
        s.average_holdings;

    median_holdings(k) = ...
        s.median_holdings;

end


summary_table = ...
    table( ...
        variant_name, ...
        sharpe, ...
        cagr, ...
        annualized_volatility, ...
        maximum_drawdown, ...
        average_turnover, ...
        average_holdings, ...
        median_holdings, ...
        'VariableNames', { ...
            'variant', ...
            'sharpe', ...
            'cagr', ...
            'annualized_volatility', ...
            'maximum_drawdown', ...
            'average_turnover', ...
            'average_holdings', ...
            'median_holdings'});


%% Structured output

r1 = ...
    struct();

r1.signal = ...
    struct();

r1.signal.sigma = ...
    sigma;

r1.series = ...
    series;

r1.summary = ...
    summary_table;

r1.rank_correlation = ...
    struct();

r1.rank_correlation.monthly = ...
    rank_table;

r1.rank_correlation.mean = ...
    mean_rank_correlation;


%% Method metadata

r1.meta = ...
    struct();

r1.meta.analysis = ...
    "R1 - downside deviation versus total volatility";

r1.meta.sigma_definition = ...
    "Sample standard deviation of daily excess returns using N-1.";

r1.meta.common_signal_configuration = ...
    "cfg.signals.downside";

end


function series = extract_series(performance, portfolio_name)
%EXTRACT_SERIES Extract paired total- and excess-return series.

assert(isfield(performance.returns, portfolio_name), ...
    'R1:MissingReturnSeries', ...
    'Missing return series: %s.', ...
    portfolio_name);

assert(isfield(performance.excess_returns, portfolio_name), ...
    'R1:MissingExcessReturnSeries', ...
    'Missing excess-return series: %s.', ...
    portfolio_name);

series = ...
    struct();

series.returns = ...
    performance.returns.(portfolio_name);

series.excess_returns = ...
    performance.excess_returns.(portfolio_name);

end