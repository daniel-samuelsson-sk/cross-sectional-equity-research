function ff = load_fama_french_monthly_market(csv_file, portfolio_month)
%LOAD_FAMA_FRENCH_MONTHLY_MARKET Load monthly market and RF factors.
%
% ff = LOAD_FAMA_FRENCH_MONTHLY_MARKET(csv_file, portfolio_month)
%
% Reads the monthly section of the Kenneth French Fama/French 3 Factors
% CSV file as text. Only rows whose first field is a six-digit YYYYMM
% value are treated as monthly observations.
%
% The function returns only the fields required for the CAPM analysis:
%
%   Mkt-RF
%   RF
%
% Source values are reported in percent and are converted to decimals.
% Monthly observations are converted to month-end dates and aligned
% explicitly to portfolio_month.
%
% Portfolio months must be consecutive month-end dates.


%% Validate inputs

assert( ...
    ischar(csv_file) || ...
    (isstring(csv_file) && isscalar(csv_file)), ...
    'FamaFrenchMonthly:InvalidFilePath', ...
    'csv_file must be a character vector or scalar string.');

csv_file = ...
    string(csv_file);

assert(isfile(csv_file), ...
    'FamaFrenchMonthly:MissingFile', ...
    'Fama-French factor file not found: %s', ...
    csv_file);


assert(isdatetime(portfolio_month), ...
    'FamaFrenchMonthly:InvalidPortfolioMonth', ...
    'portfolio_month must be a datetime vector.');

portfolio_month = ...
    portfolio_month(:);

assert(~any(isnat(portfolio_month)), ...
    'FamaFrenchMonthly:MissingPortfolioMonth', ...
    'portfolio_month must not contain NaT values.');

assert( ...
    all( ...
        portfolio_month == ...
        dateshift(portfolio_month, 'end', 'month')), ...
    'FamaFrenchMonthly:PortfolioMonthNotMonthEnd', ...
    'All portfolio months must be month-end dates.');


portfolio_month_index = ...
    12 .* year(portfolio_month) + ...
    month(portfolio_month);

assert( ...
    all(diff(portfolio_month_index) == 1), ...
    'FamaFrenchMonthly:NonConsecutivePortfolioMonths', ...
    'Portfolio months must be consecutive.');

%% Read raw text

raw_text = ...
    fileread(char(csv_file));

lines = ...
    splitlines(string(raw_text));

assert(~isempty(lines), ...
    'FamaFrenchMonthly:EmptyFile', ...
    'The Fama-French factor file is empty.');


%% Extract source-version line

creation_line = ...
    "";

n_creation_lines = ...
    0;


for k = 1:numel(lines)

    line = ...
        strtrim(lines(k));

    if startsWith( ...
            line, ...
            "This file was created using the ") && ...
       endsWith( ...
            line, ...
            " CRSP database.")

        creation_line = ...
            line;

        n_creation_lines = ...
            n_creation_lines + 1;

    end

end


assert(n_creation_lines <= 1, ...
    'FamaFrenchMonthly:CreationLineNotUnique', ...
    'Expected at most one CRSP creation/version line.');


%% Validate factor header

header_line = ...
    "";

header_found = ...
    false;


for k = 1:numel(lines)

    fields = ...
        strtrim( ...
            split(lines(k), ","));

    if numel(fields) == 5 && ...
       fields(1) == "" && ...
       fields(2) == "Mkt-RF" && ...
       fields(3) == "SMB" && ...
       fields(4) == "HML" && ...
       fields(5) == "RF"

        header_line = ...
            strtrim(lines(k));

        header_found = ...
            true;

        break

    end

end


assert(header_found, ...
    'FamaFrenchMonthly:MissingHeader', ...
    ['Expected factor header ",Mkt-RF,SMB,HML,RF" was not found.']);


%% Parse six-digit YYYYMM rows only

max_rows = ...
    numel(lines);

yyyymm = ...
    NaN(max_rows,1);

mkt_rf_pct = ...
    NaN(max_rows,1);

rf_pct = ...
    NaN(max_rows,1);

n_monthly_rows = ...
    0;


for k = 1:numel(lines)

    fields = ...
        strtrim( ...
            split(lines(k), ","));

    if isempty(fields)
        continue
    end


    first_field = ...
        fields(1);


    is_monthly_row = ...
        ~isempty( ...
            regexp( ...
                char(first_field), ...
                '^\d{6}$', ...
                'once'));


    if ~is_monthly_row
        continue
    end


    assert(numel(fields) == 5, ...
        'FamaFrenchMonthly:MalformedMonthlyRow', ...
        'A YYYYMM row does not contain exactly five comma-separated fields.');


    n_monthly_rows = ...
        n_monthly_rows + 1;


    yyyymm(n_monthly_rows) = ...
        str2double(first_field);

    mkt_rf_pct(n_monthly_rows) = ...
        str2double(fields(2));

    rf_pct(n_monthly_rows) = ...
        str2double(fields(5));

end


assert(n_monthly_rows > 0, ...
    'FamaFrenchMonthly:NoMonthlyRows', ...
    'No six-digit YYYYMM factor rows were found.');


yyyymm = ...
    yyyymm(1:n_monthly_rows);

mkt_rf_pct = ...
    mkt_rf_pct(1:n_monthly_rows);

rf_pct = ...
    rf_pct(1:n_monthly_rows);


%% Validate parsed monthly block

assert( ...
    all(isfinite(yyyymm)), ...
    'FamaFrenchMonthly:InvalidDateCode', ...
    'At least one monthly YYYYMM value is invalid.');

assert( ...
    all(isfinite(mkt_rf_pct)) && ...
    all(isfinite(rf_pct)), ...
    'FamaFrenchMonthly:NonFiniteFactorValue', ...
    'Monthly Mkt-RF and RF values must be finite.');


missing_value = ...
    -99.99;

assert( ...
    all(mkt_rf_pct ~= missing_value) && ...
    all(rf_pct ~= missing_value), ...
    'FamaFrenchMonthly:MissingFactorValue', ...
    'Monthly Mkt-RF or RF contains the -99.99 missing-value code.');


year_value = ...
    floor(yyyymm ./ 100);

month_value = ...
    mod(yyyymm,100);


assert( ...
    all(month_value >= 1 & month_value <= 12), ...
    'FamaFrenchMonthly:InvalidMonth', ...
    'At least one YYYYMM row contains an invalid month.');


monthly_dates = ...
    datetime( ...
        year_value, ...
        month_value, ...
        ones(n_monthly_rows,1));

monthly_dates = ...
    dateshift( ...
        monthly_dates, ...
        'end', ...
        'month');


assert( ...
    numel(unique(monthly_dates)) == ...
        n_monthly_rows, ...
    'FamaFrenchMonthly:DuplicateMonthlyDate', ...
    'The monthly factor block contains duplicate dates.');


full_month_index = ...
    12 .* year(monthly_dates) + ...
    month(monthly_dates);

assert( ...
    all(diff(full_month_index) == 1), ...
    'FamaFrenchMonthly:NonConsecutiveMonthlyBlock', ...
    'The parsed monthly factor block is not consecutive.');


%% Align explicitly to OOS portfolio months

[month_found, factor_row] = ...
    ismember( ...
        portfolio_month, ...
        monthly_dates);


assert(all(month_found), ...
    'FamaFrenchMonthly:MissingOOSMonth', ...
    'At least one OOS portfolio month is absent from the factor file.');


aligned_mkt_rf_pct = ...
    mkt_rf_pct(factor_row);

aligned_rf_pct = ...
    rf_pct(factor_row);


assert( ...
    all(isfinite(aligned_mkt_rf_pct)) && ...
    all(isfinite(aligned_rf_pct)), ...
    'FamaFrenchMonthly:NonFiniteAlignedFactor', ...
    'All aligned factor observations must be finite.');


%% Convert percent to decimal

mkt_rf = ...
    aligned_mkt_rf_pct ./ 100;

rf = ...
    aligned_rf_pct ./ 100;


conversion_tolerance = ...
    1e-12;

assert( ...
    max(abs(100 .* mkt_rf - aligned_mkt_rf_pct)) <= ...
        conversion_tolerance && ...
    max(abs(100 .* rf - aligned_rf_pct)) <= ...
        conversion_tolerance, ...
    'FamaFrenchMonthly:UnitConversionFailure', ...
    'Factor values were not converted from percent to decimal correctly.');


%% Output

ff = ...
    struct();

ff.portfolio_month = ...
    portfolio_month;

ff.mkt_rf = ...
    mkt_rf;

ff.rf = ...
    rf;


ff.meta = ...
    struct();

ff.meta.source = ...
    "Kenneth French Data Library";

ff.meta.source_dataset = ...
    "Fama/French 3 Factors";

if n_creation_lines == 1

    ff.meta.creation_line = ...
        creation_line;

end

ff.meta.header_line = ...
    header_line;

ff.meta.input_units = ...
    "percent";

ff.meta.output_units = ...
    "decimal";

ff.meta.n_file_months = ...
    n_monthly_rows;

ff.meta.file_start_month = ...
    monthly_dates(1);

ff.meta.file_end_month = ...
    monthly_dates(end);

ff.meta.n_oos_months = ...
    numel(portfolio_month);

ff.meta.oos_start_month = ...
    portfolio_month(1);

ff.meta.oos_end_month = ...
    portfolio_month(end);

end