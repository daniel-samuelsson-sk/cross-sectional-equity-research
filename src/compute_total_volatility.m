function sigma = compute_total_volatility(data, calendar, cfg)
%COMPUTE_TOTAL_VOLATILITY Compute total volatility on daily excess returns.
%
% sigma = COMPUTE_TOTAL_VOLATILITY(data, calendar, cfg)
%
% Computes total volatility as the sample standard deviation of daily
% excess returns.
%
% The signal uses exactly the same:
%
%   - daily excess returns
%   - signal window
%   - lag convention
%   - minimum coverage rule
%
% as the downside-deviation signal. This isolates the choice of risk
% statistic while keeping the underlying observations and timing fixed.
%
% Parameters are read from cfg.signals.downside so that downside
% deviation and total volatility are constructed on identical windows
% and under identical coverage requirements.


validate_research_data(data);


%% Validate configuration

assert( ...
    isfield(cfg, 'signals') && ...
    isfield(cfg.signals, 'downside'), ...
    'TotalVolatility:MissingConfiguration', ...
    'cfg.signals.downside is required.');

vol_cfg = ...
    cfg.signals.downside;

required_cfg = { ...
    'start_lag_months', ...
    'end_lag_months', ...
    'min_coverage'};

for k = 1:numel(required_cfg)

    assert(isfield(vol_cfg, required_cfg{k}), ...
        'TotalVolatility:MissingConfiguration', ...
        'Missing downside configuration field: %s', ...
        required_cfg{k});

end

start_lag = ...
    vol_cfg.start_lag_months;

end_lag = ...
    vol_cfg.end_lag_months;


assert( ...
    isscalar(start_lag) && ...
    isscalar(end_lag) && ...
    isfinite(start_lag) && ...
    isfinite(end_lag) && ...
    start_lag == floor(start_lag) && ...
    end_lag == floor(end_lag) && ...
    start_lag > end_lag && ...
    end_lag >= 1, ...
    'TotalVolatility:InvalidLags', ...
    'Volatility lags must satisfy start_lag > end_lag >= 1.');

assert( ...
    isscalar(vol_cfg.min_coverage) && ...
    isfinite(vol_cfg.min_coverage) && ...
    vol_cfg.min_coverage > 0 && ...
    vol_cfg.min_coverage <= 1, ...
    'TotalVolatility:InvalidCoverage', ...
    'min_coverage must lie in the interval (0,1].');


%% Validate calendar interface

required_calendar = { ...
    'portfolio_month', ...
    'daily_window_start', ...
    'daily_window_end'};

for k = 1:numel(required_calendar)

    assert( ...
        ismember( ...
            required_calendar{k}, ...
            calendar.Properties.VariableNames), ...
        'TotalVolatility:MissingCalendarField', ...
        'Calendar is missing required field: %s', ...
        required_calendar{k});

end


%% Confirm calendar matches signal configuration

expected_window_start = ...
    dateshift( ...
        calendar.portfolio_month - calmonths(start_lag), ...
        'start', ...
        'month');

expected_window_end = ...
    dateshift( ...
        calendar.portfolio_month - calmonths(end_lag), ...
        'end', ...
        'month');

assert( ...
    isequal( ...
        calendar.daily_window_start, ...
        expected_window_start), ...
    'TotalVolatility:CalendarStartMismatch', ...
    'Research calendar does not match configured downside start lag.');

assert( ...
    isequal( ...
        calendar.daily_window_end, ...
        expected_window_end), ...
    'TotalVolatility:CalendarEndMismatch', ...
    'Research calendar does not match configured downside end lag.');


%% Input data

daily_dates = ...
    data.daily.dates(:);

daily_returns = ...
    data.daily.returns;

daily_rf = ...
    data.daily.rf(:);

M = ...
    height(calendar);

N = ...
    numel(data.assets.id);

assert(M > 0, ...
    'TotalVolatility:EmptyCalendar', ...
    'Research calendar contains no portfolio months.');

assert( ...
    size(daily_returns,1) == numel(daily_rf), ...
    'TotalVolatility:DailyRFMismatch', ...
    'Daily returns and risk-free series must have the same number of rows.');


%% Preallocate

value = ...
    NaN(M,N);

valid = ...
    false(M,N);

n_observations = ...
    zeros(M,N);

coverage = ...
    zeros(M,N);

n_expected_observations = ...
    zeros(M,1);

min_required_observations = ...
    zeros(M,1);


%% Compute total volatility

for k = 1:M

    window_start = ...
        calendar.daily_window_start(k);

    window_end = ...
        calendar.daily_window_end(k);

    rows = ...
        daily_dates >= window_start & ...
        daily_dates <= window_end;

    n_days = ...
        sum(rows);

    assert(n_days > 0, ...
        'TotalVolatility:EmptyDailyWindow', ...
        ['No daily observations exist between %s and %s for ' ...
         'portfolio month %s.'], ...
        string(window_start), ...
        string(window_end), ...
        string(calendar.portfolio_month(k)));

    n_expected_observations(k) = ...
        n_days;

    required_n = ...
        ceil(vol_cfg.min_coverage * n_days);

    min_required_observations(k) = ...
        required_n;


    %% Daily excess returns

    stock_returns = ...
        daily_returns(rows,:);

    rf = ...
        daily_rf(rows);

    excess_returns = ...
        stock_returns - rf;


    %% Coverage and validity

    observed = ...
        isfinite(excess_returns);

    n_obs = ...
        sum(observed,1);

    n_observations(k,:) = ...
        n_obs;

    coverage(k,:) = ...
        n_obs / n_days;

    signal_valid = ...
        n_obs >= required_n;

    valid(k,:) = ...
        signal_valid;


    %% Sample standard deviation
    %
    % The normalization flag 0 gives the N-1 sample standard deviation.
    % Missing observations are omitted after the common coverage rule has
    % determined signal eligibility.

    if any(signal_valid)

        x = ...
            excess_returns(:,signal_valid);

        value(k,signal_valid) = ...
            std( ...
                x, ...
                0, ...
                1, ...
                'omitnan');

    end

end


%% Integrity checks

assert(all(isnan(value(~valid))), ...
    'TotalVolatility:InvalidSignalStored', ...
    'Invalid total-volatility observations must remain NaN.');

assert(all(isfinite(value(valid))), ...
    'TotalVolatility:NonFiniteSignal', ...
    'Valid total-volatility observations must be finite.');

assert(all(value(valid) >= 0), ...
    'TotalVolatility:NegativeSignal', ...
    'Total volatility cannot be negative.');

required_matrix = ...
    repmat( ...
        min_required_observations, ...
        1, ...
        N);

assert(all( ...
    n_observations(valid) >= required_matrix(valid)), ...
    'TotalVolatility:CoverageViolation', ...
    'A valid signal violates the configured coverage requirement.');


%% Output

sigma = ...
    struct();

sigma.portfolio_month = ...
    calendar.portfolio_month;

sigma.value = ...
    value;

sigma.valid = ...
    valid;

sigma.n_observations = ...
    n_observations;

sigma.coverage = ...
    coverage;

sigma.n_expected_observations = ...
    n_expected_observations;

sigma.min_required_observations = ...
    min_required_observations;

sigma.window_start = ...
    calendar.daily_window_start;

sigma.window_end = ...
    calendar.daily_window_end;

end