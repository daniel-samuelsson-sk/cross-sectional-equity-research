function capm = analyze_market_beta_channel( ...
    series, ...
    rf_dataset, ...
    ff)
%ANALYZE_MARKET_BETA_CHANNEL Analyze market-beta exposure and variance.
%
% Required level portfolios:
%
%   MOM
%   DD-only
%   sigma-only
%   MOM+DD
%   MOM+sigma
%   FINAL
%   equal-weight panel benchmark
%   value-weighted panel benchmark
%
% Difference portfolios are regressed directly on monthly differences in
% portfolio excess returns.
%
% Market excess return is constructed as
%
%   market_excess = (Mkt-RF)_FF + RF_FF - rf_dataset
%
% The variance-channel diagnostic is evaluated only for
%
%   MOM -> MOM+DD
%   MOM -> MOM+sigma
%
% q is computed only when the reduction in portfolio excess-return
% variance is at least 10 percent of the starting portfolio variance.


%% Common dates

assert(isstruct(series), ...
    'MarketBetaChannel:InvalidSeries', ...
    'series must be a structure.');

assert(isfield(series, 'portfolio_month'), ...
    'MarketBetaChannel:MissingPortfolioMonth', ...
    'series.portfolio_month is required.');


portfolio_month = ...
    series.portfolio_month(:);


assert(isdatetime(portfolio_month), ...
    'MarketBetaChannel:InvalidPortfolioMonth', ...
    'series.portfolio_month must be datetime.');

month_index = ...
    12 .* year(portfolio_month) + ...
    month(portfolio_month);


assert( ...
    all(diff(month_index) == 1), ...
    'MarketBetaChannel:NonConsecutiveMonths', ...
    'The OOS sample must contain consecutive monthly observations.');


%% Portfolio interface

portfolio_keys = { ...
    'mom', ...
    'dd_only', ...
    'sigma_only', ...
    'mom_dd', ...
    'mom_sigma', ...
    'final', ...
    'ew', ...
    'vw'};


portfolio_labels = [ ...
    "MOM"; ...
    "DD-only"; ...
    "Sigma-only"; ...
    "MOM+DD"; ...
    "MOM+sigma"; ...
    "FINAL"; ...
    "Equal-weight panel benchmark"; ...
    "Value-weighted panel benchmark"];


n_portfolios = ...
    numel(portfolio_keys);


for k = 1:n_portfolios

    key = ...
        portfolio_keys{k};


    assert(isfield(series, key), ...
        'MarketBetaChannel:MissingPortfolio', ...
        'Missing series.%s.', ...
        key);


    assert( ...
        isstruct(series.(key)) && ...
        isfield(series.(key), 'returns') && ...
        isfield(series.(key), 'excess_returns'), ...
        'MarketBetaChannel:InvalidPortfolioInterface', ...
        'series.%s must contain returns and excess_returns.', ...
        key);


    total_return = ...
        series.(key).returns(:);

    excess_return = ...
        series.(key).excess_returns(:);


    assert( ...
        numel(total_return) == numel(portfolio_month) && ...
        numel(excess_return) == numel(portfolio_month), ...
        'MarketBetaChannel:PortfolioLengthMismatch', ...
        'series.%s must contain one observation per portfolio month.', ...
        key);


    assert( ...
        all(isfinite(total_return)) && ...
        all(isfinite(excess_return)), ...
        'MarketBetaChannel:NonFinitePortfolioSeries', ...
        'series.%s contains non-finite observations.', ...
        key);

end


%% Dataset risk-free rate

assert( ...
    isnumeric(rf_dataset) && ...
    isreal(rf_dataset) && ...
    isvector(rf_dataset), ...
    'MarketBetaChannel:InvalidDatasetRF', ...
    'rf_dataset must be a real numeric vector.');


rf_dataset = ...
    rf_dataset(:);


assert( ...
    numel(rf_dataset) == numel(portfolio_month) && ...
    all(isfinite(rf_dataset)), ...
    'MarketBetaChannel:InvalidDatasetRF', ...
    'rf_dataset must contain one finite observation per portfolio month.');


return_identity_max_difference = ...
    0;


for k = 1:n_portfolios

    key = ...
        portfolio_keys{k};


    identity_difference = ...
        max( ...
            abs( ...
                ( ...
                    series.(key).returns(:) - ...
                    rf_dataset ...
                ) - ...
                series.(key).excess_returns(:)));


    return_identity_max_difference = ...
        max( ...
            return_identity_max_difference, ...
            identity_difference);

end


assert( ...
    return_identity_max_difference <= 1e-12, ...
    'MarketBetaChannel:RiskFreeAlignmentMismatch', ...
    ['rf_dataset does not reproduce the risk-free-rate convention ' ...
     'used by the supplied portfolio excess-return series.']);


%% Fama-French factor input

assert(isstruct(ff), ...
    'MarketBetaChannel:InvalidFactorInput', ...
    'ff must be a structure.');


required_ff_fields = { ...
    'portfolio_month', ...
    'mkt_rf', ...
    'rf', ...
    'meta'};


for k = 1:numel(required_ff_fields)

    field = ...
        required_ff_fields{k};


    assert(isfield(ff, field), ...
        'MarketBetaChannel:MissingFactorField', ...
        'ff.%s is required.', ...
        field);

end


assert( ...
    isequal( ...
        ff.portfolio_month(:), ...
        portfolio_month), ...
    'MarketBetaChannel:FactorDateMismatch', ...
    'Fama-French observations must align exactly with portfolio months.');


ff_mkt_rf = ...
    ff.mkt_rf(:);

ff_rf = ...
    ff.rf(:);


assert( ...
    numel(ff_mkt_rf) == numel(portfolio_month) && ...
    numel(ff_rf) == numel(portfolio_month) && ...
    all(isfinite(ff_mkt_rf)) && ...
    all(isfinite(ff_rf)), ...
    'MarketBetaChannel:InvalidFactorSeries', ...
    'Fama-French Mkt-RF and RF must contain one finite value per month.');


%% Market excess return

market_excess = ...
    ff_mkt_rf + ...
    ff_rf - ...
    rf_dataset;


assert(all(isfinite(market_excess)), ...
    'MarketBetaChannel:NonFiniteMarketExcess', ...
    'Constructed market excess returns must be finite.');


max_abs_ff_rf_minus_dataset_rf = ...
    max( ...
        abs( ...
            ff_rf - ...
            rf_dataset));


%% Periods

% Full sample plus the two halves shared with the subperiod analysis.

halves = ...
    split_sample_halves(portfolio_month);

period_labels = [ ...
    halves.full_label; ...
    halves.label];


period_masks = { ...
    true(numel(portfolio_month),1), ...
    halves.mask{1}, ...
    halves.mask{2}};


n_periods = ...
    numel(period_labels);


period_start = ...
    NaT(n_periods,1);

period_end = ...
    NaT(n_periods,1);

period_n_months = ...
    zeros(n_periods,1);

period_hac_lag = ...
    zeros(n_periods,1);


for p = 1:n_periods

    mask = ...
        period_masks{p};

    dates_p = ...
        portfolio_month(mask);


    L = ...
        floor( ...
            4 * ...
            (numel(dates_p) / 100)^(2/9));


    period_start(p) = ...
        dates_p(1);

    period_end(p) = ...
        dates_p(end);

    period_n_months(p) = ...
        numel(dates_p);

    period_hac_lag(p) = ...
        L;

end


periods = ...
    table( ...
        period_labels, ...
        period_start, ...
        period_end, ...
        period_n_months, ...
        period_hac_lag, ...
        'VariableNames', { ...
            'period', ...
            'start_date', ...
            'end_date', ...
            'n_months', ...
            'hac_lag'});


%% Level regressions

level_rows = ...
    cell( ...
        n_periods * n_portfolios, ...
        1);


level_fits = ...
    cell( ...
        n_periods, ...
        n_portfolios);


row = ...
    0;


for p = 1:n_periods

    mask = ...
        period_masks{p};

    dates_p = ...
        portfolio_month(mask);

    market_p = ...
        market_excess(mask);


    for k = 1:n_portfolios

        key = ...
            portfolio_keys{k};


        y = ...
            series.(key).excess_returns(mask);


        fit = ...
            estimate_capm_regression( ...
                dates_p, ...
                y, ...
                market_p);


        assert( ...
            fit.hac_lag == period_hac_lag(p), ...
            'MarketBetaChannel:LevelHACLagMismatch', ...
            'Unexpected HAC lag for %s in %s.', ...
            portfolio_labels(k), ...
            period_labels(p));


        level_fits{p,k} = ...
            fit;


        row = ...
            row + 1;


        level_rows{row} = ...
            make_regression_row( ...
                period_labels(p), ...
                portfolio_labels(k), ...
                fit);

    end

end


levels = ...
    struct2table( ...
        vertcat( ...
            level_rows{:}));


assert(height(levels) == n_periods * n_portfolios, ...
    'MarketBetaChannel:UnexpectedLevelRegressionCount', ...
    'Expected one level regression per period and portfolio.');


%% Difference-portfolio regressions

difference_labels = [ ...
    "MOM+DD - MOM"; ...
    "MOM+sigma - MOM+DD"; ...
    "FINAL - MOM+DD"; ...
    "MOM+DD - DD-only"];


difference_A_keys = { ...
    'mom', ...
    'mom_dd', ...
    'mom_dd', ...
    'dd_only'};


difference_A_labels = [ ...
    "MOM"; ...
    "MOM+DD"; ...
    "MOM+DD"; ...
    "DD-only"];


difference_B_keys = { ...
    'mom_dd', ...
    'mom_sigma', ...
    'final', ...
    'mom_dd'};


difference_B_labels = [ ...
    "MOM+DD"; ...
    "MOM+sigma"; ...
    "FINAL"; ...
    "MOM+DD"];


n_differences = ...
    numel(difference_labels);


difference_rows = ...
    cell( ...
        n_periods * n_differences, ...
        1);


row = ...
    0;


for p = 1:n_periods

    mask = ...
        period_masks{p};

    dates_p = ...
        portfolio_month(mask);

    market_p = ...
        market_excess(mask);


    for k = 1:n_differences

        key_A = ...
            difference_A_keys{k};

        key_B = ...
            difference_B_keys{k};


        difference_excess_return = ...
            series.(key_B).excess_returns(mask) - ...
            series.(key_A).excess_returns(mask);


        fit = ...
            estimate_capm_regression( ...
                dates_p, ...
                difference_excess_return, ...
                market_p);


        assert( ...
            fit.hac_lag == period_hac_lag(p), ...
            'MarketBetaChannel:DifferenceHACLagMismatch', ...
            'Unexpected HAC lag for %s in %s.', ...
            difference_labels(k), ...
            period_labels(p));


        row = ...
            row + 1;


        difference_rows{row} = ...
            make_difference_row( ...
                period_labels(p), ...
                difference_labels(k), ...
                difference_A_labels(k), ...
                difference_B_labels(k), ...
                fit);

    end

end


differences = ...
    struct2table( ...
        vertcat( ...
            difference_rows{:}));


assert(height(differences) == n_periods * n_differences, ...
    'MarketBetaChannel:UnexpectedDifferenceRegressionCount', ...
    'Expected one difference regression per period and difference.');


%% Market-beta variance channel

channel_labels = [ ...
    "MOM -> MOM+DD"; ...
    "MOM -> MOM+sigma"];


channel_A_keys = { ...
    'mom', ...
    'mom'};


channel_A_labels = [ ...
    "MOM"; ...
    "MOM"];


channel_B_keys = { ...
    'mom_dd', ...
    'mom_sigma'};


channel_B_labels = [ ...
    "MOM+DD"; ...
    "MOM+sigma"];


q_materiality_threshold = ...
    0.10;


n_channels = ...
    numel(channel_labels);


channel_rows = ...
    cell( ...
        n_periods * n_channels, ...
        1);


row = ...
    0;


for p = 1:n_periods

    for k = 1:n_channels

        index_A = ...
            find( ...
                strcmp( ...
                    portfolio_keys, ...
                    channel_A_keys{k}), ...
                1);

        index_B = ...
            find( ...
                strcmp( ...
                    portfolio_keys, ...
                    channel_B_keys{k}), ...
                1);


        assert( ...
            ~isempty(index_A) && ...
            ~isempty(index_B), ...
            'MarketBetaChannel:PortfolioLookupFailure', ...
            'Could not locate a channel portfolio.');


        fit_A = ...
            level_fits{p,index_A};

        fit_B = ...
            level_fits{p,index_B};


        variance_A = ...
            fit_A.portfolio_excess_variance;

        variance_B = ...
            fit_B.portfolio_excess_variance;


        assert( ...
            variance_A > 0 && ...
            variance_B > 0, ...
            'MarketBetaChannel:InvalidChannelVariance', ...
            'Channel portfolio variances must be positive.');


        market_variance = ...
            fit_A.market_excess_variance;


        market_variance_difference = ...
            abs( ...
                fit_A.market_excess_variance - ...
                fit_B.market_excess_variance);


        market_variance_tolerance = ...
            1e-12 + ...
            1e-10 * ...
            abs(fit_A.market_excess_variance);


        assert( ...
            market_variance_difference <= ...
                market_variance_tolerance, ...
            'MarketBetaChannel:ChannelMarketMismatch', ...
            'Channel portfolios must use the same market series.');


        beta_component_A = ...
            fit_A.market_beta_component_variance;

        beta_component_B = ...
            fit_B.market_beta_component_variance;


        residual_variance_A = ...
            fit_A.capm_residual_variance;

        residual_variance_B = ...
            fit_B.capm_residual_variance;


        total_variance_reduction = ...
            variance_A - ...
            variance_B;


        relative_variance_reduction = ...
            total_variance_reduction / ...
            variance_A;


        beta_component_variance_reduction = ...
            beta_component_A - ...
            beta_component_B;


        residual_variance_reduction = ...
            residual_variance_A - ...
            residual_variance_B;


        variance_decomposition_error = ...
            total_variance_reduction - ...
            beta_component_variance_reduction - ...
            residual_variance_reduction;


        variance_decomposition_reference = ...
            max( ...
                [ ...
                    abs(total_variance_reduction), ...
                    abs(beta_component_variance_reduction), ...
                    abs(residual_variance_reduction), ...
                    eps]);


        variance_decomposition_tolerance = ...
            1e-12 + ...
            1e-10 * ...
            variance_decomposition_reference;


        assert( ...
            abs(variance_decomposition_error) <= ...
                variance_decomposition_tolerance, ...
            'MarketBetaChannel:VarianceReductionIdentityFailure', ...
            'The channel variance decomposition failed numerically.');


        if relative_variance_reduction >= ...
                q_materiality_threshold

            q = ...
                beta_component_variance_reduction / ...
                total_variance_reduction;

            q_computed = ...
                true;

            q_reason = ...
                "computed";

        elseif relative_variance_reduction < 0

            q = ...
                NaN;

            q_computed = ...
                false;

            q_reason = ...
                "variance did not decline";

        else

            q = ...
                NaN;

            q_computed = ...
                false;

            q_reason = ...
                "variance reduction below 10% materiality threshold";

        end


        row = ...
            row + 1;


        channel_row = ...
            struct();


        channel_row.period = ...
            period_labels(p);

        channel_row.transition = ...
            channel_labels(k);

        channel_row.portfolio_from = ...
            channel_A_labels(k);

        channel_row.portfolio_to = ...
            channel_B_labels(k);

        channel_row.n_months = ...
            fit_A.n_months;


        channel_row.beta_from = ...
            fit_A.beta;

        channel_row.beta_to = ...
            fit_B.beta;


        channel_row.market_excess_variance = ...
            market_variance;


        channel_row.portfolio_excess_variance_from = ...
            variance_A;

        channel_row.portfolio_excess_variance_to = ...
            variance_B;


        channel_row.total_variance_reduction = ...
            total_variance_reduction;

        channel_row.relative_variance_reduction = ...
            relative_variance_reduction;


        channel_row.beta_component_variance_reduction = ...
            beta_component_variance_reduction;

        channel_row.residual_variance_reduction = ...
            residual_variance_reduction;


        channel_row.q = ...
            q;

        channel_row.q_computed = ...
            q_computed;

        channel_row.q_reason = ...
            q_reason;


        channel_row.variance_decomposition_error = ...
            variance_decomposition_error;


        channel_rows{row} = ...
            channel_row;

    end

end


channel = ...
    struct2table( ...
        vertcat( ...
            channel_rows{:}));


assert(height(channel) == n_periods * n_channels, ...
    'MarketBetaChannel:UnexpectedChannelCount', ...
    'Expected one channel row per period and transition.');


%% Metadata

meta = ...
    struct();


meta.market_excess_formula = ...
    "(Mkt-RF)_FF + RF_FF - rf_dataset";

meta.max_abs_ff_rf_minus_dataset_rf = ...
    max_abs_ff_rf_minus_dataset_rf;

meta.max_return_identity_difference = ...
    return_identity_max_difference;


meta.n_oos_months = ...
    numel(portfolio_month);

meta.oos_start_month = ...
    portfolio_month(1);

meta.oos_end_month = ...
    portfolio_month(end);


meta.regression_frequency = ...
    "monthly";

meta.model = ...
    "single-factor market model with intercept";


meta.hac_kernel = ...
    "Bartlett";

meta.hac_lag_rule = ...
    "floor(4*(T/100)^(2/9))";

meta.hac_lags_full_period = ...
    period_hac_lag(1);

meta.hac_lags_half_period = ...
    max(period_hac_lag(2:3));

meta.hac_small_sample_correction = ...
    false;

meta.hac_prewhitening_order = ...
    0;


meta.confidence_level = ...
    0.95;

meta.confidence_critical_value = ...
    norminv(0.975,0,1);


meta.alpha_annualization = ...
    "12 * monthly alpha";

meta.capm_residual_volatility_annualization = ...
    "sqrt(12) * monthly CAPM residual standard deviation";

meta.variance_normalization = ...
    "sample variance, denominator T-1";

meta.variance_basis = ...
    "portfolio excess returns";


meta.q_definition = ...
    "((beta_A^2-beta_B^2)*var(m))/(var(A)-var(B))";

meta.q_materiality_threshold = ...
    q_materiality_threshold;


if isfield(ff.meta, 'source')

    meta.factor_source = ...
        ff.meta.source;

end


if isfield(ff.meta, 'source_dataset')

    meta.factor_dataset = ...
        ff.meta.source_dataset;

end


if isfield(ff.meta, 'creation_line')

    meta.factor_creation_line = ...
        ff.meta.creation_line;

end


%% Output

capm = ...
    struct();

capm.periods = ...
    periods;

capm.levels = ...
    levels;

capm.differences = ...
    differences;

capm.channel = ...
    channel;

capm.meta = ...
    meta;

end


function row = make_regression_row( ...
    period_label, ...
    portfolio_label, ...
    fit)
%MAKE_REGRESSION_ROW Create one level-regression output row.

row = ...
    struct();


row.period = ...
    period_label;

row.portfolio = ...
    portfolio_label;

row.start_date = ...
    fit.start_date;

row.end_date = ...
    fit.end_date;

row.n_months = ...
    fit.n_months;

row.hac_lag = ...
    fit.hac_lag;


row.alpha_monthly = ...
    fit.alpha_monthly;

row.alpha_hac_se = ...
    fit.alpha_hac_se;

row.alpha_monthly_hac_ci_low = ...
    fit.alpha_monthly_hac_ci(1);

row.alpha_monthly_hac_ci_high = ...
    fit.alpha_monthly_hac_ci(2);


row.alpha_annualized = ...
    fit.alpha_annualized;

row.alpha_annualized_hac_ci_low = ...
    fit.alpha_annualized_hac_ci(1);

row.alpha_annualized_hac_ci_high = ...
    fit.alpha_annualized_hac_ci(2);

row.alpha_hac_ci_excludes_zero = ...
    fit.alpha_hac_ci_excludes_zero;


row.beta = ...
    fit.beta;

row.beta_hac_se = ...
    fit.beta_hac_se;

row.beta_hac_ci_low = ...
    fit.beta_hac_ci(1);

row.beta_hac_ci_high = ...
    fit.beta_hac_ci(2);


row.r_squared = ...
    fit.r_squared;


row.capm_residual_volatility_annualized = ...
    fit.capm_residual_volatility_annualized;

end


