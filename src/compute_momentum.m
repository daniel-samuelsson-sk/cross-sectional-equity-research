function momentum = compute_momentum(data, calendar, cfg)
%COMPUTE_MOMENTUM Compute cross-sectional 12-2 momentum signals.
%
% For portfolio month t, momentum is the compounded total return over
% months t-12 through t-2, inclusive:
%
%       MOM_i,t = prod(1 + r_i,s) - 1
%                 s = t-12,...,t-2
%
% The most recent month, t-1, is deliberately excluded.
%
% The default specification requires a complete monthly return history.
% Signal validity is kept separate from formation-universe eligibility:
% this function only determines whether the momentum signal itself can be
% estimated.
%
% All timing comes from the research calendar. This function does not
% independently construct t-12 or t-2 dates.

validate_research_data(data);


%% Validate configuration

assert( ...
    isfield(cfg, 'signals') && ...
    isfield(cfg.signals, 'momentum'), ...
    'Momentum:MissingConfiguration', ...
    'cfg.signals.momentum is required.');

mom_cfg = cfg.signals.momentum;

required_cfg = { ...
    'start_lag_months', ...
    'end_lag_months', ...
    'require_complete_history'};

for k = 1:numel(required_cfg)

    assert(isfield(mom_cfg, required_cfg{k}), ...
        'Momentum:MissingConfiguration', ...
        'Missing momentum configuration field: %s', ...
        required_cfg{k});

end

start_lag = mom_cfg.start_lag_months;
end_lag   = mom_cfg.end_lag_months;

assert( ...
    isscalar(start_lag) && ...
    isscalar(end_lag) && ...
    isfinite(start_lag) && ...
    isfinite(end_lag) && ...
    start_lag == floor(start_lag) && ...
    end_lag == floor(end_lag) && ...
    start_lag > end_lag && ...
    end_lag >= 1, ...
    'Momentum:InvalidLags', ...
    'Momentum lags must satisfy start_lag > end_lag >= 1.');

assert( ...
    islogical(mom_cfg.require_complete_history) && ...
    isscalar(mom_cfg.require_complete_history), ...
    'Momentum:InvalidHistoryRule', ...
    'require_complete_history must be a logical scalar.');

% The current research specification requires complete monthly history.
% Supporting partial-history momentum would require an explicit separate
% methodology rather than silently compounding different windows.
assert(mom_cfg.require_complete_history, ...
    'Momentum:UnsupportedHistoryRule', ...
    ['The current momentum specification requires complete monthly ' ...
     'history. Partial-history momentum is not supported.']);


%% Validate calendar interface

required_calendar = { ...
    'portfolio_month', ...
    'signal_start_index', ...
    'signal_end_index', ...
    'signal_start_month', ...
    'signal_end_month'};

for k = 1:numel(required_calendar)

    assert( ...
        ismember( ...
            required_calendar{k}, ...
            calendar.Properties.VariableNames), ...
        'Momentum:MissingCalendarField', ...
        'Calendar is missing required field: %s', ...
        required_calendar{k});

end


%% Dimensions

monthly_returns = data.monthly.returns;
monthly_dates   = data.monthly.dates(:);

M = height(calendar);
N = numel(data.assets.id);

assert(M > 0, ...
    'Momentum:EmptyCalendar', ...
    'Research calendar contains no portfolio months.');

expected_n_months = ...
    start_lag - end_lag + 1;


%% Preallocate

value = ...
    NaN(M,N);

valid = ...
    false(M,N);

n_observations = ...
    zeros(M,N);


%% Compute momentum

for k = 1:M

    i_start = ...
        calendar.signal_start_index(k);

    i_end = ...
        calendar.signal_end_index(k);

    assert( ...
        i_start >= 1 && ...
        i_end <= size(monthly_returns,1) && ...
        i_start <= i_end, ...
        'Momentum:InvalidCalendarIndex', ...
        'Momentum window contains invalid monthly indices.');

    window_index = ...
        i_start:i_end;

    assert( ...
        numel(window_index) == expected_n_months, ...
        'Momentum:UnexpectedWindowLength', ...
        ['Momentum window for portfolio month %s contains %d months; ' ...
         'expected %d.'], ...
        string(calendar.portfolio_month(k)), ...
        numel(window_index), ...
        expected_n_months);

    % Verify that the calendar indices actually point to the dates the
    % central research calendar claims they represent.

    assert( ...
        monthly_dates(i_start) == ...
            calendar.signal_start_month(k), ...
        'Momentum:CalendarStartMismatch', ...
        'Signal start index does not match signal start date.');

    assert( ...
        monthly_dates(i_end) == ...
            calendar.signal_end_month(k), ...
        'Momentum:CalendarEndMismatch', ...
        'Signal end index does not match signal end date.');

    history = ...
        monthly_returns(window_index,:);

    observed = ...
        isfinite(history);

    n_observations(k,:) = ...
        sum(observed,1);

    signal_valid = ...
        all(observed,1);

    valid(k,:) = ...
        signal_valid;

    if any(signal_valid)

        valid_history = ...
            history(:,signal_valid);

        value(k,signal_valid) = ...
            prod(1 + valid_history, 1) - 1;

    end

end


%% Integrity checks

assert(all(isnan(value(~valid))), ...
    'Momentum:InvalidSignalStored', ...
    'Invalid momentum observations must remain NaN.');

assert(all(isfinite(value(valid))), ...
    'Momentum:NonFiniteSignal', ...
    'Valid momentum observations must be finite.');

assert(all( ...
    n_observations(valid) == expected_n_months), ...
    'Momentum:IncompleteValidHistory', ...
    'A valid momentum signal has incomplete monthly history.');


%% Output

momentum.portfolio_month = ...
    calendar.portfolio_month;

momentum.value = ...
    value;

momentum.valid = ...
    valid;

momentum.n_observations = ...
    n_observations;

momentum.window_start = ...
    calendar.signal_start_month;

momentum.window_end = ...
    calendar.signal_end_month;

momentum.expected_n_observations = ...
    expected_n_months;

end