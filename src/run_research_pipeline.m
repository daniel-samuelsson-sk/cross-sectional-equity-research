function research = run_research_pipeline(data, cfg)
%RUN_RESEARCH_PIPELINE Execute the core equity-research pipeline.
%
% research = RUN_RESEARCH_PIPELINE(data, cfg)
%
% Executes the complete provider-neutral research workflow:
%
%   1. validate standardized research data
%   2. build the research calendar
%   3. construct the point-in-time formation universe
%   4. assign size buckets
%   5. compute momentum
%   6. compute downside deviation
%   7. compute idiosyncratic skewness
%   8. evaluate the calibration grid and record the configured cutoffs
%   9. apply the recorded cutoffs out of sample
%
% DATA SOURCE
%
% This function is provider-neutral. It operates only on the standardized
% research-data contract. Source-specific loading and normalization occur
% before this function is called.
%
% CONFIGURATION
%
% If cfg is omitted or empty, default_config() is used.
%
% OUTPUT
%
% research.config
% research.calendar
% research.universe
% research.size_control
% research.signals.momentum
% research.signals.downside
% research.signals.idio_skew
% research.calibration
% research.evaluation
% research.meta
%
% The raw input dataset is deliberately NOT copied into the output object.

if nargin < 2 || isempty(cfg)

    cfg = ...
        default_config();

end


%% Validate top-level inputs

assert(isstruct(data), ...
    'ResearchPipeline:InvalidData', ...
    'data must be a research-data struct.');

assert(isstruct(cfg), ...
    'ResearchPipeline:InvalidConfiguration', ...
    'cfg must be a configuration struct.');


%% Standardized data contract

validate_research_data(data);


%% Research calendar

calendar = ...
    build_research_calendar( ...
        data, ...
        cfg);


%% Point-in-time formation universe

universe = ...
    build_formation_universe( ...
        data, ...
        calendar, ...
        cfg);


%% Size control

size_control = ...
    assign_size_buckets( ...
        universe, ...
        cfg);


%% Signal engine

momentum = ...
    compute_momentum( ...
        data, ...
        calendar, ...
        cfg);

downside = ...
    compute_downside_deviation( ...
        data, ...
        calendar, ...
        cfg);

idio_skew = ...
    compute_idiosyncratic_skewness( ...
        data, ...
        calendar, ...
        cfg);


%% Calibration

calibration = ...
    calibrate_cutoffs( ...
        data, ...
        calendar, ...
        universe, ...
        size_control, ...
        momentum, ...
        downside, ...
        idio_skew, ...
        cfg);


%% Out-of-sample evaluation

evaluation = ...
    evaluate_out_of_sample( ...
        data, ...
        calendar, ...
        universe, ...
        size_control, ...
        momentum, ...
        downside, ...
        idio_skew, ...
        calibration, ...
        cfg);


%% Structured output

research = ...
    struct();

research.config = ...
    cfg;

research.calendar = ...
    calendar;

research.universe = ...
    universe;

research.size_control = ...
    size_control;

research.signals = ...
    struct();

research.signals.momentum = ...
    momentum;

research.signals.downside = ...
    downside;

research.signals.idio_skew = ...
    idio_skew;

research.calibration = ...
    calibration;

research.evaluation = ...
    evaluation;


%% Reproducibility metadata
%
% Keep metadata deterministic. Do not insert run timestamps into the core
% research result because identical inputs should produce identical
% research objects.

research.meta = ...
    struct();

research.meta.engine = ...
    "cross-sectional-equity-research";

research.meta.pipeline_version = ...
    "1.0";

research.meta.provider = ...
    "unspecified";

if isfield(data, 'meta') && ...
   isfield(data.meta, 'provider')

    research.meta.provider = ...
        string(data.meta.provider);

end

research.meta.calibration_start = ...
    cfg.periods.calibration_start;

research.meta.calibration_end = ...
    cfg.periods.calibration_end;

research.meta.evaluation_start = ...
    cfg.periods.evaluation_start;

research.meta.evaluation_end = ...
    cfg.periods.evaluation_end;

research.meta.raw_data_embedded = ...
    false;

end