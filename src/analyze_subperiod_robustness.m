function r4 = analyze_subperiod_robustness(data, research)
%ANALYZE_SUBPERIOD_ROBUSTNESS Evaluate OOS performance across two periods.
%
% r4 = ANALYZE_SUBPERIOD_ROBUSTNESS(data, research)
%
% The analysis divides the out-of-sample period into two consecutive
% halves (split_sample_halves): h1 holds the first floor(M/2) months and h2
% the remaining months. In the published 1990-2023 study these are January
% 1990 through December 2006 and January 2007 through December 2023.
%
% Existing OOS portfolio weights are reused without modification.
% Performance is recomputed by evaluate_performance after replacing the
% evaluation phase label with h1 or h2.
%
% The reported portfolios are:
%
%   MOM
%   MOM + DD
%   FINAL
%   EW
%   value-weighted panel benchmark
%
% The reported measures are Sharpe ratio, CAGR and annualized volatility.
%
% period_differences contains the differences used for the time-period
% statements:
%
%   FINAL - value-weighted panel benchmark:
%       Delta Sharpe
%       Delta CAGR
%
%   MOM+DD - MOM:
%       Delta annualized volatility


%% Validate inputs

validate_research_data(data);

assert(isstruct(research), ...
    'SubperiodRobustness:InvalidResearch', ...
    'research must be a research-result struct.');

required_research_fields = { ...
    'config', ...
    'evaluation'};

for k = 1:numel(required_research_fields)

    field = ...
        required_research_fields{k};

    assert(isfield(research, field), ...
        'SubperiodRobustness:MissingResearchField', ...
        'research.%s is required.', ...
        field);

end


assert(isfield(research.evaluation, 'calendar'), ...
    'SubperiodRobustness:MissingCalendar', ...
    'research.evaluation.calendar is required.');

assert(isfield(research.evaluation, 'portfolios'), ...
    'SubperiodRobustness:MissingPortfolios', ...
    'research.evaluation.portfolios is required.');

assert(isfield(research.evaluation, 'performance'), ...
    'SubperiodRobustness:MissingPerformance', ...
    'research.evaluation.performance is required.');


cfg = ...
    research.config;

base_calendar = ...
    research.evaluation.calendar;

portfolios = ...
    research.evaluation.portfolios;

base_performance = ...
    research.evaluation.performance;


%% Validate OOS calendar

assert(istable(base_calendar), ...
    'SubperiodRobustness:InvalidCalendar', ...
    'research.evaluation.calendar must be a table.');

assert( ...
    ismember('portfolio_month', base_calendar.Properties.VariableNames) && ...
    ismember('phase', base_calendar.Properties.VariableNames), ...
    'SubperiodRobustness:MissingCalendarField', ...
    'Evaluation calendar must contain portfolio_month and phase.');

assert(all(base_calendar.phase == "evaluation"), ...
    'SubperiodRobustness:UnexpectedBasePhase', ...
    'The input calendar must contain evaluation-period months only.');


portfolio_month = ...
    base_calendar.portfolio_month(:);

M = ...
    numel(portfolio_month);

%% Define the two periods

halves = ...
    split_sample_halves(portfolio_month);

h1_mask = ...
    halves.mask{1};

h2_mask = ...
    halves.mask{2};


%% Construct phase-labeled calendar

calendar = ...
    base_calendar;

calendar.phase = ...
    strings(M,1);

calendar.phase(h1_mask) = ...
    "h1";

calendar.phase(h2_mask) = ...
    "h2";


assert(all(calendar.phase ~= ""), ...
    'SubperiodRobustness:MissingPhaseLabel', ...
    'Every OOS month must have an R4 phase label.');


%% Evaluate unchanged portfolio weights under the two phase labels

performance = ...
    evaluate_performance( ...
        data, ...
        portfolios, ...
        calendar, ...
        cfg);


%% Verify that phase relabeling did not change monthly returns

portfolio_fields = { ...
    'momentum', ...
    'momentum_downside', ...
    'final', ...
    'equal_weight', ...
    'value_weight'};

portfolio_labels = [ ...
    "MOM"; ...
    "MOM+DD"; ...
    "FINAL"; ...
    "EW"; ...
    "Value-weighted panel benchmark"];


for j = 1:numel(portfolio_fields)

    field = ...
        portfolio_fields{j};

    assert(isfield(performance.returns, field), ...
        'SubperiodRobustness:MissingReturnSeries', ...
        'R4 performance is missing total returns for %s.', ...
        field);

    assert(isfield(performance.excess_returns, field), ...
        'SubperiodRobustness:MissingExcessReturnSeries', ...
        'R4 performance is missing excess returns for %s.', ...
        field);

    assert(isfield(base_performance.returns, field), ...
        'SubperiodRobustness:MissingBaseReturnSeries', ...
        'Existing evaluation performance is missing returns for %s.', ...
        field);

    assert(isfield(base_performance.excess_returns, field), ...
        'SubperiodRobustness:MissingBaseExcessReturnSeries', ...
        'Existing evaluation performance is missing excess returns for %s.', ...
        field);


    assert( ...
        isequaln( ...
            performance.returns.(field), ...
            base_performance.returns.(field)), ...
        'SubperiodRobustness:ReturnSeriesChanged', ...
        ['Changing only the phase labels changed the monthly total ' ...
         'return series for %s.'], ...
        field);

    assert( ...
        isequaln( ...
            performance.excess_returns.(field), ...
            base_performance.excess_returns.(field)), ...
        'SubperiodRobustness:ExcessReturnSeriesChanged', ...
        ['Changing only the phase labels changed the monthly excess ' ...
         'return series for %s.'], ...
        field);

end


%% Require the two phase summaries

assert(isfield(performance.summary, 'h1'), ...
    'SubperiodRobustness:MissingH1Summary', ...
    'evaluate_performance did not produce an h1 summary.');

assert(isfield(performance.summary, 'h2'), ...
    'SubperiodRobustness:MissingH2Summary', ...
    'evaluate_performance did not produce an h2 summary.');


%% Build compact level table

period_keys = { ...
    'h1', ...
    'h2'};

period_labels = ...
    halves.label;


n_periods = ...
    numel(period_keys);

n_portfolios = ...
    numel(portfolio_fields);

n_rows = ...
    n_periods * n_portfolios;


period_column = ...
    strings(n_rows,1);

portfolio_column = ...
    strings(n_rows,1);

sharpe_column = ...
    NaN(n_rows,1);

cagr_column = ...
    NaN(n_rows,1);

volatility_column = ...
    NaN(n_rows,1);


row = ...
    0;


for p = 1:n_periods

    phase = ...
        period_keys{p};

    for j = 1:n_portfolios

        row = ...
            row + 1;

        field = ...
            portfolio_fields{j};

        metrics = ...
            performance.summary.(phase).(field);


        period_column(row) = ...
            period_labels(p);

        portfolio_column(row) = ...
            portfolio_labels(j);

        sharpe_column(row) = ...
            metrics.sharpe;

        cagr_column(row) = ...
            metrics.cagr;

        volatility_column(row) = ...
            metrics.annualized_volatility;

    end

end


summary = ...
    table( ...
        period_column, ...
        portfolio_column, ...
        sharpe_column, ...
        cagr_column, ...
        volatility_column, ...
        'VariableNames', { ...
            'period', ...
            'portfolio', ...
            'sharpe', ...
            'cagr', ...
            'annualized_volatility'});


%% Compute the differences used for the time-period statements

difference_period = ...
    strings(6,1);

difference_comparison = ...
    strings(6,1);

difference_metric = ...
    strings(6,1);

difference_value = ...
    NaN(6,1);


row = ...
    0;


for p = 1:n_periods

    phase = ...
        period_keys{p};

    final_metrics = ...
        performance.summary.(phase).final;

    vw_metrics = ...
        performance.summary.(phase).value_weight;

    mom_metrics = ...
        performance.summary.(phase).momentum;

    dd_metrics = ...
        performance.summary.(phase).momentum_downside;


    %% FINAL - value-weighted panel benchmark: Sharpe

    row = ...
        row + 1;

    difference_period(row) = ...
        period_labels(p);

    difference_comparison(row) = ...
        "FINAL - value-weighted panel benchmark";

    difference_metric(row) = ...
        "sharpe";

    difference_value(row) = ...
        final_metrics.sharpe - ...
        vw_metrics.sharpe;


    %% FINAL - value-weighted panel benchmark: CAGR

    row = ...
        row + 1;

    difference_period(row) = ...
        period_labels(p);

    difference_comparison(row) = ...
        "FINAL - value-weighted panel benchmark";

    difference_metric(row) = ...
        "cagr";

    difference_value(row) = ...
        final_metrics.cagr - ...
        vw_metrics.cagr;


    %% MOM+DD - MOM: annualized volatility

    row = ...
        row + 1;

    difference_period(row) = ...
        period_labels(p);

    difference_comparison(row) = ...
        "MOM+DD - MOM";

    difference_metric(row) = ...
        "annualized_volatility";

    difference_value(row) = ...
        dd_metrics.annualized_volatility - ...
        mom_metrics.annualized_volatility;

end


period_differences = ...
    table( ...
        difference_period, ...
        difference_comparison, ...
        difference_metric, ...
        difference_value, ...
        'VariableNames', { ...
            'period', ...
            'comparison', ...
            'metric', ...
            'difference'});


%% Output

r4 = ...
    struct();

r4.calendar = ...
    calendar;

r4.performance = ...
    performance;

r4.summary = ...
    summary;

r4.period_differences = ...
    period_differences;


r4.meta = ...
    struct();

r4.meta.h1_start = ...
    halves.start_month(1);

r4.meta.h1_end = ...
    halves.end_month(1);

r4.meta.h2_start = ...
    halves.start_month(2);

r4.meta.h2_end = ...
    halves.end_month(2);

r4.meta.h1_months = ...
    sum(h1_mask);

r4.meta.h2_months = ...
    sum(h2_mask);

r4.meta.portfolio_order = ...
    portfolio_labels;

r4.meta.metrics = [ ...
    "sharpe"; ...
    "cagr"; ...
    "annualized_volatility"];

end