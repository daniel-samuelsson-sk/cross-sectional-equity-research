function idio_skew = compute_idiosyncratic_skewness(data, calendar, cfg)
%COMPUTE_IDIOSYNCRATIC_SKEWNESS Compute CAPM-residual skewness signals.
%
% For portfolio month t, daily stock excess returns are regressed on
% daily market excess returns over calendar months t-12 through t-2:
%
%   r_i,d - rf_d = alpha_i + beta_i * (r_m,d - rf_d) + epsilon_i,d
%
% The signal is the finite-sample bias-corrected sample skewness of the
% CAPM residuals:
%
%   skewness(epsilon_i,d, 0)
%
% A signal is valid only when:
%   1. the configured minimum daily coverage is satisfied,
%   2. the CAPM regression is identifiable,
%   3. regression coefficients and residuals are numerically valid, and
%   4. residual skewness is finite.
%
% Timing is supplied entirely by build_research_calendar(). This function
% does not independently construct t-12, t-2, or formation dates.

validate_research_data(data);


%% Validate configuration

assert( ...
    isfield(cfg, 'signals') && ...
    isfield(cfg.signals, 'idio_skew'), ...
    'IdioSkew:MissingConfiguration', ...
    'cfg.signals.idio_skew is required.');

skew_cfg = cfg.signals.idio_skew;

required_cfg = { ...
    'start_lag_months', ...
    'end_lag_months', ...
    'min_coverage'};

for k = 1:numel(required_cfg)

    assert(isfield(skew_cfg, required_cfg{k}), ...
        'IdioSkew:MissingConfiguration', ...
        'Missing idiosyncratic-skewness configuration field: %s', ...
        required_cfg{k});

end

start_lag = ...
    skew_cfg.start_lag_months;

end_lag = ...
    skew_cfg.end_lag_months;

assert( ...
    isscalar(start_lag) && ...
    isscalar(end_lag) && ...
    isfinite(start_lag) && ...
    isfinite(end_lag) && ...
    start_lag == floor(start_lag) && ...
    end_lag == floor(end_lag) && ...
    start_lag > end_lag && ...
    end_lag >= 1, ...
    'IdioSkew:InvalidLags', ...
    'Idiosyncratic-skewness lags must satisfy start_lag > end_lag >= 1.');

assert( ...
    isscalar(skew_cfg.min_coverage) && ...
    isfinite(skew_cfg.min_coverage) && ...
    skew_cfg.min_coverage > 0 && ...
    skew_cfg.min_coverage <= 1, ...
    'IdioSkew:InvalidCoverage', ...
    'min_coverage must lie in the interval (0,1].');


%% Validate calendar interface

required_calendar = { ...
    'portfolio_month', ...
    'daily_window_start', ...
    'daily_window_end'};

for k = 1:numel(required_calendar)

    assert( ...
        ismember( ...
            required_calendar{k}, ...
            calendar.Properties.VariableNames), ...
        'IdioSkew:MissingCalendarField', ...
        'Calendar is missing required field: %s', ...
        required_calendar{k});

end


%% Confirm calendar/config consistency

expected_window_start = dateshift( ...
    calendar.portfolio_month - calmonths(start_lag), ...
    'start', ...
    'month');

expected_window_end = dateshift( ...
    calendar.portfolio_month - calmonths(end_lag), ...
    'end', ...
    'month');

assert( ...
    isequal( ...
        calendar.daily_window_start, ...
        expected_window_start), ...
    'IdioSkew:CalendarStartMismatch', ...
    'Research calendar does not match configured skewness start lag.');

assert( ...
    isequal( ...
        calendar.daily_window_end, ...
        expected_window_end), ...
    'IdioSkew:CalendarEndMismatch', ...
    'Research calendar does not match configured skewness end lag.');


%% Input data

daily_dates = ...
    data.daily.dates(:);

daily_returns = ...
    data.daily.returns;

daily_rf = ...
    data.daily.rf(:);

market_excess = ...
    data.daily.market_excess(:);

M = ...
    height(calendar);

N = ...
    numel(data.assets.id);

assert(M > 0, ...
    'IdioSkew:EmptyCalendar', ...
    'Research calendar contains no portfolio months.');

assert(size(daily_returns,1) == numel(daily_rf), ...
    'IdioSkew:DailyRFMismatch', ...
    'Daily stock returns and risk-free returns must align.');

assert(size(daily_returns,1) == numel(market_excess), ...
    'IdioSkew:MarketFactorMismatch', ...
    'Daily stock returns and market-excess returns must align.');


%% Preallocate

value = ...
    NaN(M,N);

valid = ...
    false(M,N);

coverage_valid = ...
    false(M,N);

regression_valid = ...
    false(M,N);

alpha = ...
    NaN(M,N);

beta = ...
    NaN(M,N);

n_observations = ...
    zeros(M,N);

coverage = ...
    zeros(M,N);

n_expected_observations = ...
    zeros(M,1);

min_required_observations = ...
    zeros(M,1);


%% Compute signal

for k = 1:M

    window_start = ...
        calendar.daily_window_start(k);

    window_end = ...
        calendar.daily_window_end(k);

    rows = ...
        daily_dates >= window_start & ...
        daily_dates <= window_end;

    n_days = ...
        sum(rows);

    assert(n_days > 0, ...
        'IdioSkew:EmptyDailyWindow', ...
        ['No daily observations exist between %s and %s for ' ...
         'portfolio month %s.'], ...
        string(window_start), ...
        string(window_end), ...
        string(calendar.portfolio_month(k)));

    n_expected_observations(k) = ...
        n_days;

    % At least three observations are mathematically required to define
    % residual skewness, even if a caller configures a lower threshold.
    required_n = max( ...
        ceil(skew_cfg.min_coverage * n_days), ...
        3);

    min_required_observations(k) = ...
        required_n;


    %% Construct excess-return panel

    stock_returns = ...
        daily_returns(rows,:);

    rf = ...
        daily_rf(rows);

    factor = ...
        market_excess(rows);

    stock_excess = ...
        stock_returns - rf;

    observed = ...
        isfinite(stock_excess);

    n_obs = ...
        sum(observed,1);

    n_observations(k,:) = ...
        n_obs;

    coverage(k,:) = ...
        n_obs / n_days;

    eligible_by_coverage = ...
        n_obs >= required_n;

    coverage_valid(k,:) = ...
        eligible_by_coverage;


    %% Assets with complete daily history

    complete = ...
        eligible_by_coverage & ...
        n_obs == n_days;

    complete_idx = ...
        find(complete);

    if ~isempty(complete_idx)

        X = [ ...
            ones(n_days,1), ...
            factor];

        % A constant or otherwise degenerate market factor makes the CAPM
        % slope unidentified.
        if rank(X) == 2

            Y = ...
                stock_excess(:,complete_idx);

            B = ...
                X \ Y;

            E = ...
                Y - X * B;

            residual_scale = ...
                std(E,0,1);

            y_scale = ...
                std(Y,0,1);

            numerical_tolerance = ...
                sqrt(eps) .* max(1,y_scale);

            good_regression = ...
                all(isfinite(B),1) & ...
                isfinite(residual_scale) & ...
                residual_scale > numerical_tolerance;

            good_idx = ...
                complete_idx(good_regression);

            if ~isempty(good_idx)

                B_good = ...
                    B(:,good_regression);

                E_good = ...
                    E(:,good_regression);

                alpha(k,good_idx) = ...
                    B_good(1,:);

                beta(k,good_idx) = ...
                    B_good(2,:);

                regression_valid(k,good_idx) = ...
                    true;

                % Explicit finite-sample bias correction.
                skew_values = ...
                    skewness(E_good,0,1);

                finite_skew = ...
                    isfinite(skew_values);

                final_idx = ...
                    good_idx(finite_skew);

                if ~isempty(final_idx)

                    value(k,final_idx) = ...
                        skew_values(finite_skew);

                    valid(k,final_idx) = ...
                        true;

                end

            end

        end

    end


    %% Assets with sufficient but incomplete history
    %
    % Missing-return patterns can differ by security, so these regressions
    % require asset-specific design matrices.

    partial_idx = find( ...
        eligible_by_coverage & ...
        n_obs < n_days);

    for j = 1:numel(partial_idx)

        i = ...
            partial_idx(j);

        y = ...
            stock_excess(:,i);

        ok = ...
            isfinite(y);

        y_ok = ...
            y(ok);

        factor_ok = ...
            factor(ok);

        if numel(y_ok) < required_n
            continue;
        end

        X = [ ...
            ones(numel(y_ok),1), ...
            factor_ok];

        if rank(X) < 2
            continue;
        end

        B = ...
            X \ y_ok;

        if any(~isfinite(B))
            continue;
        end

        residual = ...
            y_ok - X * B;

        residual_scale = ...
            std(residual,0);

        y_scale = ...
            std(y_ok,0);

        numerical_tolerance = ...
            sqrt(eps) * max(1,y_scale);

        if ~isfinite(residual_scale) || ...
           residual_scale <= numerical_tolerance
            continue;
        end

        alpha(k,i) = ...
            B(1);

        beta(k,i) = ...
            B(2);

        regression_valid(k,i) = ...
            true;

        % Use the same explicit estimator as in the complete-data path.
        skew_value = ...
            skewness(residual,0);

        if isfinite(skew_value)

            value(k,i) = ...
                skew_value;

            valid(k,i) = ...
                true;

        end

    end

end


%% Integrity checks

assert(all(isnan(value(~valid))), ...
    'IdioSkew:InvalidSignalStored', ...
    'Invalid idiosyncratic-skewness observations must remain NaN.');

assert(all(isfinite(value(valid))), ...
    'IdioSkew:NonFiniteSignal', ...
    'Valid idiosyncratic-skewness observations must be finite.');

assert(all(valid(:) <= coverage_valid(:)), ...
    'IdioSkew:CoverageViolation', ...
    'A valid skewness signal violates the coverage requirement.');

assert(all(valid(:) <= regression_valid(:)), ...
    'IdioSkew:RegressionViolation', ...
    'A valid skewness signal does not have a valid CAPM regression.');

required_matrix = ...
    repmat(min_required_observations,1,N);

assert(all( ...
    n_observations(valid) >= required_matrix(valid)), ...
    'IdioSkew:ObservationViolation', ...
    'A valid skewness signal has too few observations.');

assert(all(isfinite(alpha(regression_valid))), ...
    'IdioSkew:InvalidAlpha', ...
    'Valid CAPM regressions must have finite alpha estimates.');

assert(all(isfinite(beta(regression_valid))), ...
    'IdioSkew:InvalidBeta', ...
    'Valid CAPM regressions must have finite beta estimates.');


%% Output

idio_skew.portfolio_month = ...
    calendar.portfolio_month;

idio_skew.value = ...
    value;

idio_skew.valid = ...
    valid;

idio_skew.coverage_valid = ...
    coverage_valid;

idio_skew.regression_valid = ...
    regression_valid;

idio_skew.alpha = ...
    alpha;

idio_skew.beta = ...
    beta;

idio_skew.n_observations = ...
    n_observations;

idio_skew.coverage = ...
    coverage;

idio_skew.n_expected_observations = ...
    n_expected_observations;

idio_skew.min_required_observations = ...
    min_required_observations;

idio_skew.window_start = ...
    calendar.daily_window_start;

idio_skew.window_end = ...
    calendar.daily_window_end;

end