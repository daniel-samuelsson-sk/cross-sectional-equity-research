function result = compute_bootstrap_comparison_statistics(series, indices)
%COMPUTE_BOOTSTRAP_COMPARISON_STATISTICS
% Compute paired portfolio differences from supplied bootstrap indices.
%
% result = COMPUTE_BOOTSTRAP_COMPARISON_STATISTICS(series, indices)
%
% The function evaluates six portfolio series:
%
%   MOM
%   MOM + DD
%   FINAL
%   EW
%   MOM + sigma
%   DD only
%
% and five paired comparisons:
%
%   MOM+DD - MOM
%   FINAL - MOM+DD
%   MOM+DD - EW
%   MOM+sigma - MOM+DD
%   MOM+DD - DD-only
%
% For every portfolio and resampled path, metrics are computed as:
%
%   Sharpe:
%       sqrt(12) * mean(excess return) / std(excess return,0)
%
%   Annualized volatility:
%       sqrt(12) * std(total return,0)
%
%   CAGR:
%       prod(1 + total return)^(12/T) - 1
%
% The supplied index matrix determines the number of bootstrap
% replicates. B is therefore always size(indices,1), which allows the
% same statistic code to be used with different bootstrap samples.
%
% The same index path is applied to total and excess returns so that the
% two series remain aligned within every resampled month.


%% Validate series

assert(isstruct(series), ...
    'BootstrapStatistics:InvalidSeries', ...
    'series must be a struct.');

assert(isfield(series, 'portfolio_month'), ...
    'BootstrapStatistics:MissingCalendar', ...
    'series.portfolio_month is required.');

portfolio_fields = { ...
    'mom', ...
    'mom_dd', ...
    'final', ...
    'ew', ...
    'mom_sigma', ...
    'dd_only'};

portfolio_labels = [ ...
    "MOM"; ...
    "MOM+DD"; ...
    "FINAL"; ...
    "EW"; ...
    "MOM+sigma"; ...
    "DD-only"];


T = ...
    numel(series.portfolio_month);

assert(T >= 2, ...
    'BootstrapStatistics:InsufficientSample', ...
    'At least two monthly observations are required.');


%% Assemble aligned portfolio panels

n_portfolios = ...
    numel(portfolio_fields);

returns = ...
    NaN(T, n_portfolios);

excess_returns = ...
    NaN(T, n_portfolios);


for j = 1:n_portfolios

    field = ...
        portfolio_fields{j};

    assert(isfield(series, field), ...
        'BootstrapStatistics:MissingPortfolio', ...
        'Missing portfolio series: %s.', ...
        field);

    assert( ...
        isfield(series.(field), 'returns') && ...
        isfield(series.(field), 'excess_returns'), ...
        'BootstrapStatistics:MissingReturnField', ...
        'Portfolio %s must contain returns and excess_returns.', ...
        field);

    r = ...
        series.(field).returns(:);

    ex = ...
        series.(field).excess_returns(:);

    assert( ...
        numel(r) == T && ...
        numel(ex) == T, ...
        'BootstrapStatistics:SeriesLengthMismatch', ...
        'Portfolio %s does not match the common calendar.', ...
        field);

    assert( ...
        all(isfinite(r)) && ...
        all(isfinite(ex)), ...
        'BootstrapStatistics:NonFiniteReturn', ...
        'Portfolio %s contains non-finite returns.', ...
        field);

    assert( ...
        all(1 + r > 0), ...
        'BootstrapStatistics:InvalidCompoundReturn', ...
        ['Portfolio %s contains a monthly total return with ' ...
         '1 + r <= 0, so CAGR is not defined by the required formula.'], ...
        field);

    returns(:,j) = ...
        r;

    excess_returns(:,j) = ...
        ex;

end


%% Validate bootstrap indices

assert( ...
    isnumeric(indices) && ...
    ismatrix(indices), ...
    'BootstrapStatistics:InvalidIndices', ...
    'indices must be a numeric B-by-T matrix.');

B = ...
    size(indices,1);

assert(B >= 1, ...
    'BootstrapStatistics:EmptyBootstrap', ...
    'indices must contain at least one bootstrap replicate.');

assert( ...
    size(indices,2) == T, ...
    'BootstrapStatistics:IndexLengthMismatch', ...
    'Each bootstrap index path must contain exactly T observations.');

assert( ...
    all(isfinite(indices(:))) && ...
    all(indices(:) == floor(indices(:))) && ...
    all(indices(:) >= 1) && ...
    all(indices(:) <= T), ...
    'BootstrapStatistics:InvalidIndexValue', ...
    'Bootstrap indices must be integers in the range 1,...,T.');


%% Observed portfolio levels
%
% The same metric function is used here and inside the bootstrap loop.

observed_metrics = ...
    NaN(n_portfolios, 3);

for j = 1:n_portfolios

    observed_metrics(j,:) = ...
        compute_metrics( ...
            returns(:,j), ...
            excess_returns(:,j));

end


observed_levels = ...
    table( ...
        portfolio_labels, ...
        observed_metrics(:,1), ...
        observed_metrics(:,2), ...
        observed_metrics(:,3), ...
        'VariableNames', { ...
            'portfolio', ...
            'sharpe', ...
            'annualized_volatility', ...
            'cagr'});


%% Paired comparison definitions

comparison_labels = [ ...
    "MOM+DD - MOM"; ...
    "FINAL - MOM+DD"; ...
    "MOM+DD - EW"; ...
    "MOM+sigma - MOM+DD"; ...
    "MOM+DD - DD-only"];

pairs = [ ...
    2 1; ...
    3 2; ...
    2 4; ...
    5 2; ...
    2 6];

n_comparisons = ...
    size(pairs,1);


%% Observed paired differences

observed_differences = ...
    NaN(n_comparisons, 3);

for p = 1:n_comparisons

    a = ...
        pairs(p,1);

    b = ...
        pairs(p,2);

    observed_differences(p,:) = ...
        observed_metrics(a,:) - observed_metrics(b,:);

end


%% Bootstrap distributions
%
% Columns correspond to the five paired comparisons above.

bootstrap_sharpe = ...
    NaN(B, n_comparisons);

bootstrap_volatility = ...
    NaN(B, n_comparisons);

bootstrap_cagr = ...
    NaN(B, n_comparisons);


for b = 1:B

    idx = ...
        indices(b,:).';

    resampled_metrics = ...
        NaN(n_portfolios, 3);


    %% Recompute portfolio metrics on this resampled path

    for j = 1:n_portfolios

        resampled_metrics(j,:) = ...
            compute_metrics( ...
                returns(idx,j), ...
                excess_returns(idx,j));

    end


    %% Paired differences using the same resampled months

    for p = 1:n_comparisons

        a = ...
            pairs(p,1);

        c = ...
            pairs(p,2);

        difference = ...
            resampled_metrics(a,:) - ...
            resampled_metrics(c,:);

        bootstrap_sharpe(b,p) = ...
            difference(1);

        bootstrap_volatility(b,p) = ...
            difference(2);

        bootstrap_cagr(b,p) = ...
            difference(3);

    end

end


%% Percentile confidence intervals

metric_labels = [ ...
    "sharpe"; ...
    "annualized_volatility"; ...
    "cagr"];

n_metrics = ...
    numel(metric_labels);

n_rows = ...
    n_comparisons * n_metrics;

comparison_column = ...
    strings(n_rows,1);

metric_column = ...
    strings(n_rows,1);

observed_column = ...
    NaN(n_rows,1);

ci_lower = ...
    NaN(n_rows,1);

ci_upper = ...
    NaN(n_rows,1);


row = ...
    0;


for p = 1:n_comparisons

    for m = 1:n_metrics

        row = ...
            row + 1;

        comparison_column(row) = ...
            comparison_labels(p);

        metric_column(row) = ...
            metric_labels(m);

        observed_column(row) = ...
            observed_differences(p,m);


        switch m

            case 1

                bootstrap_values = ...
                    bootstrap_sharpe(:,p);

            case 2

                bootstrap_values = ...
                    bootstrap_volatility(:,p);

            case 3

                bootstrap_values = ...
                    bootstrap_cagr(:,p);

            otherwise

                error( ...
                    'BootstrapStatistics:UnknownMetric', ...
                    'Unexpected metric index.');

        end


        bounds = ...
            prctile( ...
                bootstrap_values, ...
                [2.5 97.5]);

        ci_lower(row) = ...
            bounds(1);

        ci_upper(row) = ...
            bounds(2);

    end

end


summary_table = ...
    table( ...
        comparison_column, ...
        metric_column, ...
        observed_column, ...
        ci_lower, ...
        ci_upper, ...
        'VariableNames', { ...
            'comparison', ...
            'metric', ...
            'observed_difference', ...
            'ci_lower', ...
            'ci_upper'});


%% Output

result = ...
    struct();

result.observed_levels = ...
    observed_levels;

result.summary = ...
    summary_table;

result.bootstrap = ...
    struct();

result.bootstrap.comparison = ...
    comparison_labels;

result.bootstrap.sharpe = ...
    bootstrap_sharpe;

result.bootstrap.annualized_volatility = ...
    bootstrap_volatility;

result.bootstrap.cagr = ...
    bootstrap_cagr;

end


function metrics = compute_metrics(r, ex)
%COMPUTE_METRICS Compute the three R2 performance measures.

r = ...
    r(:);

ex = ...
    ex(:);

T = ...
    numel(r);


assert( ...
    T >= 2 && ...
    numel(ex) == T, ...
    'BootstrapStatistics:MetricLengthMismatch', ...
    'Total and excess return series must have equal length >= 2.');

assert( ...
    all(isfinite(r)) && ...
    all(isfinite(ex)), ...
    'BootstrapStatistics:NonFiniteMetricInput', ...
    'Metric inputs must be finite.');

assert( ...
    all(1 + r > 0), ...
    'BootstrapStatistics:InvalidMetricCompoundReturn', ...
    'CAGR requires 1 + r > 0 for every monthly return.');


excess_volatility = ...
    std(ex, 0);

assert( ...
    isfinite(excess_volatility) && ...
    excess_volatility > 0, ...
    'BootstrapStatistics:InvalidExcessVolatility', ...
    'Sharpe requires positive finite excess-return volatility.');


sharpe = ...
    sqrt(12) * ...
    mean(ex) / ...
    excess_volatility;

annualized_volatility = ...
    sqrt(12) * ...
    std(r, 0);

cagr = ...
    prod(1 + r)^(12 / T) - 1;


metrics = [ ...
    sharpe, ...
    annualized_volatility, ...
    cagr];

end