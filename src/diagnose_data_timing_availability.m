function diagnostic = diagnose_data_timing_availability(data)
%DIAGNOSE_DATA_TIMING_AVAILABILITY
% Diagnose market-cap timing and inherited formation availability.
%
% diagnostic = DIAGNOSE_DATA_TIMING_AVAILABILITY(data)
%
% This function implements the R0 data-timing and availability diagnostic.
%
% It answers two questions:
%
%   1. Does the standardized market-cap series behave consistently with
%      the documented timing convention?
%
%   2. How does the source-provided formation-availability indicator relate
%      to realized monthly-return presence?
%
% The function is diagnostic only. It does not modify the research
% universe, signals, portfolio weights, or returns.
%
% MARKET-CAP TIMING
%
% For adjacent calendar-month market-cap observations, the function
% compares
%
%   delta log(ME), ending at date D
%
% with
%
%   log(1 + return)
%
% for:
%
%   - the month ending at D          [documented alignment]
%   - the month ending one month
%     after D                        [forward/look-ahead control]
%
% The documented alignment is supported when it has both:
%
%   - lower median absolute discrepancy
%   - higher Pearson correlation
%
% than the forward control.
%
% AVAILABILITY
%
% The availability diagnostic compares
%
%   data.availability.available
%
% directly with finite realized monthly returns over the full panel.
%
% A zero mismatch count is an empirical result, not a pass condition.


%% Validate required structure

assert(isstruct(data), ...
    'R0Diagnostic:InvalidData', ...
    'data must be a research-data struct.');

assert(isfield(data, 'market_cap'), ...
    'R0Diagnostic:MissingMarketCap', ...
    'data.market_cap is required.');

assert(isfield(data.market_cap, 'dates'), ...
    'R0Diagnostic:MissingMarketCapDates', ...
    'data.market_cap.dates is required.');

assert(isfield(data.market_cap, 'values'), ...
    'R0Diagnostic:MissingMarketCapValues', ...
    'data.market_cap.values is required.');

assert(isfield(data.market_cap, 'valid'), ...
    'R0Diagnostic:MissingMarketCapValidity', ...
    'data.market_cap.valid is required.');

assert(isfield(data, 'monthly'), ...
    'R0Diagnostic:MissingMonthlyData', ...
    'data.monthly is required.');

assert(isfield(data.monthly, 'dates'), ...
    'R0Diagnostic:MissingMonthlyDates', ...
    'data.monthly.dates is required.');

assert(isfield(data.monthly, 'returns'), ...
    'R0Diagnostic:MissingMonthlyReturns', ...
    'data.monthly.returns is required.');

assert(isfield(data, 'availability'), ...
    'R0Diagnostic:MissingAvailability', ...
    'data.availability is required.');

assert(isfield(data.availability, 'dates'), ...
    'R0Diagnostic:MissingAvailabilityDates', ...
    'data.availability.dates is required.');

assert(isfield(data.availability, 'available'), ...
    'R0Diagnostic:MissingAvailabilityIndicator', ...
    'data.availability.available is required.');


%% Local aliases

me_dates = ...
    data.market_cap.dates(:);

me = ...
    data.market_cap.values;

me_valid = ...
    data.market_cap.valid;

monthly_dates = ...
    data.monthly.dates(:);

monthly_returns = ...
    data.monthly.returns;

availability_dates = ...
    data.availability.dates(:);

available = ...
    data.availability.available;


%% Dimension checks

assert(size(me,1) == numel(me_dates), ...
    'R0Diagnostic:MarketCapDateMismatch', ...
    'Market-cap rows must match market-cap dates.');

assert(isequal(size(me_valid), size(me)), ...
    'R0Diagnostic:MarketCapValidityMismatch', ...
    'Market-cap validity must match market-cap values.');

assert(size(monthly_returns,1) == numel(monthly_dates), ...
    'R0Diagnostic:MonthlyDateMismatch', ...
    'Monthly-return rows must match monthly dates.');

assert(size(monthly_returns,2) == size(me,2), ...
    'R0Diagnostic:AssetDimensionMismatch', ...
    'Monthly returns and market cap must contain the same assets.');

assert(size(available,1) == numel(availability_dates), ...
    'R0Diagnostic:AvailabilityDateMismatch', ...
    'Availability rows must match availability dates.');

assert(isequal(size(available), size(monthly_returns)), ...
    'R0Diagnostic:AvailabilityDimensionMismatch', ...
    'Availability must match the monthly-return panel.');


%% R0A: market-cap timing diagnostic
%
% Compare adjacent market-cap observations only when their information
% dates are consecutive calendar months.
%
% If the pair ends at market-cap date D, match D explicitly to the monthly
% return whose date is D.
%
% The negative control uses the monthly return ending one calendar month
% after D.

n_me_rows = ...
    numel(me_dates);

correct_dlog = ...
    cell(n_me_rows - 1, 1);

correct_return = ...
    cell(n_me_rows - 1, 1);

forward_dlog = ...
    cell(n_me_rows - 1, 1);

forward_return = ...
    cell(n_me_rows - 1, 1);


for t = 2:n_me_rows

    previous_date = ...
        me_dates(t - 1);

    current_date = ...
        me_dates(t);

    expected_current_date = ...
        dateshift( ...
            previous_date + calmonths(1), ...
            'end', ...
            'month');

    if current_date ~= expected_current_date
        continue;
    end


    %% Require valid market cap at both endpoints

    valid_pair = ...
        me_valid(t - 1,:) & ...
        me_valid(t,:);

    if ~any(valid_pair)
        continue;
    end


    %% Change in log market cap

    dlog_me = ...
        NaN(1, size(me,2));

    dlog_me(valid_pair) = ...
        log(me(t,valid_pair)) - ...
        log(me(t - 1,valid_pair));


    %% Correct/documented alignment

    correct_idx = ...
        find(monthly_dates == current_date, 1);

    if ~isempty(correct_idx)

        r = ...
            monthly_returns(correct_idx,:);

        valid_correct = ...
            valid_pair & ...
            isfinite(r) & ...
            (1 + r > 0);

        if any(valid_correct)

            correct_dlog{t - 1} = ...
                dlog_me(valid_correct).';

            correct_return{t - 1} = ...
                log(1 + r(valid_correct)).';

        end

    end


    %% Forward/look-ahead negative control

    forward_date = ...
        dateshift( ...
            current_date + calmonths(1), ...
            'end', ...
            'month');

    forward_idx = ...
        find(monthly_dates == forward_date, 1);

    if ~isempty(forward_idx)

        r_forward = ...
            monthly_returns(forward_idx,:);

        valid_forward = ...
            valid_pair & ...
            isfinite(r_forward) & ...
            (1 + r_forward > 0);

        if any(valid_forward)

            forward_dlog{t - 1} = ...
                dlog_me(valid_forward).';

            forward_return{t - 1} = ...
                log(1 + r_forward(valid_forward)).';

        end

    end

end


%% Pool valid stock-month observations

correct_dlog = ...
    vertcat(correct_dlog{:});

correct_return = ...
    vertcat(correct_return{:});

forward_dlog = ...
    vertcat(forward_dlog{:});

forward_return = ...
    vertcat(forward_return{:});


%% Timing statistics

correct_n = ...
    numel(correct_dlog);

forward_n = ...
    numel(forward_dlog);

assert(correct_n > 1, ...
    'R0Diagnostic:InsufficientCorrectObservations', ...
    'Insufficient observations for documented timing alignment.');

assert(forward_n > 1, ...
    'R0Diagnostic:InsufficientForwardObservations', ...
    'Insufficient observations for forward timing control.');


correct_median_abs_discrepancy = ...
    median( ...
        abs(correct_dlog - correct_return));

forward_median_abs_discrepancy = ...
    median( ...
        abs(forward_dlog - forward_return));


correct_correlation_matrix = ...
    corrcoef( ...
        correct_dlog, ...
        correct_return);

forward_correlation_matrix = ...
    corrcoef( ...
        forward_dlog, ...
        forward_return);

correct_correlation = ...
    correct_correlation_matrix(1,2);

forward_correlation = ...
    forward_correlation_matrix(1,2);


timing_supported = ...
    correct_median_abs_discrepancy < ...
        forward_median_abs_discrepancy && ...
    correct_correlation > ...
        forward_correlation;


timing_table = ...
    table( ...
        ["documented"; "forward_control"], ...
        [correct_n; forward_n], ...
        [ ...
            correct_median_abs_discrepancy; ...
            forward_median_abs_discrepancy ...
        ], ...
        [ ...
            correct_correlation; ...
            forward_correlation ...
        ], ...
        'VariableNames', ...
        { ...
            'alignment', ...
            'N', ...
            'median_abs_discrepancy', ...
            'pearson_correlation' ...
        });


%% R0B: availability diagnostic
%
% Match availability and monthly returns by date explicitly rather than
% relying on row-number equality.

[availability_match, monthly_idx] = ...
    ismember( ...
        availability_dates, ...
        monthly_dates);

assert(all(availability_match), ...
    'R0Diagnostic:AvailabilityDateAlignment', ...
    'One or more availability dates are absent from monthly dates.');

returns_for_availability = ...
    monthly_returns(monthly_idx,:);

return_present = ...
    isfinite(returns_for_availability);


available_and_return = ...
    nnz(available & return_present);

available_and_no_return = ...
    nnz(available & ~return_present);

unavailable_and_return = ...
    nnz(~available & return_present);

unavailable_and_no_return = ...
    nnz(~available & ~return_present);

mismatch_count = ...
    available_and_no_return + ...
    unavailable_and_return;

total_stock_months = ...
    numel(available);


availability_table = ...
    table( ...
        total_stock_months, ...
        available_and_return, ...
        available_and_no_return, ...
        unavailable_and_return, ...
        unavailable_and_no_return, ...
        mismatch_count, ...
        'VariableNames', ...
        { ...
            'total_stock_months', ...
            'available_return', ...
            'available_no_return', ...
            'unavailable_return', ...
            'unavailable_no_return', ...
            'mismatch_count' ...
        });


%% Structured output

diagnostic = ...
    struct();

diagnostic.timing = ...
    struct();

diagnostic.timing.summary = ...
    timing_table;

diagnostic.timing.documented_supported = ...
    timing_supported;

diagnostic.availability = ...
    struct();

diagnostic.availability.summary = ...
    availability_table;


%% Interpretation metadata

diagnostic.meta = ...
    struct();

diagnostic.meta.analysis = ...
    "R0 - data timing and availability diagnostic";

diagnostic.meta.timing_interpretation = ...
    [ ...
        "Market-cap timing is supported only when the documented " ...
        + "alignment has both lower median absolute discrepancy and " ...
        + "higher Pearson correlation than the forward control." ...
    ];

diagnostic.meta.availability_interpretation = ...
    [ ...
        "Formation availability is an inherited course-data convention. " ...
        + "Any observed agreement with realized return presence is an " ...
        + "empirical property of the source data, not a real-time " ...
        + "availability rule created by the research pipeline." ...
    ];

diagnostic.meta.modifies_research_pipeline = ...
    false;

end