function calendar = build_research_calendar(data, cfg)
%BUILD_RESEARCH_CALENDAR Construct point-in-time research windows.
%
% For every portfolio month, defines:
%   - formation date
%   - information cutoff
%   - monthly 12-2 signal window
%   - corresponding daily signal window
%   - calibration/evaluation phase
%
% All downstream research functions must use this calendar rather than
% independently constructing lagged date windows.

validate_research_data(data);

monthly_dates = data.monthly.dates(:);

%% Validate signal-window specification

start_lag = cfg.signals.momentum.start_lag_months;
end_lag   = cfg.signals.momentum.end_lag_months;

assert(start_lag > end_lag && end_lag >= 1, ...
    'ResearchCalendar:InvalidSignalLags', ...
    'Signal lags must satisfy start_lag > end_lag >= 1.');

% All three signals currently use the same 12-2 information window.
assert( ...
    cfg.signals.downside.start_lag_months == start_lag && ...
    cfg.signals.downside.end_lag_months   == end_lag && ...
    cfg.signals.idio_skew.start_lag_months == start_lag && ...
    cfg.signals.idio_skew.end_lag_months   == end_lag, ...
    'ResearchCalendar:InconsistentSignalWindows', ...
    'Momentum, downside deviation and idiosyncratic skewness must use the same calendar window.');

%% Validate research periods

assert(cfg.periods.calibration_start <= cfg.periods.calibration_end, ...
    'ResearchCalendar:InvalidCalibrationPeriod', ...
    'Calibration start must not be after calibration end.');

assert(cfg.periods.evaluation_start <= cfg.periods.evaluation_end, ...
    'ResearchCalendar:InvalidEvaluationPeriod', ...
    'Evaluation start must not be after evaluation end.');

assert(cfg.periods.calibration_end < cfg.periods.evaluation_start, ...
    'ResearchCalendar:OverlappingPeriods', ...
    'Calibration and evaluation periods must not overlap.');

%% Identify portfolio months

is_calibration = ...
    monthly_dates >= cfg.periods.calibration_start & ...
    monthly_dates <= cfg.periods.calibration_end;

is_evaluation = ...
    monthly_dates >= cfg.periods.evaluation_start & ...
    monthly_dates <= cfg.periods.evaluation_end;

research_mask = is_calibration | is_evaluation;

monthly_index = find(research_mask);

assert(~isempty(monthly_index), ...
    'ResearchCalendar:NoResearchMonths', ...
    'No monthly observations fall inside the configured research periods.');

portfolio_month = monthly_dates(monthly_index);

%% Point-in-time dates

% Portfolio return is realized during portfolio_month.
% Portfolio is formed at the beginning of that month.
formation_date = dateshift(portfolio_month, 'start', 'month');

% Last permissible information date.
information_cutoff = dateshift( ...
    portfolio_month - calmonths(1), ...
    'end', 'month');

%% Signal windows

signal_start_month = dateshift( ...
    portfolio_month - calmonths(start_lag), ...
    'end', 'month');

signal_end_month = dateshift( ...
    portfolio_month - calmonths(end_lag), ...
    'end', 'month');

% Find corresponding rows in the standardized monthly dataset.
[has_start, signal_start_index] = ...
    ismember(signal_start_month, monthly_dates);

[has_end, signal_end_index] = ...
    ismember(signal_end_month, monthly_dates);

assert(all(has_start) && all(has_end), ...
    'ResearchCalendar:MissingSignalHistory', ...
    'The monthly dataset does not contain all required signal-window dates.');

% Daily signals cover the complete calendar months represented by
% t-start_lag through t-end_lag.
daily_window_start = dateshift( ...
    signal_start_month, ...
    'start', 'month');

daily_window_end = signal_end_month;

%% Research phase

phase = strings(numel(monthly_index),1);

phase(is_calibration(monthly_index)) = "calibration";
phase(is_evaluation(monthly_index))  = "evaluation";

assert(all(phase ~= ""), ...
    'ResearchCalendar:UndefinedPhase', ...
    'Every research month must belong to a defined research phase.');

%% Output

calendar = table( ...
    monthly_index, ...
    portfolio_month, ...
    formation_date, ...
    information_cutoff, ...
    signal_start_index, ...
    signal_end_index, ...
    signal_start_month, ...
    signal_end_month, ...
    daily_window_start, ...
    daily_window_end, ...
    phase);

end