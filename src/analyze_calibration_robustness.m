function r5 = analyze_calibration_robustness(data, research)
%ANALYZE_CALIBRATION_ROBUSTNESS Evaluate nearby calibration specifications.
%
% r5 = ANALYZE_CALIBRATION_ROBUSTNESS(data, research)
%
% The analysis evaluates all admissible calibration specifications already
% contained in research.calibration.ranked_candidates.
%
% Calibration order and rank are inherited directly from that table.
% No additional ranking or parameter selection is performed here.
%
% For each specification, the corresponding cutoffs are injected into
% evaluate_out_of_sample and the FINAL portfolio's OOS Sharpe ratio is
% recorded.
%
% The reported rank relationship is the Spearman correlation between
% calibration Sharpe and OOS Sharpe across all admissible specifications.


%% Validate inputs

validate_research_data(data);

assert(isstruct(research), ...
    'CalibrationRobustness:InvalidResearch', ...
    'research must be a research-result struct.');

required_research_fields = { ...
    'config', ...
    'calendar', ...
    'universe', ...
    'size_control', ...
    'signals', ...
    'calibration', ...
    'evaluation'};

for k = 1:numel(required_research_fields)

    field = ...
        required_research_fields{k};

    assert(isfield(research, field), ...
        'CalibrationRobustness:MissingResearchField', ...
        'research.%s is required.', ...
        field);

end


required_signal_fields = { ...
    'momentum', ...
    'downside', ...
    'idio_skew'};

for k = 1:numel(required_signal_fields)

    field = ...
        required_signal_fields{k};

    assert(isfield(research.signals, field), ...
        'CalibrationRobustness:MissingSignal', ...
        'research.signals.%s is required.', ...
        field);

end


assert(isfield(research.calibration, 'ranked_candidates'), ...
    'CalibrationRobustness:MissingRankedCandidates', ...
    'research.calibration.ranked_candidates is required.');

assert(isfield(research.calibration, 'selected_cutoffs'), ...
    'CalibrationRobustness:MissingSelectedCutoffs', ...
    'research.calibration.selected_cutoffs is required.');

assert(isfield(research.calibration, 'selected_rank'), ...
    'CalibrationRobustness:MissingSelectedRank', ...
    'research.calibration.selected_rank is required.');

assert( ...
    isfield(research.evaluation, 'summary') && ...
    isfield(research.evaluation.summary, 'final'), ...
    'CalibrationRobustness:MissingMainEvaluation', ...
    'The main FINAL evaluation summary is required.');


%% Use the existing admissible ranking directly

ranked = ...
    research.calibration.ranked_candidates;

assert(istable(ranked), ...
    'CalibrationRobustness:InvalidRankedCandidates', ...
    'ranked_candidates must be a table.');


required_candidate_fields = { ...
    'momentum_pct', ...
    'downside_pct', ...
    'skew_pct', ...
    'sharpe', ...
    'rank'};

for k = 1:numel(required_candidate_fields)

    field = ...
        required_candidate_fields{k};

    assert( ...
        ismember(field, ranked.Properties.VariableNames), ...
        'CalibrationRobustness:MissingCandidateField', ...
        'ranked_candidates is missing %s.', ...
        field);

end


n_specifications = ...
    height(ranked);

expected_rank = ...
    (1:n_specifications)';

assert( ...
    isequal(ranked.rank, expected_rank), ...
    'CalibrationRobustness:UnexpectedRankSequence', ...
    'Calibration ranks must be inherited as 1 through n.');


%% Validate the reported specification

selected_cutoffs = ...
    research.calibration.selected_cutoffs;

selected_rank = ...
    research.calibration.selected_rank;


required_cutoffs = { ...
    'momentum_pct', ...
    'downside_pct', ...
    'skew_pct'};

for k = 1:numel(required_cutoffs)

    field = ...
        required_cutoffs{k};

    assert(isfield(selected_cutoffs, field), ...
        'CalibrationRobustness:MissingReportedCutoff', ...
        'selected_cutoffs.%s is required.', ...
        field);

    value = ...
        selected_cutoffs.(field);

    assert( ...
        isnumeric(value) && ...
        isscalar(value) && ...
        isfinite(value), ...
        'CalibrationRobustness:InvalidReportedCutoff', ...
        'selected_cutoffs.%s must be a finite scalar.', ...
        field);

end


assert( ...
    isnumeric(selected_rank) && ...
    isscalar(selected_rank) && ...
    isfinite(selected_rank), ...
    'CalibrationRobustness:InvalidSelectedRank', ...
    'research.calibration.selected_rank must be a finite scalar.');


%% Confirm configuration and calibration identify the same specification

assert(isfield(research.config, 'selection'), ...
    'CalibrationRobustness:MissingSelectionConfiguration', ...
    'research.config.selection is required.');

cfg_selection = ...
    research.config.selection;


assert( ...
    cfg_selection.momentum_pct == ...
        selected_cutoffs.momentum_pct && ...
    cfg_selection.downside_pct == ...
        selected_cutoffs.downside_pct && ...
    cfg_selection.skew_pct == ...
        selected_cutoffs.skew_pct, ...
    'CalibrationRobustness:SelectionConfigurationMismatch', ...
    ['The reported calibration cutoffs must match the research ' ...
     'selection configuration.']);


%% Build the local table without re-sorting

momentum_cutoff = ...
    ranked.momentum_pct;

downside_cutoff = ...
    ranked.downside_pct;

skew_cutoff = ...
    ranked.skew_pct;

calibration_sharpe = ...
    ranked.sharpe;

calibration_rank = ...
    ranked.rank;


is_reported_specification = ...
    momentum_cutoff == selected_cutoffs.momentum_pct & ...
    downside_cutoff == selected_cutoffs.downside_pct & ...
    skew_cutoff == selected_cutoffs.skew_pct;


assert(nnz(is_reported_specification) == 1, ...
    'CalibrationRobustness:ReportedSpecificationMultiplicity', ...
    'The reported specification must occur exactly once.');

assert( ...
    calibration_rank(is_reported_specification) == selected_rank, ...
    'CalibrationRobustness:ReportedRankMismatch', ...
    ['The reported specification rank must match ' ...
     'research.calibration.selected_rank.']);


%% Evaluate each specification through the existing OOS path

oos_sharpe = ...
    NaN(n_specifications,1);


for k = 1:n_specifications

    cutoffs = ...
        struct();

    cutoffs.momentum_pct = ...
        momentum_cutoff(k);

    cutoffs.downside_pct = ...
        downside_cutoff(k);

    cutoffs.skew_pct = ...
        skew_cutoff(k);


    injected_calibration = ...
        research.calibration;

    injected_calibration.selected_cutoffs = ...
        cutoffs;


    evaluation = ...
        evaluate_out_of_sample( ...
            data, ...
            research.calendar, ...
            research.universe, ...
            research.size_control, ...
            research.signals.momentum, ...
            research.signals.downside, ...
            research.signals.idio_skew, ...
            injected_calibration, ...
            research.config);


    assert( ...
        evaluation.cutoffs.momentum_pct == ...
            cutoffs.momentum_pct && ...
        evaluation.cutoffs.downside_pct == ...
            cutoffs.downside_pct && ...
        evaluation.cutoffs.skew_pct == ...
            cutoffs.skew_pct, ...
        'CalibrationRobustness:CutoffInjectionMismatch', ...
        'evaluate_out_of_sample did not use the injected cutoffs.');


    assert( ...
        isfield(evaluation.summary, 'final') && ...
        isfield(evaluation.summary.final, 'sharpe'), ...
        'CalibrationRobustness:MissingOOSSharpe', ...
        'FINAL OOS Sharpe is missing for one specification.');


    oos_sharpe(k) = ...
        evaluation.summary.final.sharpe;

end


%% Require finite Sharpe ratios

assert( ...
    all(isfinite(calibration_sharpe)), ...
    'CalibrationRobustness:NonFiniteCalibrationSharpe', ...
    'All calibration Sharpe values must be finite.');

assert( ...
    all(isfinite(oos_sharpe)), ...
    'CalibrationRobustness:NonFiniteOOSSharpe', ...
    'All OOS Sharpe values must be finite.');


%% Check that the reported specification reproduces the main result

main_oos_sharpe = ...
    research.evaluation.summary.final.sharpe;

reported_oos_sharpe = ...
    oos_sharpe(is_reported_specification);

main_result_tolerance = ...
    1e-12;


assert( ...
    isfinite(main_oos_sharpe), ...
    'CalibrationRobustness:NonFiniteMainSharpe', ...
    'The main FINAL OOS Sharpe must be finite.');

assert( ...
    abs( ...
        reported_oos_sharpe - ...
        main_oos_sharpe) <= main_result_tolerance, ...
    'CalibrationRobustness:MainResultMismatch', ...
    ['The injected reported specification does not reproduce the ' ...
     'main FINAL OOS Sharpe within %.1e.'], ...
    main_result_tolerance);


%% Spearman relation
%
% The correlation is defined on the Sharpe levels, not on the calibration
% rank column.

spearman_rho = ...
    corr( ...
        calibration_sharpe, ...
        oos_sharpe, ...
        'Type', ...
        'Spearman');


assert( ...
    isfinite(spearman_rho), ...
    'CalibrationRobustness:NonFiniteSpearman', ...
    'The Spearman correlation must be finite.');


%% Machine-readable outputs

local_table = ...
    table( ...
        momentum_cutoff, ...
        downside_cutoff, ...
        skew_cutoff, ...
        calibration_sharpe, ...
        calibration_rank, ...
        is_reported_specification, ...
        oos_sharpe, ...
        'VariableNames', { ...
            'momentum_cutoff', ...
            'downside_cutoff', ...
            'skew_cutoff', ...
            'calibration_sharpe', ...
            'calibration_rank', ...
            'is_reported_specification', ...
            'oos_sharpe'});


r5 = ...
    struct();

r5.local_table = ...
    local_table;


r5.rank_relation = ...
    struct();

r5.rank_relation.spearman_rho = ...
    spearman_rho;


r5.meta = ...
    struct();

r5.meta.n_specifications = ...
    n_specifications;

r5.meta.reported_specification = [ ...
    selected_cutoffs.momentum_pct, ...
    selected_cutoffs.downside_pct, ...
    selected_cutoffs.skew_pct];

r5.meta.reported_calibration_rank = ...
    selected_rank;

end