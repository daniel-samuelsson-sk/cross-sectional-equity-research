function selection = apply_signal_filters( ...
    universe, ...
    size_control, ...
    momentum, ...
    downside, ...
    idio_skew, ...
    cutoffs)
%APPLY_SIGNAL_FILTERS Apply sequential cross-sectional signal filters.
%
% The selection sequence is:
%
%   base formation universe
%       ↓
%   valid momentum signal
%       ↓
%   high-momentum filter within size bucket
%       ↓
%   valid downside-deviation signal
%       ↓
%   low-downside filter within surviving stocks and size bucket
%       ↓
%   valid idiosyncratic-skewness signal
%       ↓
%   low-skewness filter within surviving stocks and size bucket
%
% Percentile interpretation:
%
%   momentum_pct:
%       percentile threshold. Securities with momentum greater than or
%       equal to the threshold survive.
%
%       Example:
%           momentum_pct = 70
%           -> retain approximately the top 30%.
%
%   downside_pct:
%       fraction of the surviving population retained from the lower tail.
%
%       Example:
%           downside_pct = 40
%           -> retain approximately the bottom 40%.
%
%   skew_pct:
%       fraction of the surviving population retained from the lower tail.
%
%       Example:
%           skew_pct = 90
%           -> retain approximately the bottom 90%.
%
% Missing or invalid signal observations never pass their corresponding
% filter.
%
% This function contains no calibration or evaluation logic. The same
% implementation must be used in both phases.

%% Validate cutoffs

required_cutoffs = { ...
    'momentum_pct', ...
    'downside_pct', ...
    'skew_pct'};

for k = 1:numel(required_cutoffs)

    assert(isfield(cutoffs, required_cutoffs{k}), ...
        'SignalFilters:MissingCutoff', ...
        'Missing cutoff field: %s', ...
        required_cutoffs{k});

end

validate_percentile( ...
    cutoffs.momentum_pct, ...
    'momentum_pct');

validate_percentile( ...
    cutoffs.downside_pct, ...
    'downside_pct');

validate_percentile( ...
    cutoffs.skew_pct, ...
    'skew_pct');


%% Validate universe

required_universe = { ...
    'portfolio_month', ...
    'base_eligible'};

for k = 1:numel(required_universe)

    assert(isfield(universe, required_universe{k}), ...
        'SignalFilters:MissingUniverseField', ...
        'Universe is missing required field: %s', ...
        required_universe{k});

end

base_eligible = ...
    universe.base_eligible;

assert(islogical(base_eligible), ...
    'SignalFilters:InvalidUniverseType', ...
    'universe.base_eligible must be logical.');

[M,N] = ...
    size(base_eligible);


%% Validate size control

required_size = { ...
    'portfolio_month', ...
    'bucket', ...
    'n_buckets'};

for k = 1:numel(required_size)

    assert(isfield(size_control, required_size{k}), ...
        'SignalFilters:MissingSizeField', ...
        'Size control is missing required field: %s', ...
        required_size{k});

end

assert( ...
    isequal(size(size_control.bucket), [M N]), ...
    'SignalFilters:SizeDimensionMismatch', ...
    'Size-bucket matrix must match the formation-universe dimensions.');

B = ...
    size_control.n_buckets;

assert( ...
    isscalar(B) && ...
    isfinite(B) && ...
    B == floor(B) && ...
    B >= 2, ...
    'SignalFilters:InvalidBucketCount', ...
    'size_control.n_buckets must be an integer >= 2.');


%% Validate signals

validate_signal( ...
    momentum, ...
    universe.portfolio_month, ...
    M, ...
    N, ...
    'momentum');

validate_signal( ...
    downside, ...
    universe.portfolio_month, ...
    M, ...
    N, ...
    'downside');

validate_signal( ...
    idio_skew, ...
    universe.portfolio_month, ...
    M, ...
    N, ...
    'idio_skew');


%% Validate calendar alignment

assert( ...
    isequal( ...
        size_control.portfolio_month(:), ...
        universe.portfolio_month(:)), ...
    'SignalFilters:SizeCalendarMismatch', ...
    'Size-control and universe portfolio months must align.');


%% Preallocate eligibility states

eligible_momentum = ...
    false(M,N);

eligible_downside = ...
    false(M,N);

eligible_skew = ...
    false(M,N);


%% Preallocate selections

selected_momentum = ...
    false(M,N);

selected_momentum_downside = ...
    false(M,N);

selected_final = ...
    false(M,N);


%% Preallocate percentile thresholds

momentum_threshold = ...
    NaN(M,B);

downside_threshold = ...
    NaN(M,B);

skew_threshold = ...
    NaN(M,B);


%% Preallocate diagnostics

momentum_candidate_count = ...
    zeros(M,B);

momentum_selected_count = ...
    zeros(M,B);

downside_candidate_count = ...
    zeros(M,B);

downside_selected_count = ...
    zeros(M,B);

skew_candidate_count = ...
    zeros(M,B);

skew_selected_count = ...
    zeros(M,B);


%% Sequential selection

for t = 1:M

    for b = 1:B

        in_bucket = ...
            base_eligible(t,:) & ...
            size_control.bucket(t,:) == b;


        %% Stage 1: momentum

        momentum_pool = ...
            in_bucket & ...
            momentum.valid(t,:) & ...
            isfinite(momentum.value(t,:));

        eligible_momentum(t,:) = ...
            eligible_momentum(t,:) | momentum_pool;

        momentum_candidate_count(t,b) = ...
            sum(momentum_pool);

        if any(momentum_pool)

            values = ...
                momentum.value(t,momentum_pool);

            q = ...
                prctile( ...
                    values, ...
                    cutoffs.momentum_pct);

            momentum_threshold(t,b) = ...
                q;

            keep = ...
                momentum_pool & ...
                momentum.value(t,:) >= q;

            selected_momentum(t,:) = ...
                selected_momentum(t,:) | keep;

            momentum_selected_count(t,b) = ...
                sum(keep);

        end


        %% Stage 2: downside deviation

        downside_pool = ...
            selected_momentum(t,:) & ...
            size_control.bucket(t,:) == b & ...
            downside.valid(t,:) & ...
            isfinite(downside.value(t,:));

        eligible_downside(t,:) = ...
            eligible_downside(t,:) | downside_pool;

        downside_candidate_count(t,b) = ...
            sum(downside_pool);

        if any(downside_pool)

            values = ...
                downside.value(t,downside_pool);

            q = ...
                prctile( ...
                    values, ...
                    cutoffs.downside_pct);

            downside_threshold(t,b) = ...
                q;

            if cutoffs.downside_pct == 0

                keep = ...
                    false(1,N);

            elseif cutoffs.downside_pct == 100

                keep = ...
                    downside_pool;

            else

                keep = ...
                    downside_pool & ...
                    downside.value(t,:) <= q;

            end

            selected_momentum_downside(t,:) = ...
                selected_momentum_downside(t,:) | keep;

            downside_selected_count(t,b) = ...
                sum(keep);

        end


        %% Stage 3: idiosyncratic skewness

        skew_pool = ...
            selected_momentum_downside(t,:) & ...
            size_control.bucket(t,:) == b & ...
            idio_skew.valid(t,:) & ...
            isfinite(idio_skew.value(t,:));

        eligible_skew(t,:) = ...
            eligible_skew(t,:) | skew_pool;

        skew_candidate_count(t,b) = ...
            sum(skew_pool);

        if any(skew_pool)

            values = ...
                idio_skew.value(t,skew_pool);

            q = ...
                prctile( ...
                    values, ...
                    cutoffs.skew_pct);

            skew_threshold(t,b) = ...
                q;

            if cutoffs.skew_pct == 0

                keep = ...
                    false(1,N);

            elseif cutoffs.skew_pct == 100

                keep = ...
                    skew_pool;

            else

                keep = ...
                    skew_pool & ...
                    idio_skew.value(t,:) <= q;

            end

            selected_final(t,:) = ...
                selected_final(t,:) | keep;

            skew_selected_count(t,b) = ...
                sum(keep);

        end

    end

end


%% Integrity checks

assert(all( ...
    selected_momentum(:) <= eligible_momentum(:)), ...
    'SignalFilters:MomentumEligibilityViolation', ...
    'A selected momentum stock is not momentum-eligible.');

assert(all( ...
    selected_momentum_downside(:) <= selected_momentum(:)), ...
    'SignalFilters:DownsideSequenceViolation', ...
    'A downside-selected stock did not pass momentum first.');

assert(all( ...
    selected_momentum_downside(:) <= downside.valid(:)), ...
    'SignalFilters:DownsideValidityViolation', ...
    'A stock with invalid downside deviation passed the downside filter.');

assert(all( ...
    selected_final(:) <= selected_momentum_downside(:)), ...
    'SignalFilters:SkewSequenceViolation', ...
    'A final-selected stock did not pass momentum and downside first.');

assert(all( ...
    selected_final(:) <= idio_skew.valid(:)), ...
    'SignalFilters:SkewValidityViolation', ...
    'A stock with invalid idiosyncratic skewness passed the skew filter.');

assert(~any( ...
    selected_momentum(~base_eligible)), ...
    'SignalFilters:UniverseViolation', ...
    'A stock outside the formation universe was selected.');

assert(~any( ...
    selected_final(~base_eligible)), ...
    'SignalFilters:UniverseViolation', ...
    'A stock outside the formation universe reached the final selection.');


%% Overall counts

n_base = ...
    sum(base_eligible,2);

n_momentum_eligible = ...
    sum(eligible_momentum,2);

n_momentum_selected = ...
    sum(selected_momentum,2);

n_downside_eligible = ...
    sum(eligible_downside,2);

n_momentum_downside_selected = ...
    sum(selected_momentum_downside,2);

n_skew_eligible = ...
    sum(eligible_skew,2);

n_final_selected = ...
    sum(selected_final,2);


%% Output

selection.portfolio_month = ...
    universe.portfolio_month;

selection.cutoffs = ...
    cutoffs;


%% Eligibility

selection.eligible.momentum = ...
    eligible_momentum;

selection.eligible.downside = ...
    eligible_downside;

selection.eligible.skew = ...
    eligible_skew;


%% Selection masks

selection.selected.momentum = ...
    selected_momentum;

selection.selected.momentum_downside = ...
    selected_momentum_downside;

selection.selected.final = ...
    selected_final;


%% Thresholds

selection.thresholds.momentum = ...
    momentum_threshold;

selection.thresholds.downside = ...
    downside_threshold;

selection.thresholds.skew = ...
    skew_threshold;


%% Counts by portfolio month

selection.counts.base = ...
    n_base;

selection.counts.momentum_eligible = ...
    n_momentum_eligible;

selection.counts.momentum = ...
    n_momentum_selected;

selection.counts.downside_eligible = ...
    n_downside_eligible;

selection.counts.momentum_downside = ...
    n_momentum_downside_selected;

selection.counts.skew_eligible = ...
    n_skew_eligible;

selection.counts.final = ...
    n_final_selected;


%% Counts by size bucket

selection.bucket_counts.momentum_candidates = ...
    momentum_candidate_count;

selection.bucket_counts.momentum_selected = ...
    momentum_selected_count;

selection.bucket_counts.downside_candidates = ...
    downside_candidate_count;

selection.bucket_counts.downside_selected = ...
    downside_selected_count;

selection.bucket_counts.skew_candidates = ...
    skew_candidate_count;

selection.bucket_counts.skew_selected = ...
    skew_selected_count;

end


function validate_percentile(value, name)
%VALIDATE_PERCENTILE Validate a scalar percentile on MATLAB's 0-100 scale.

assert( ...
    isnumeric(value) && ...
    isscalar(value) && ...
    isfinite(value) && ...
    value >= 0 && ...
    value <= 100, ...
    'SignalFilters:InvalidCutoff', ...
    '%s must be a finite scalar between 0 and 100.', ...
    name);

end


function validate_signal(signal, portfolio_month, M, N, signal_name)
%VALIDATE_SIGNAL Validate the common signal interface.

required = { ...
    'portfolio_month', ...
    'value', ...
    'valid'};

for k = 1:numel(required)

    assert(isfield(signal, required{k}), ...
        'SignalFilters:MissingSignalField', ...
        '%s signal is missing required field: %s', ...
        signal_name, ...
        required{k});

end

assert( ...
    isequal(size(signal.value), [M N]), ...
    'SignalFilters:SignalDimensionMismatch', ...
    '%s signal values do not match universe dimensions.', ...
    signal_name);

assert( ...
    isequal(size(signal.valid), [M N]), ...
    'SignalFilters:SignalDimensionMismatch', ...
    '%s signal validity matrix does not match universe dimensions.', ...
    signal_name);

assert(islogical(signal.valid), ...
    'SignalFilters:InvalidSignalType', ...
    '%s.valid must be logical.', ...
    signal_name);

assert( ...
    isequal( ...
        signal.portfolio_month(:), ...
        portfolio_month(:)), ...
    'SignalFilters:SignalCalendarMismatch', ...
    '%s signal portfolio months do not align with the universe.', ...
    signal_name);

end