function validate_research_data(data)
%VALIDATE_RESEARCH_DATA Validate the provider-neutral research data contract.
%
% Raises an error if the supplied dataset violates structural requirements
% needed by the research engine.
%
% This function is provider-neutral. It validates the same standardized
% contract for source datasets and synthetic test fixtures.

%% Required top-level structures

required_top = { ...
    'assets', ...
    'daily', ...
    'monthly', ...
    'market_cap', ...
    'availability'};

for k = 1:numel(required_top)

    assert(isfield(data, required_top{k}), ...
        'ResearchData:MissingField', ...
        'Missing required data structure: data.%s', ...
        required_top{k});

end


%% Asset identifiers

assert(isfield(data.assets, 'id'), ...
    'ResearchData:MissingAssetID', ...
    'data.assets.id is required.');

asset_ids = data.assets.id(:);

N = numel(asset_ids);

assert(N > 0, ...
    'ResearchData:EmptyUniverse', ...
    'The asset universe is empty.');

assert(all(~ismissing(asset_ids)), ...
    'ResearchData:MissingAssetID', ...
    'Asset identifiers must not contain missing values.');

assert(numel(unique(asset_ids)) == N, ...
    'ResearchData:DuplicateAssetID', ...
    'Asset identifiers must be unique.');

assert(isfield(data.assets, 'security_type'), ...
    'ResearchData:MissingSecurityType', ...
    'data.assets.security_type is required.');

security_type = ...
    data.assets.security_type;

assert(isstring(security_type), ...
    'ResearchData:InvalidSecurityTypeType', ...
    'data.assets.security_type must be a string array.');

assert( ...
    isrow(security_type) && ...
    numel(security_type) == N, ...
    'ResearchData:SecurityTypeAssetMismatch', ...
    ['data.assets.security_type must contain one value per asset ' ...
     'as a 1-by-N string array.']);

allowed_security_types = [ ...
    "common_equity", ...
    "non_common_equity", ...
    "unknown"];

assert(all(ismember(security_type, allowed_security_types)), ...
    'ResearchData:InvalidSecurityType', ...
    ['data.assets.security_type may contain only common_equity, ' ...
     'non_common_equity, or unknown.']);


%% Daily data

required_daily = { ...
    'dates', ...
    'returns', ...
    'rf', ...
    'market_excess'};

for k = 1:numel(required_daily)

    assert(isfield(data.daily, required_daily{k}), ...
        'ResearchData:MissingDailyField', ...
        'Missing required field: data.daily.%s', ...
        required_daily{k});

end

daily_dates   = data.daily.dates(:);
daily_returns = data.daily.returns;

assert(isdatetime(daily_dates), ...
    'ResearchData:InvalidDailyDates', ...
    'data.daily.dates must be datetime.');

assert(size(daily_returns,1) == numel(daily_dates), ...
    'ResearchData:DailyRowMismatch', ...
    'Daily return rows must match number of daily dates.');

assert(size(daily_returns,2) == N, ...
    'ResearchData:DailyAssetMismatch', ...
    'Daily return columns must match number of assets.');

assert(numel(data.daily.rf) == numel(daily_dates), ...
    'ResearchData:DailyRFMismatch', ...
    'Daily risk-free series must match the daily calendar.');

assert(numel(data.daily.market_excess) == numel(daily_dates), ...
    'ResearchData:DailyMarketMismatch', ...
    'Daily market-excess series must match the daily calendar.');

assert( ...
    issorted(daily_dates) && ...
    numel(unique(daily_dates)) == numel(daily_dates), ...
    'ResearchData:InvalidDailyCalendar', ...
    'Daily dates must be strictly increasing and unique.');

assert(all(isfinite(data.daily.rf)), ...
    'ResearchData:InvalidDailyRF', ...
    'Daily risk-free returns must be finite.');

assert(all(isfinite(data.daily.market_excess)), ...
    'ResearchData:InvalidMarketExcess', ...
    'Daily market-excess returns must be finite.');


%% Monthly data

required_monthly = { ...
    'dates', ...
    'returns', ...
    'rf'};

for k = 1:numel(required_monthly)

    assert(isfield(data.monthly, required_monthly{k}), ...
        'ResearchData:MissingMonthlyField', ...
        'Missing required field: data.monthly.%s', ...
        required_monthly{k});

end

monthly_dates   = data.monthly.dates(:);
monthly_returns = data.monthly.returns;

assert(isdatetime(monthly_dates), ...
    'ResearchData:InvalidMonthlyDates', ...
    'data.monthly.dates must be datetime.');

assert(size(monthly_returns,1) == numel(monthly_dates), ...
    'ResearchData:MonthlyRowMismatch', ...
    'Monthly return rows must match number of monthly dates.');

assert(size(monthly_returns,2) == N, ...
    'ResearchData:MonthlyAssetMismatch', ...
    'Monthly return columns must match number of assets.');

assert(numel(data.monthly.rf) == numel(monthly_dates), ...
    'ResearchData:MonthlyRFMismatch', ...
    'Monthly risk-free series must match the monthly calendar.');

assert( ...
    issorted(monthly_dates) && ...
    numel(unique(monthly_dates)) == numel(monthly_dates), ...
    'ResearchData:InvalidMonthlyCalendar', ...
    'Monthly dates must be strictly increasing and unique.');

assert(all(isfinite(data.monthly.rf)), ...
    'ResearchData:InvalidMonthlyRF', ...
    'Monthly risk-free returns must be finite.');


%% Market-cap observations

assert( ...
    isfield(data.market_cap, 'dates') && ...
    isfield(data.market_cap, 'values') && ...
    isfield(data.market_cap, 'valid'), ...
    'ResearchData:MissingMarketCapField', ...
    'data.market_cap must contain dates, values and valid.');

market_cap_dates = data.market_cap.dates(:);
market_cap       = data.market_cap.values;

assert(isdatetime(market_cap_dates), ...
    'ResearchData:InvalidMarketCapDates', ...
    'data.market_cap.dates must be datetime.');

assert(size(market_cap,1) == numel(market_cap_dates), ...
    'ResearchData:MarketCapRowMismatch', ...
    'Market-cap rows must match number of market-cap dates.');

assert(size(market_cap,2) == N, ...
    'ResearchData:MarketCapAssetMismatch', ...
    'Market-cap columns must match number of assets.');

assert( ...
    issorted(market_cap_dates) && ...
    numel(unique(market_cap_dates)) == numel(market_cap_dates), ...
    'ResearchData:InvalidMarketCapCalendar', ...
    'Market-cap dates must be strictly increasing and unique.');

% Market cap may legitimately be NaN when an asset is unavailable.
valid_cap = ~isnan(market_cap);

assert(all(market_cap(valid_cap) > 0), ...
    'ResearchData:InvalidMarketCap', ...
    'Observed market-cap values must be strictly positive.');

assert( ...
    islogical(data.market_cap.valid) && ...
    isequal(size(data.market_cap.valid), size(market_cap)), ...
    'ResearchData:InvalidMarketCapValidity', ...
    'data.market_cap.valid must be a logical matrix of the same size as values.');


%% Availability

assert( ...
    isfield(data.availability, 'dates') && ...
    isfield(data.availability, 'available'), ...
    'ResearchData:MissingAvailabilityField', ...
    'data.availability must contain dates and available.');

availability_dates = data.availability.dates(:);
availability       = data.availability.available;

assert(isdatetime(availability_dates), ...
    'ResearchData:InvalidAvailabilityDates', ...
    'data.availability.dates must be datetime.');

assert(size(availability,1) == numel(availability_dates), ...
    'ResearchData:AvailabilityRowMismatch', ...
    'Availability rows must match number of availability dates.');

assert(size(availability,2) == N, ...
    'ResearchData:AvailabilityAssetMismatch', ...
    'Availability columns must match number of assets.');

assert(islogical(availability), ...
    'ResearchData:InvalidAvailabilityType', ...
    'data.availability.available must be logical.');

assert( ...
    issorted(availability_dates) && ...
    numel(unique(availability_dates)) == numel(availability_dates), ...
    'ResearchData:InvalidAvailabilityCalendar', ...
    'Availability dates must be strictly increasing and unique.');


%% Return sanity

% NaN is allowed because securities can enter, exit, or have missing data.
% Infinite values are never valid observations.

assert(~any(isinf(daily_returns(:))), ...
    'ResearchData:InfiniteDailyReturn', ...
    'Daily returns must not contain Inf or -Inf.');

assert(~any(isinf(monthly_returns(:))), ...
    'ResearchData:InfiniteMonthlyReturn', ...
    'Monthly returns must not contain Inf or -Inf.');

% A simple return below -100% is impossible.

observed_daily = ...
    daily_returns(~isnan(daily_returns));

observed_monthly = ...
    monthly_returns(~isnan(monthly_returns));

assert(all(observed_daily >= -1), ...
    'ResearchData:ImpossibleDailyReturn', ...
    'Daily simple returns cannot be below -100%%.');

assert(all(observed_monthly >= -1), ...
    'ResearchData:ImpossibleMonthlyReturn', ...
    'Monthly simple returns cannot be below -100%%.');

end