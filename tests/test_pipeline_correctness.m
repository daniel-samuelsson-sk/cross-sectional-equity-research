function tests = test_pipeline_correctness
%TEST_PIPELINE_CORRECTNESS End-to-end correctness tests for the research pipeline.
%
% The tests use only the deterministic synthetic fixture and the research
% functions in src/.

tests = ...
    functiontests(localfunctions);

end


function setupOnce(testCase)

    test_file = ...
        mfilename('fullpath');

    tests_dir = ...
        fileparts(test_file);

    root = ...
        fileparts(tests_dir);

    src_dir = ...
        fullfile(root,'src');

    fixture_dir = ...
        fullfile(tests_dir,'fixtures');

    addpath(src_dir);
    addpath(fixture_dir);

    [data,cfg] = ...
        make_synthetic_research_fixture();

    validate_research_data(data);

    research = ...
        run_research_pipeline( ...
            data, ...
            cfg);

    testCase.TestData.data = ...
        data;

    testCase.TestData.cfg = ...
        cfg;

    testCase.TestData.research = ...
        research;

end


function testEndToEndKnownAnswer(testCase)

    data = ...
        testCase.TestData.data;

    research = ...
        testCase.TestData.research;

    ticker = ...
        data.assets.ticker;

    tstar = ...
        datetime(2020,11,30);


    %% Formation universe

    iu = ...
        row_for_month( ...
            research.universe.portfolio_month, ...
            tstar);

    eligible = ...
        research.universe.base_eligible(iu,:);

    expected_eligible = [ ...
        "A01" "A02" "A03" "A04" ...
        "A05" "A06" "A07" "A08" ...
        "A09" "A10" "A11" "A12" ...
        "A13" "A14" "A15" "A16"];

    verifyEqual(testCase, ...
        ticker(eligible), ...
        expected_eligible, ...
        ['The synthetic formation universe does not match the ' ...
         'documented known answer.']);


    %% Size buckets

    iz = ...
        row_for_month( ...
            research.size_control.portfolio_month, ...
            tstar);

    bucket = ...
        research.size_control.bucket(iz,:);

    expected_bucket_1 = [ ...
        "A01" "A02" "A03" "A04" ...
        "A05" "A06" "A07" "A08"];

    expected_bucket_2 = [ ...
        "A09" "A10" "A11" "A12" ...
        "A13" "A14" "A15" "A16"];

    verifyEqual(testCase, ...
        ticker(eligible & bucket == 1), ...
        expected_bucket_1, ...
        'Size bucket 1 does not match the documented known answer.');

    verifyEqual(testCase, ...
        ticker(eligible & bucket == 2), ...
        expected_bucket_2, ...
        'Size bucket 2 does not match the documented known answer.');


    %% Final selection

    ie = ...
        row_for_month( ...
            research.evaluation.selection.portfolio_month, ...
            tstar);

    final_selected = ...
        research.evaluation.selection.selected.final(ie,:);

    verifyEqual(testCase, ...
        ticker(final_selected), ...
        ["A06" "A14"], ...
        'FINAL selection does not match the documented known answer.');


    %% Final weights

    ip = ...
        row_for_month( ...
            research.evaluation.portfolios.portfolio_month, ...
            tstar);

    weights = ...
        research.evaluation.portfolios.weights.final(ip,:);

    i_a06 = ...
        asset_index(ticker,"A06");

    i_a14 = ...
        asset_index(ticker,"A14");

    verifyEqual(testCase, ...
        weights(i_a06), ...
        0.5, ...
        'A06 does not have the documented FINAL weight.');

    verifyEqual(testCase, ...
        weights(i_a14), ...
        0.5, ...
        'A14 does not have the documented FINAL weight.');

    verifyEqual(testCase, ...
        ticker(weights > 0), ...
        ["A06" "A14"], ...
        'FINAL positive-weight holdings do not match the known answer.');


    %% Calibration ranking

    ranked = ...
        research.calibration.ranked_candidates;

    verifyEqual(testCase, ...
        [ranked.momentum_pct, ranked.downside_pct, ranked.skew_pct], ...
        [50 40 50; 25 40 50], ...
        'The calibration ranking does not match the documented known answer.');

    verifyEqual(testCase, ...
        ranked.sharpe, ...
        [39.8813164650450; 19.8068283114989], ...
        'AbsTol',1e-10);

    verifyEqual(testCase, ...
        research.calibration.selected_rank, ...
        2);

end


function testSignalWindowTiming(testCase)

    data = ...
        testCase.TestData.data;

    cfg = ...
        testCase.TestData.cfg;

    baseline = ...
        testCase.TestData.research;

    ticker = ...
        data.assets.ticker;

    i_a06 = ...
        asset_index(ticker,"A06");

    tstar = ...
        datetime(2020,11,30);


    %% Baseline signals

    baseline_momentum = ...
        signal_value_at( ...
            baseline.signals.momentum, ...
            tstar, ...
            i_a06);

    baseline_downside = ...
        signal_value_at( ...
            baseline.signals.downside, ...
            tstar, ...
            i_a06);

    baseline_skew = ...
        signal_value_at( ...
            baseline.signals.idio_skew, ...
            tstar, ...
            i_a06);


    %% Derive signal-window months from cfg
    %
    % These dates are deliberately derived from the configured lags rather
    % than from calendar output so that the test remains capable of
    % detecting an incorrect calendar implementation.

    momentum_start_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.momentum.start_lag_months), ...
            'end', ...
            'month');

    downside_start_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.downside.start_lag_months), ...
            'end', ...
            'month');

    skew_start_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.idio_skew.start_lag_months), ...
            'end', ...
            'month');

    momentum_excluded_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.momentum.end_lag_months - 1), ...
            'end', ...
            'month');

    downside_excluded_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.downside.end_lag_months - 1), ...
            'end', ...
            'month');

    skew_excluded_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.idio_skew.end_lag_months - 1), ...
            'end', ...
            'month');

    current_month = ...
        dateshift( ...
            tstar, ...
            'end', ...
            'month');

    momentum_end_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.momentum.end_lag_months), ...
            'end', ...
            'month');

    downside_end_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.downside.end_lag_months), ...
            'end', ...
            'month');

    skew_end_month = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.idio_skew.end_lag_months), ...
            'end', ...
            'month');


    %% Positive control: start-lag month must affect all three signals

    changed_start = ...
        data;

    monthly_row = ...
        exact_date_row( ...
            changed_start.monthly.dates, ...
            momentum_start_month);

    start_daily_rows = ...
        unique([ ...
            first_daily_row_in_month( ...
                changed_start.daily.dates, ...
                downside_start_month); ...
            first_daily_row_in_month( ...
                changed_start.daily.dates, ...
                skew_start_month)]);

    changed_start.monthly.returns(monthly_row,i_a06) = ...
        changed_start.monthly.returns(monthly_row,i_a06) + ...
        0.10;

    changed_start.daily.returns(start_daily_rows,i_a06) = ...
        changed_start.daily.returns(start_daily_rows,i_a06) + ...
        0.001;

    verifyTrue(testCase, ...
        isfinite( ...
            changed_start.monthly.returns(monthly_row,i_a06)) && ...
        changed_start.monthly.returns(monthly_row,i_a06) >= -1, ...
        'The momentum start-lag perturbation must remain a valid return.');

    verifyTrue(testCase, ...
        all(isfinite( ...
            changed_start.daily.returns( ...
                start_daily_rows, ...
                i_a06))) && ...
        all( ...
            changed_start.daily.returns( ...
                start_daily_rows, ...
                i_a06) >= -1), ...
        'The daily start-lag perturbation must remain a valid return.');

    changed_start_research = ...
        run_research_pipeline( ...
            changed_start, ...
            cfg);

    changed_start_momentum = ...
        signal_value_at( ...
            changed_start_research.signals.momentum, ...
            tstar, ...
            i_a06);

    changed_start_downside = ...
        signal_value_at( ...
            changed_start_research.signals.downside, ...
            tstar, ...
            i_a06);

    changed_start_skew = ...
        signal_value_at( ...
            changed_start_research.signals.idio_skew, ...
            tstar, ...
            i_a06);

    verifyFalse(testCase, ...
        isequaln( ...
            changed_start_momentum, ...
            baseline_momentum), ...
        'Changing the configured start-lag month did not change momentum.');

    verifyFalse(testCase, ...
        isequaln( ...
            changed_start_downside, ...
            baseline_downside), ...
        ['Changing a daily return in the configured start-lag month ' ...
         'did not change downside deviation.']);

    verifyFalse(testCase, ...
        isequaln( ...
            changed_start_skew, ...
            baseline_skew), ...
        ['Changing a daily return in the configured start-lag month ' ...
         'did not change idiosyncratic skewness.']);


    %% Positive control: end-lag month must affect all three signals

    changed_end = ...
        data;

    monthly_row = ...
        exact_date_row( ...
            changed_end.monthly.dates, ...
            momentum_end_month);

    end_daily_rows = ...
        unique([ ...
            first_daily_row_in_month( ...
                changed_end.daily.dates, ...
                downside_end_month); ...
            first_daily_row_in_month( ...
                changed_end.daily.dates, ...
                skew_end_month)]);

    changed_end.monthly.returns(monthly_row,i_a06) = ...
        changed_end.monthly.returns(monthly_row,i_a06) + ...
        0.10;

    changed_end.daily.returns(end_daily_rows,i_a06) = ...
        changed_end.daily.returns(end_daily_rows,i_a06) + ...
        0.001;

    changed_end_research = ...
        run_research_pipeline( ...
            changed_end, ...
            cfg);

    verifyFalse(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_end_research.signals.momentum, ...
                tstar, ...
                i_a06), ...
            baseline_momentum), ...
        'Changing the configured end-lag month did not change momentum.');

    verifyFalse(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_end_research.signals.downside, ...
                tstar, ...
                i_a06), ...
            baseline_downside), ...
        ['Changing a daily return in the configured end-lag month ' ...
         'did not change downside deviation.']);

    verifyFalse(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_end_research.signals.idio_skew, ...
                tstar, ...
                i_a06), ...
            baseline_skew), ...
        ['Changing a daily return in the configured end-lag month ' ...
         'did not change idiosyncratic skewness.']);


    %% Excluded most-recent month must not affect the signals

    changed_excluded = ...
        data;

    monthly_row = ...
        exact_date_row( ...
            changed_excluded.monthly.dates, ...
            momentum_excluded_month);

    excluded_daily_rows = ...
        unique([ ...
            first_daily_row_in_month( ...
                changed_excluded.daily.dates, ...
                downside_excluded_month); ...
            first_daily_row_in_month( ...
                changed_excluded.daily.dates, ...
                skew_excluded_month)]);

    changed_excluded.monthly.returns(monthly_row,i_a06) = ...
        changed_excluded.monthly.returns(monthly_row,i_a06) + ...
        0.10;

    changed_excluded.daily.returns(excluded_daily_rows,i_a06) = ...
        changed_excluded.daily.returns(excluded_daily_rows,i_a06) + ...
        0.001;

    verifyTrue(testCase, ...
        isfinite( ...
            changed_excluded.monthly.returns(monthly_row,i_a06)) && ...
        changed_excluded.monthly.returns(monthly_row,i_a06) >= -1, ...
        ['The excluded-month momentum perturbation must remain a ' ...
         'valid return.']);

    verifyTrue(testCase, ...
        all(isfinite( ...
            changed_excluded.daily.returns( ...
                excluded_daily_rows, ...
                i_a06))) && ...
        all( ...
            changed_excluded.daily.returns( ...
                excluded_daily_rows, ...
                i_a06) >= -1), ...
        ['The excluded-month daily perturbation must remain a ' ...
         'valid return.']);

    changed_excluded_research = ...
        run_research_pipeline( ...
            changed_excluded, ...
            cfg);

    verifyTrue(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_excluded_research.signals.momentum, ...
                tstar, ...
                i_a06), ...
            baseline_momentum), ...
        'The excluded most-recent month changed momentum at t*.');

    verifyTrue(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_excluded_research.signals.downside, ...
                tstar, ...
                i_a06), ...
            baseline_downside), ...
        'The excluded most-recent month changed downside deviation at t*.');

    verifyTrue(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_excluded_research.signals.idio_skew, ...
                tstar, ...
                i_a06), ...
            baseline_skew), ...
        ['The excluded most-recent month changed idiosyncratic ' ...
         'skewness at t*.']);


    %% Current portfolio month must not affect the signals

    changed_current = ...
        data;

    monthly_row = ...
        exact_date_row( ...
            changed_current.monthly.dates, ...
            current_month);

    current_daily_row = ...
        first_daily_row_in_month( ...
            changed_current.daily.dates, ...
            current_month);

    changed_current.monthly.returns(monthly_row,i_a06) = ...
        changed_current.monthly.returns(monthly_row,i_a06) + ...
        0.10;

    changed_current.daily.returns(current_daily_row,i_a06) = ...
        changed_current.daily.returns(current_daily_row,i_a06) + ...
        0.001;

    verifyTrue(testCase, ...
        isfinite( ...
            changed_current.monthly.returns(monthly_row,i_a06)) && ...
        changed_current.monthly.returns(monthly_row,i_a06) >= -1, ...
        ['The current-month momentum perturbation must remain a ' ...
         'valid return.']);

    verifyTrue(testCase, ...
        isfinite( ...
            changed_current.daily.returns(current_daily_row,i_a06)) && ...
        changed_current.daily.returns(current_daily_row,i_a06) >= -1, ...
        ['The current-month daily perturbation must remain a ' ...
         'valid return.']);

    changed_current_research = ...
        run_research_pipeline( ...
            changed_current, ...
            cfg);

    verifyTrue(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_current_research.signals.momentum, ...
                tstar, ...
                i_a06), ...
            baseline_momentum), ...
        'The current portfolio month changed momentum at t*.');

    verifyTrue(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_current_research.signals.downside, ...
                tstar, ...
                i_a06), ...
            baseline_downside), ...
