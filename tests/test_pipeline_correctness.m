            dates(:) == target_date);

    if numel(matches) ~= 1

        error( ...
            'PipelineCorrectness:DateLookupFailure', ...
            'Expected exactly one input row dated %s.', ...
            string(target_date));

    end

    row = ...
        matches;

end


function row = first_daily_row_in_month(dates, target_month)
