    verifyTrue(testCase, ...
        isequaln( ...
            signal_value_at( ...
                changed_current_research.signals.idio_skew, ...
                tstar, ...
                i_a06), ...
            baseline_skew), ...
        'The current portfolio month changed idiosyncratic skewness at t*.');

