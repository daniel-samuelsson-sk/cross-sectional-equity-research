function modified = perturb_numeric_inputs_after(data, boundary)
%PERTURB_NUMERIC_INPUTS_AFTER Perturb dated numeric inputs after a boundary.
%
% The perturbations are deterministic and preserve the standardized data
% contract. Availability is deliberately left unchanged by this helper.

    modified = ...
        data;


    %% Monthly returns and risk-free rate

    monthly_rows = ...
        modified.monthly.dates > ...
        boundary;

    modified.monthly.returns(monthly_rows,:) = ...
        modified.monthly.returns(monthly_rows,:) + ...
        0.05;

    modified.monthly.rf(monthly_rows) = ...
        modified.monthly.rf(monthly_rows) + ...
        0.002;


    %% Daily returns, risk-free rate and market factor

    daily_rows = ...
        modified.daily.dates > ...
        boundary;

    modified.daily.returns(daily_rows,:) = ...
        modified.daily.returns(daily_rows,:) + ...
        0.001;

    modified.daily.rf(daily_rows) = ...
        modified.daily.rf(daily_rows) + ...
        0.0002;

    modified.daily.market_excess(daily_rows) = ...
        modified.daily.market_excess(daily_rows) + ...
        0.0003;


    %% Market capitalization

    market_cap_rows = ...
        modified.market_cap.dates > ...
        boundary;

    modified.market_cap.values(market_cap_rows,:) = ...
        1.25 * ...
        modified.market_cap.values(market_cap_rows,:);

end


function out = subset_output_through_month(input, target_month)
%SUBSET_OUTPUT_THROUGH_MONTH Retain row-aligned output through one month.

    portfolio_month = ...
        input.portfolio_month(:);

    rows = ...
        portfolio_month <= target_month;

    n_rows = ...
        numel(portfolio_month);

    out = ...
        slice_row_aligned_fields( ...
            input, ...
            rows, ...
            n_rows);

end


function out = slice_row_aligned_fields(input, rows, n_rows)
%SLICE_ROW_ALIGNED_FIELDS Slice row-aligned fields inside a scalar struct.

    out = ...
        input;

    names = ...
        fieldnames(input);

    for k = 1:numel(names)

        name = ...
            names{k};

        value = ...
            input.(name);

        if isstruct(value) && isscalar(value)

            out.(name) = ...
                slice_row_aligned_fields( ...
                    value, ...
                    rows, ...
                    n_rows);

        elseif istable(value) && ...
               height(value) == n_rows

            out.(name) = ...
                value(rows,:);

        elseif ~isempty(value) && ...
               size(value,1) == n_rows

            out.(name) = ...
                value(rows,:);

        else

            out.(name) = ...
                value;

        end

    end

end


function out = portfolio_weights_through_month( ...
    portfolios, ...
    target_month)
%PORTFOLIO_WEIGHTS_THROUGH_MONTH Retain portfolio weights through one month.

    wrapper.portfolio_month = ...
        portfolios.portfolio_month;

    wrapper.weights = ...
        portfolios.weights;

    out = ...
        subset_output_through_month( ...
            wrapper, ...
            target_month);

end