function testMarketCapTiming(testCase)

    data = ...
        testCase.TestData.data;

    cfg = ...
        testCase.TestData.cfg;

    baseline = ...
        testCase.TestData.research;

    ticker = ...
        data.assets.ticker;

    tstar = ...
        datetime(2020,11,30);

    i_a01 = ...
        asset_index(ticker,"A01");

    i_a09 = ...
        asset_index(ticker,"A09");


    %% Independently defined information boundary

    information_cutoff = ...
        dateshift( ...
            tstar - calmonths(1), ...
            'end', ...
            'month');

    ic = ...
        row_for_month( ...
            baseline.calendar.portfolio_month, ...
            tstar);

    verifyEqual(testCase, ...
        baseline.calendar.information_cutoff(ic), ...
        information_cutoff, ...
        ['The research calendar does not use the documented end-of-t-1 ' ...
         'information boundary.']);

    cap_row = ...
        exact_date_row( ...
            data.market_cap.dates, ...
            information_cutoff);


    %% Baseline assignments

    iz = ...
        row_for_month( ...
            baseline.size_control.portfolio_month, ...
            tstar);

    baseline_bucket = ...
        baseline.size_control.bucket(iz,:);

    verifyEqual(testCase, ...
        baseline_bucket(i_a01), ...
        1, ...
        'A01 must begin in size bucket 1.');

    verifyEqual(testCase, ...
        baseline_bucket(i_a09), ...
        2, ...
        'A09 must begin in size bucket 2.');


    %% Positive control at the exact information boundary

    modified = ...
        data;

    modified.market_cap.values(cap_row,i_a01) = ...
        255;

    changed = ...
        run_research_pipeline( ...
            modified, ...
            cfg);

    iz_changed = ...
        row_for_month( ...
            changed.size_control.portfolio_month, ...
            tstar);

    changed_bucket = ...
        changed.size_control.bucket(iz_changed,:);

    verifyEqual(testCase, ...
        changed_bucket(i_a01), ...
        2, ...
        ['Changing A01 market capitalization exactly at the information ' ...
         'boundary did not move A01 into size bucket 2.']);

    verifyEqual(testCase, ...
        changed_bucket(i_a09), ...
        1, ...
        ['The planted market-cap boundary change did not move A09 into ' ...
         'size bucket 1 as expected.']);

end


function testPipelineFutureInvariance(testCase)

    data = ...
        testCase.TestData.data;

    cfg = ...
        testCase.TestData.cfg;

    baseline = ...
        testCase.TestData.research;

    tstar = ...
        datetime(2020,11,30);


    %% Independently defined information boundary

    information_cutoff = ...
        dateshift( ...
            tstar - calmonths(1), ...
            'end', ...
            'month');

    ic = ...
        row_for_month( ...
            baseline.calendar.portfolio_month, ...
            tstar);

    verifyEqual(testCase, ...
        baseline.calendar.information_cutoff(ic), ...
        information_cutoff, ...
        ['The research calendar does not use the documented end-of-t-1 ' ...
         'information boundary.']);


    %% Perturb every specified numeric input strictly after the boundary

    modified = ...
        perturb_numeric_inputs_after( ...
            data, ...
            information_cutoff);

    verifyTrue(testCase, ...
        isequaln( ...
            modified.availability, ...
            data.availability), ...
        'Availability must remain fixed in the future-invariance test.');

    changed = ...
        run_research_pipeline( ...
            modified, ...
            cfg);


    %% Formation universe through t*

    verifyTrue(testCase, ...
        isequaln( ...
            subset_output_through_month( ...
                baseline.universe, ...
                tstar), ...
            subset_output_through_month( ...
                changed.universe, ...
                tstar)), ...
        ['Formation-universe output changed at or before t* after only ' ...
         'post-boundary numeric inputs were perturbed.']);


    %% Size control through t*

    verifyTrue(testCase, ...
        isequaln( ...
            subset_output_through_month( ...
                baseline.size_control, ...
                tstar), ...
            subset_output_through_month( ...
                changed.size_control, ...
                tstar)), ...
        ['Size-bucket output changed at or before t* after only ' ...
         'post-boundary numeric inputs were perturbed.']);


    %% All three signals through t*

    verifyTrue(testCase, ...
        isequaln( ...
            subset_output_through_month( ...
                baseline.signals.momentum, ...
                tstar), ...
            subset_output_through_month( ...
                changed.signals.momentum, ...
                tstar)), ...
        ['Momentum output changed at or before t* after only ' ...
         'post-boundary numeric inputs were perturbed.']);

    verifyTrue(testCase, ...
        isequaln( ...
            subset_output_through_month( ...
                baseline.signals.downside, ...
                tstar), ...
            subset_output_through_month( ...
                changed.signals.downside, ...
                tstar)), ...
        ['Downside-deviation output changed at or before t* after only ' ...
         'post-boundary numeric inputs were perturbed.']);

    verifyTrue(testCase, ...
        isequaln( ...
            subset_output_through_month( ...
                baseline.signals.idio_skew, ...
                tstar), ...
            subset_output_through_month( ...
                changed.signals.idio_skew, ...
                tstar)), ...
        ['Idiosyncratic-skewness output changed at or before t* after ' ...
         'only post-boundary numeric inputs were perturbed.']);


    %% Evaluation selections through t*

    verifyTrue(testCase, ...
        isequaln( ...
            subset_output_through_month( ...
                baseline.evaluation.selection, ...
                tstar), ...
            subset_output_through_month( ...
                changed.evaluation.selection, ...
                tstar)), ...
        ['Evaluation selection changed at or before t* after only ' ...
         'post-boundary numeric inputs were perturbed.']);


    %% Evaluation portfolio weights through t*

    verifyTrue(testCase, ...
        isequaln( ...
            portfolio_weights_through_month( ...
                baseline.evaluation.portfolios, ...
                tstar), ...
            portfolio_weights_through_month( ...
                changed.evaluation.portfolios, ...
                tstar)), ...
        ['Evaluation portfolio weights changed at or before t* after ' ...
         'only post-boundary numeric inputs were perturbed.']);


    %% Calibration must remain exactly unchanged

    verifyTrue(testCase, ...
        isequaln( ...
            baseline.calibration, ...
            changed.calibration), ...
        ['Calibration changed after perturbing only inputs strictly ' ...
         'after the t* information boundary.']);


    %% Positive control: realized FINAL return in t* must change

    baseline_return = ...
        portfolio_return_at( ...
            baseline.evaluation.performance, ...
            "final", ...
            tstar);

    changed_return = ...
        portfolio_return_at( ...
            changed.evaluation.performance, ...
            "final", ...
            tstar);

    verifyFalse(testCase, ...
        isequaln( ...
            baseline_return, ...
            changed_return), ...
        ['The post-boundary perturbation did not change the realized ' ...
         'FINAL return in t*.']);

end


