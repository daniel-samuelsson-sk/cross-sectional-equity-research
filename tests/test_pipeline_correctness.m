function testDownsideDeviationUsesExcessReturns(testCase)
% The fixture's daily risk-free rate is zero, so the other tests cannot
% tell excess returns from raw returns. This test sets a non-zero,
% time-varying rate and compares one signal value with the definition,
% computed directly from the daily data.

    data = ...
        testCase.TestData.data;

    cfg = ...
        testCase.TestData.cfg;

    data.daily.rf = ...
        0.0002 + ...
        0.0001 .* sin((1:numel(data.daily.dates))');

    downside = ...
        compute_downside_deviation( ...
            data, ...
            build_research_calendar(data, cfg), ...
            cfg);

    tstar = ...
        datetime(2020,11,30);

    i_a06 = ...
        asset_index(data.assets.ticker,"A06");

    window_start = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.downside.start_lag_months), ...
            'start', ...
            'month');

    window_end = ...
        dateshift( ...
            tstar - ...
            calmonths( ...
                cfg.signals.downside.end_lag_months), ...
            'end', ...
            'month');

    rows = ...
        data.daily.dates >= window_start & ...
        data.daily.dates <= window_end;

    excess_returns = ...
        data.daily.returns(rows,i_a06) - ...
        data.daily.rf(rows);

    verifyEqual(testCase, ...
        signal_value_at(downside, tstar, i_a06), ...
        sqrt(mean(min(excess_returns,0).^2)), ...
        'AbsTol',1e-12, ...
        'Downside deviation is not computed from daily excess returns.');

end


function row = row_for_month(portfolio_month, target_month)
%ROW_FOR_MONTH Locate one portfolio month in an output calendar.

    matches = ...
        find( ...
            portfolio_month(:) == target_month);

    if numel(matches) ~= 1

        error( ...
            'PipelineCorrectness:PortfolioMonthLookupFailure', ...
            'Expected exactly one output row for %s.', ...
            string(target_month));

    end

    row = ...
        matches;

end


function row = exact_date_row(dates, target_date)
%EXACT_DATE_ROW Locate one exact date in an input calendar.

