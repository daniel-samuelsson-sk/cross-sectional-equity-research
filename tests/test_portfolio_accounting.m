function tests = test_portfolio_accounting
%TEST_PORTFOLIO_ACCOUNTING Hand-calculated portfolio accounting tests.
%
% All expected values are calculated by hand from a two-asset,
% three-month synthetic case. No source data are required.

tests = functiontests(localfunctions);

end


function setupOnce(testCase) %#ok<INUSD>

    root = ...
        fileparts(fileparts(mfilename('fullpath')));

    addpath(fullfile(root,'src'));

end


function testDriftAdjustedTurnoverHandCalculation(testCase)

    [data,portfolios,calendar,cfg] = ...
        make_synthetic_case();

    result = ...
        evaluate_performance( ...
            data, ...
            portfolios, ...
            calendar, ...
            cfg);

    % Month 1 target:
    %   [0.5 0.5]
    %
    % Month 1 realized returns:
    %   [+10%, -10%]
    %
    % Pre-trade weights entering month 2:
    %
    %   [0.5*1.10, 0.5*0.90] / 1.00
    %   = [0.55, 0.45]
    %
    % Month 2 target:
    %   [0.5, 0.5]
    %
    % Turnover:
    %   0.5 * (|0.50-0.55| + |0.50-0.45|)
    %   = 0.05

    verifyTrue(testCase, ...
        isnan(result.turnover.test(1)));

    verifyEqual(testCase, ...
        result.turnover.test(2), ...
        0.05, ...
        'AbsTol',1e-12);

    % Month 2 returns are zero, so weights do not drift.
    %
    % Month 3 target moves from [0.5 0.5] to [1 0]:
    %
    % turnover = 0.5*(0.5 + 0.5) = 0.5

    verifyEqual(testCase, ...
        result.turnover.test(3), ...
        0.50, ...
        'AbsTol',1e-12);

end


function testSyntheticPortfolioReturns(testCase)

    [data,portfolios,calendar,cfg] = ...
        make_synthetic_case();

    result = ...
        evaluate_performance( ...
            data, ...
            portfolios, ...
            calendar, ...
            cfg);

    % Month 1:
    % 0.5*(+10%) + 0.5*(-10%) = 0%
    %
    % Month 2:
    % both returns 0%
    %
    % Month 3:
    % 100% asset 1 with +5% return

    expected = ...
        [0; 0; 0.05];

    verifyEqual(testCase, ...
        result.returns.test, ...
        expected, ...
        'AbsTol',1e-12);

    % A missing return for an asset that is not held (asset 2 in month 3)
    % must neither change the portfolio return nor invalidate the month.

    data.monthly.returns(3,2) = ...
        NaN;

    unheld_missing = ...
        evaluate_performance( ...
            data, ...
            portfolios, ...
            calendar, ...
            cfg);

    verifyEqual(testCase, ...
        unheld_missing.returns.test, ...
        expected, ...
        'AbsTol',1e-12);

    verifyTrue(testCase, ...
        all(unheld_missing.valid_return.test));

end


function testSyntheticSummaryMetrics(testCase)

    [data,portfolios,calendar,cfg] = ...
        make_synthetic_case();

    result = ...
        evaluate_performance( ...
            data, ...
            portfolios, ...
            calendar, ...
            cfg);

    summary = ...
        result.summary.full_sample.test;

    r = ...
        [0; 0; 0.05];

    rf = ...
        [0.001; 0.002; 0.003];

    ex = ...
        r - rf;

    expected_ann_return = ...
        12 * mean(r);

    expected_ann_vol = ...
        sqrt(12) * std(r,0);

    expected_ann_excess = ...
        12 * mean(ex);

    expected_sharpe = ...
        sqrt(12) * ...
        mean(ex) / std(ex,0);

    expected_cagr = ...
        prod(1+r)^(12/3) - 1;

    verifyTrue(testCase, ...
        summary.complete_return_series);

    verifyEqual(testCase, ...
        summary.annualized_total_return, ...
        expected_ann_return, ...
        'AbsTol',1e-12);

    verifyEqual(testCase, ...
        summary.annualized_volatility, ...
        expected_ann_vol, ...
        'AbsTol',1e-12);

    verifyEqual(testCase, ...
        summary.annualized_excess_return, ...
        expected_ann_excess, ...
        'AbsTol',1e-12);

    verifyEqual(testCase, ...
        summary.sharpe, ...
        expected_sharpe, ...
        'AbsTol',1e-12);

    verifyEqual(testCase, ...
        summary.cagr, ...
        expected_cagr, ...
        'AbsTol',1e-12);

end


function testMaximumDrawdownHandCalculation(testCase)

    [data,portfolios,calendar,cfg] = ...
        make_synthetic_case();

    % Replace returns so the portfolio itself realizes:
    %
    % month 1: +10%
    % month 2: -20%
    % month 3: +5%
    %
    % Wealth:
    % 1.00 -> 1.10 -> 0.88 -> 0.924
    %
    % Maximum drawdown:
    % 1 - 0.88/1.10 = 20%

    data.monthly.returns = ...
        [ ...
            0.10  0.10; ...
           -0.20 -0.20; ...
            0.05  0.05];

    result = ...
        evaluate_performance( ...
            data, ...
            portfolios, ...
            calendar, ...
            cfg);

    verifyEqual(testCase, ...
        result.summary.full_sample.test.maximum_drawdown, ...
        0.20, ...
        'AbsTol',1e-12);

    % A loss in the first month must be measured from the initial wealth:
    %
    % Wealth:
    % 1.00 -> 0.80 -> 0.88 -> 0.924
    %
    % Maximum drawdown:
    % 1 - 0.80/1.00 = 20%

    data.monthly.returns = ...
        [ ...
           -0.20 -0.20; ...
            0.10  0.10; ...
            0.05  0.05];

    result = ...
        evaluate_performance( ...
            data, ...
            portfolios, ...
            calendar, ...
            cfg);

    verifyEqual(testCase, ...
        result.summary.full_sample.test.maximum_drawdown, ...
        0.20, ...
        'AbsTol',1e-12);

end


function testIncompleteSeriesDoesNotProduceHeadlineMetrics(testCase)

    [data,portfolios,calendar,cfg] = ...
        make_synthetic_case();

    % Both assets are held in month 3, and the return of asset 1 is
    % missing. Dropping asset 1 and renormalizing would turn month 3 into
    % a valid -2% month. The month must instead be invalid.

    portfolios.weights.test(3,:) = ...
        [0.5 0.5];

    portfolios.n_holdings.test(3) = ...
        2;

    data.monthly.returns(3,1) = ...
        NaN;

    result = ...
        evaluate_performance( ...
            data, ...
            portfolios, ...
            calendar, ...
            cfg);

    summary = ...
        result.summary.full_sample.test;

    verifyFalse(testCase, ...
        summary.complete_return_series);

    verifyEqual(testCase, ...
        summary.n_invalid_returns, ...
        1);

    verifyTrue(testCase, ...
        isnan(summary.annualized_total_return));

    verifyTrue(testCase, ...
        isnan(summary.cagr));

    verifyTrue(testCase, ...
        isnan(summary.annualized_volatility));

    verifyTrue(testCase, ...
        isnan(summary.annualized_excess_return));

    verifyTrue(testCase, ...
        isnan(summary.sharpe));

    verifyTrue(testCase, ...
        isnan(summary.maximum_drawdown));

end


function [data,portfolios,calendar,cfg] = make_synthetic_case()
%MAKE_SYNTHETIC_CASE Build a minimal valid provider-neutral research case.

cfg = ...
    default_config();


%% Assets

data.assets.id = ...
    [101 102];

data.assets.ticker = ...
    ["AAA" "BBB"];

data.assets.security_type = ["unknown" "unknown"];


%% Monthly data

data.monthly.dates = [ ...
    datetime(2020,1,31); ...
    datetime(2020,2,29); ...
    datetime(2020,3,31)];

data.monthly.returns = [ ...
     0.10  -0.10; ...
     0.00   0.00; ...
     0.05  -0.02];

% The risk-free rate differs by month, so excess returns that use the
% wrong month's rate change the expected values.
data.monthly.rf = ...
    [0.001; 0.002; 0.003];


%% Minimal daily data required by the standard data contract

data.daily.dates = [ ...
    datetime(2020,1,2); ...
    datetime(2020,2,3); ...
    datetime(2020,3,2)];

data.daily.returns = [ ...
    0.001  0.002; ...
    0.001  0.002; ...
    0.001  0.002];

data.daily.rf = ...
    [0; 0; 0];

data.daily.market_excess = ...
    [0.001; 0.002; 0.003];


%% Market capitalization

data.market_cap.dates = [ ...
    datetime(2019,12,31); ...
    datetime(2020,1,31); ...
    datetime(2020,2,29)];

data.market_cap.values = [ ...
    100 100; ...
    100 100; ...
    100 100];

data.market_cap.valid = ...
    true(3,2);


%% Availability

data.availability.dates = ...
    data.monthly.dates;

data.availability.available = ...
    true(3,2);


%% Metadata

data.meta.provider = ...
    "synthetic";

data.meta.n_assets = ...
    2;

data.meta.n_months = ...
    3;

data.meta.n_days = ...
    3;


%% Calendar

portfolio_month = ...
    data.monthly.dates;

phase = [ ...
    "calibration"; ...
    "calibration"; ...
    "evaluation"];

calendar = ...
    table( ...
        portfolio_month, ...
        phase);


%% Target portfolios

portfolios.portfolio_month = ...
    portfolio_month;

portfolios.weights.test = [ ...
    0.5 0.5; ...
    0.5 0.5; ...
    1.0 0.0];

portfolios.valid.test = ...
    true(3,1);

portfolios.n_holdings.test = ...
    [2; 2; 1];

end
