function testPortfolioSpecification(testCase)

    cfg = ...
        testCase.TestData.cfg;

    verifyTrue(testCase, ...
        cfg.portfolio.long_only);

    verifyTrue(testCase, ...
        cfg.portfolio.fully_invested);

    verifyEqual(testCase, ...
        cfg.portfolio.strategy_weighting, ...
        "equal");

    verifyEqual(testCase, ...
        cfg.portfolio.empty_month_policy, ...
        "invalid");

    verifyEqual(testCase, ...
        cfg.turnover.method, ...
        "drift_adjusted");

end