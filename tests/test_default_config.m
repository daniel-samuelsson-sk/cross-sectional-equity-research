function tests = test_default_config
%TEST_DEFAULT_CONFIG Specification lock for the published study.
%
% These tests check that default_config equals the published specification
% so that accidental changes are detected. They do not test calculations.

tests = functiontests(localfunctions);

end


function setupOnce(testCase)

    test_file = ...
        mfilename('fullpath');

    tests_dir = ...
        fileparts(test_file);

    root = ...
        fileparts(tests_dir);

    addpath(fullfile(root,'src'));

    testCase.TestData.cfg = ...
        default_config();

end


function testResearchPeriods(testCase)

    cfg = ...
        testCase.TestData.cfg;

    verifyEqual(testCase, ...
        cfg.periods.calibration_start, ...
        datetime(1981,1,31));

    verifyEqual(testCase, ...
        cfg.periods.calibration_end, ...
        datetime(1989,12,31));

    verifyEqual(testCase, ...
        cfg.periods.evaluation_start, ...
        datetime(1990,1,31));

    verifyEqual(testCase, ...
        cfg.periods.evaluation_end, ...
        datetime(2023,12,31));

end


function testUniverseSpecification(testCase)

    cfg = ...
