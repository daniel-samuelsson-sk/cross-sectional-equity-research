function testVarianceIdentity(testCase)
% Verify the sample-variance CAPM decomposition.

T = ...
    60;


portfolio_month = ...
    dateshift( ...
        ( ...
            datetime(2000,1,1): ...
            calmonths(1): ...
            datetime(2004,12,1) ...
        )', ...
        'end', ...
        'month');


verifyEqual( ...
    testCase, ...
    numel(portfolio_month), ...
    T);


t = ...
    (1:T)';


market_excess = ...
    0.012 .* sin(0.43 .* t) + ...
    0.006 .* cos(0.17 .* t) + ...
    0.00005 .* (t - mean(t));


portfolio_excess = ...
    0.0015 + ...
    0.78 .* market_excess + ...
    0.004 .* sin(0.91 .* t) - ...
    0.002 .* cos(0.37 .* t);


fit = ...
    estimate_capm_regression( ...
        portfolio_month, ...
        portfolio_excess, ...
        market_excess);


reconstructed_variance = ...
    fit.beta^2 .* ...
    var(market_excess,0) + ...
    var(fit.residuals,0);


verifyEqual( ...
    testCase, ...
    fit.portfolio_excess_variance, ...
    reconstructed_variance, ...
    'AbsTol', ...
    1e-12);


verifyLessThanOrEqual( ...
    testCase, ...
    abs(fit.variance_identity_error), ...
    1e-12);

end


function testDifferencePortfolioOLSLinearity(testCase)
% Verify point-estimate linearity for an aligned difference portfolio.

T = ...
    72;


portfolio_month = ...
    dateshift( ...
        ( ...
            datetime(2001,1,1): ...
            calmonths(1): ...
            datetime(2006,12,1) ...
        )', ...
        'end', ...
        'month');


verifyEqual( ...
    testCase, ...
    numel(portfolio_month), ...
    T);


t = ...
    (1:T)';


market_excess = ...
    0.011 .* sin(0.31 .* t) + ...
    0.007 .* cos(0.13 .* t);


portfolio_A = ...
    0.0010 + ...
    1.10 .* market_excess + ...
    0.004 .* sin(0.59 .* t);


portfolio_B = ...
    0.0025 + ...
    0.72 .* market_excess + ...
    0.003 .* cos(0.47 .* t);


difference_return = ...
    portfolio_B - ...
    portfolio_A;


fit_A = ...
    estimate_capm_regression( ...
        portfolio_month, ...
        portfolio_A, ...
        market_excess);


fit_B = ...
    estimate_capm_regression( ...
        portfolio_month, ...
        portfolio_B, ...
        market_excess);


fit_difference = ...
    estimate_capm_regression( ...
        portfolio_month, ...
        difference_return, ...
        market_excess);


verifyEqual( ...
    testCase, ...
    fit_difference.alpha_monthly, ...
    fit_B.alpha_monthly - ...
        fit_A.alpha_monthly, ...
    'AbsTol', ...
    1e-12);


verifyEqual( ...
    testCase, ...
    fit_difference.beta, ...
    fit_B.beta - ...
        fit_A.beta, ...
    'AbsTol', ...
    1e-12);

end


function testKnownCoefficientRecovery(testCase)
% Recover known alpha and beta with residual orthogonal to [1,m].

T = ...
    84;


portfolio_month = ...
    dateshift( ...
        ( ...
            datetime(2010,1,1): ...
            calmonths(1): ...
            datetime(2016,12,1) ...
        )', ...
        'end', ...
        'month');


verifyEqual( ...
    testCase, ...
    numel(portfolio_month), ...
    T);


t = ...
    (1:T)';


market_excess = ...
    0.013 .* sin(0.27 .* t) + ...
    0.005 .* cos(0.11 .* t) + ...
    0.00003 .* (t - mean(t));


X = ...
    [ ...
        ones(T,1), ...
        market_excess];


raw_residual = ...
    0.004 .* sin(0.73 .* t) + ...
    0.002 .* cos(0.41 .* t);


residual = ...
    raw_residual - ...
    X * ...
    (X \ raw_residual);


alpha_true = ...
    0.0020;

beta_true = ...
    0.65;


portfolio_excess = ...
    alpha_true + ...
    beta_true .* market_excess + ...
    residual;


fit = ...
    estimate_capm_regression( ...
        portfolio_month, ...
        portfolio_excess, ...
        market_excess);


verifyEqual( ...
    testCase, ...
    fit.alpha_monthly, ...
    alpha_true, ...
    'AbsTol', ...
    1e-12);


verifyEqual( ...
    testCase, ...
    fit.beta, ...
    beta_true, ...
    'AbsTol', ...
    1e-12);

end

function testHacStandardErrorsKnownValues(testCase)
% Compare Newey-West standard errors with independently computed values.
%
% Reference values were computed outside MATLAB with the documented
% estimator: OLS, Bartlett weights 1 - l/(L+1), L = floor(4(T/100)^(2/9))
% = 2 for T = 24, no small-sample correction.

T = ...
    24;

portfolio_month = ...
    dateshift( ...
        ( ...
            datetime(2010,1,1): ...
            calmonths(1): ...
            datetime(2011,12,1) ...
        )', ...
        'end', ...
        'month');

t = ...
    (1:T)';

market_excess = ...
    0.010 .* sin(0.7 .* t) + ...
    0.004 .* cos(1.3 .* t);

residual = ...
    0.002 .* sin(0.35 .* t) + ...
    0.001 .* cos(0.9 .* t);

portfolio_excess = ...
    0.001 + ...
    0.9 .* market_excess + ...
    residual;

fit = ...
    estimate_capm_regression( ...
        portfolio_month, ...
        portfolio_excess, ...
        market_excess);

verifyEqual(testCase, fit.hac_lag, 2);

verifyEqual(testCase, fit.alpha_monthly, 0.001376101384511208, 'AbsTol', 1e-15);
verifyEqual(testCase, fit.beta, 0.89020018333657081, 'AbsTol', 1e-12);
verifyEqual(testCase, fit.alpha_hac_se, 0.00051543408107870749, 'AbsTol', 1e-15);
verifyEqual(testCase, fit.beta_hac_se, 0.066393134162034004, 'AbsTol', 1e-13);

end
